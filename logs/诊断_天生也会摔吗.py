"""诊断_天生也会摔吗.py —— 只靠本能"看红→走"，走长了会不会也摔？

为什么问这个：学出来的"听声音→站起来走"走到 1 米左右会翻倒（机身歪 ~180 度）。
要分清是**学出来的东西把步态搞坏了**，还是**这条天生的步态本来就只稳一小会儿**。

命令：python 诊断_天生也会摔吗.py
"""
from __future__ import annotations

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 身体_go2 as 身体

黑图 = np.zeros((主循环.图高, 主循环.图宽, 3), dtype=np.uint8)
红图 = 主循环.红图("中")


def 跑一程(名, 图, 拍数=150):
    本能.建网种子 = 20260914
    脑 = 主循环.脑(学=False, 说=False)
    身 = 身体.身体()
    身.摆成站姿(); 身.走(0.5, None)
    脑.亮[:] = False; 脑.上一拍[:] = False
    上一点 = 身.数据.qpos[:2].copy()
    路程 = 0.0
    print("\n[%s] 站着 + %s，走 %d 拍" % (名, "红" if 图.any() else "黑屏", 拍数))
    for k in range(1, 拍数 + 1):
        脑.一拍(图=图, 声=None, 身=身)
        身.步进(脑.肌肉发力())
        p = 身.数据.qpos[:2]
        路程 += float(np.hypot(p[0] - 上一点[0], p[1] - 上一点[1]))
        上一点 = p.copy()
        if k % 15 == 0:
            print("    %4d 机身高 %.3f 米  歪 %5.1f 度  路程 %.3f 米"
                  % (k, 身.机身高度(), 身.机身歪了(), 路程), flush=True)
    print("    → 走完：路程 %.3f 米，最后机身高 %.3f，歪 %.1f 度"
          % (路程, 身.机身高度(), 身.机身歪了()))


if __name__ == "__main__":
    跑一程("天生：看红", 红图)
    跑一程("对照：黑屏", 黑图)