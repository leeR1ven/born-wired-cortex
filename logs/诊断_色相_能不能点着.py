"""诊断_色相_能不能点着.py —— 没有经过任何漂移的脑，哪些色相能点着「走路」？

用途：R4 的收尾对照里「跳到 180° 走路 7/8」出乎意料。这个脚本分开两件事：
   · 是漂移（赫布学习）把 180° 变成能点着的，
   · 还是 180° 本来就能点着（「红」这个名字块对青色本来就有响应）。
这里跑的是**没漂移过的脑**，所以能回答。
"""
import numpy as np

import 本能工具_instincts as 本能
import 实验_颜色渐变 as 渐变
import 身体_go2 as 身体
import 主循环_完整的一拍 as 主循环

本能.建网种子 = 20260914
脑 = 主循环.脑(学=False, 说=False)
身 = 身体.身体()
身.摆成站姿()
身.走(0.5, None)
时刻 = 渐变.拿时刻(脑)

print("没有漂移过的脑（种子 20260914，学=关）：清空皮层后给 8 拍，看走路要不要点着")
print("  色相 | 走路点着/8  | rgb")
for h in (0, 24, 48, 72, 96, 120, 144, 168, 180, 204, 240, 270, 300, 330):
    脑.亮[:] = False
    脑.上一拍[:] = False
    统 = 渐变.跑几拍(脑, 身, 渐变.彩色块(h), 8, 时刻, 渐变.空统计())
    rgb = 渐变.彩色块(h)[500, 960]
    print("  %4d |    %d/8      | %s" % (h, 统["前进1.2"], tuple(int(x) for x in rgb)))