from __future__ import annotations

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 运动记忆区_motor_memory as 运动记忆
import 皮层连接_cortex_links as 皮层连接
import 身体_go2 as 身体

图高, 图宽 = 主循环.图高, 主循环.图宽
黑图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
红图 = 主循环.红图("中")
动作名 = "前进1.2"
教学拍数 = 80
考试拍数 = 120


def 分流(网, 亮):
    """这一拍每个细胞收到的兴奋电流，拆成「本能（固化）」和「学出来的」两份。"""
    边, 数 = 网._出边切片(np.nonzero(亮)[0])
    if 边.size == 0:
        return np.zeros(网.总数), np.zeros(网.总数)
    强 = 网._兴奋权[边].astype(np.float64)
    固 = 网._兴奋固化[边]
    目 = 网._兴奋目[边]
    本 = np.bincount(目[固], weights=强[固], minlength=网.总数)
    学 = np.bincount(目[~固], weights=强[~固], minlength=网.总数)
    return 本, 学


def main():
    名字 = 本能.读名字()
    脑 = 主循环.脑(学=True, 说=False)
    身 = 身体.身体()
    网 = 脑.网

    运记起 = 网.区起点["运动记忆"]
    走 = 运记起 + 运动记忆.时刻们(动作名)
    走起 = int(走[0])
    声 = np.asarray(本能.听觉例子["低频响"](), dtype=np.float64)

    区们 = ["视觉", "听觉", "前额叶", "运动", "运动记忆", "本体感觉", "平衡感觉", "机身状态"]
    段们 = {名: 网.区段(名) for 名 in 区们}

    print("=" * 108)
    print("出门前：兴奋连接 %d 根（其中固化的本能 %d 根，学出来的 %d 根）"
          % (网._兴奋键.size, int(网._兴奋固化.sum()), int((~网._兴奋固化).sum())))
    print("=" * 108)

    # ---------------- 教学 ----------------
    身.摆成站姿(); 身.走(0.5, None)
    脑.亮[:] = False; 脑.上一拍[:] = False
    print("\n[教学] 站着 + 红 + 声音 + 多巴胺，%d 拍" % 教学拍数)
    脑.多巴胺亮 = True
    for k in range(1, 教学拍数 + 1):
        脑.一拍(图=红图, 声=声, 身=身)
        身.步进(脑.肌肉发力())
    print("   教学完：兴奋连接 %d 根（学出来的 %d 根）"
          % (网._兴奋键.size, int((~网._兴奋固化).sum())))

    # ---------------- 考试 ----------------
    脑.多巴胺亮 = False
    脑.亮[:] = False; 脑.上一拍[:] = False
    身.摆成趴姿(); 身.走(0.3, None)
    中心 = np.zeros(网.总数, dtype=bool)
    for k in range(1, 考试拍数 + 1):
        脑.一拍(图=黑图, 声=声, 身=身)
        身.步进(脑.肌肉发力())
        if k == 1:
            中心 = 脑.亮.copy()
        if k % 20 == 0:
            本, 学 = 分流(网, 脑.亮)
            亮 = 脑.亮
            行 = ["    %4d 总%6d 前%5d 听%5d 走链%2d"
                  % (k, int(亮.sum()), int(亮[段们["前额叶"]].sum()),
                     int(亮[段们["听觉"]].sum()), int(亮[走].sum()))]
            for 名 in ("前额叶", "听觉", "视觉", "运动记忆"):
                段 = 段们[名]
                亮段 = 亮[段]
                if not 亮段.any():
                    行.append("%s 0" % 名)
                    continue
                里面 = np.nonzero(段)[0][亮段]
                靠学的 = int((学[里面] > 本[里面]).sum())
                行.append("%s:亮%d 里%5.2f 靠学%d" % (名, 里面.size, 学[里面].mean(), 靠学的))
            新亮 = int((亮 & ~中心).sum())
            行.append("比第一拍新亮 %d" % 新亮)
            print("  ".join(行), flush=True)

    print("\n考试完：兴奋连接 %d 根（学出来的 %d 根）—— 考试期间又长了 %d 根"
          % (网._兴奋键.size, int((~网._兴奋固化).sum()),
             网.统计.get("学出的兴奋直连", 0)))
    本, 学 = 分流(网, 脑.亮)
    亮 = 脑.亮
    print("最后这一拍：全脑收到本能电流 %.0f、学出来的电流 %.0f"
          % (本.sum(), 学.sum()))
    排 = np.argsort(-学)[:15]
    print("学出来的电流最大的 15 个细胞（看看是哪些区）：")
    for i in 排:
        名 = [n for n in 网.区名 if 网.区段(n)[i]][0]
        print("    #%d  %s  学%.3f  本能%.3f  亮=%s" % (i, 名, 学[i], 本[i], bool(亮[i])))


if __name__ == "__main__":
    main()