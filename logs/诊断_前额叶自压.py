# -*- coding: utf-8 -*-
"""诊断_前额叶自压.py —— 前额叶会不会越亮越多？动态整体抑制压得住吗？

问的是什么（大白话）：
  前额叶装着"一段神经元首尾接成环"以后，亮起来的细胞会赖着不走（这是用户要的：
  让一个想法不会立马消失）。可是 前额叶 → 返回线 → 视觉/听觉/运动 → 前额叶网
  → 前额叶 这条回路是正反馈，实测红屏看 200 拍就把整片前额叶点亮到 1360/1360，
  蓝屏也能被它推到点着走路，天生步态还会被带歪。

  这个脚本给前额叶加一个「动态整体抑制」（用户原话："保证前额叶始终只有少数
  神经元被激活……如果调参没法调到完美就使用动态抑制"）：
      前额叶每多亮一个细胞，就给前额叶**每个**细胞多压 前额叶自压 那么多电流；
      亮的细胞数不到 前额叶自压目标 时，一点不压（目标 0 = 一超过 0 个就开始压）。

  要看的是：红亮得多、蓝亮得少、黑基本不亮，而且亮住了不再往上涨。

命令：
  python 诊断_前额叶自压.py                        # 默认几档都试
  python 诊断_前额叶自压.py 20260914 0.004 200     # 指定 种子 自压 目标
"""
from __future__ import annotations

import gc
import sys

import numpy as np

import 本能工具_instincts as 本能
import 身体_go2 as 身体
import 运动记忆区_motor_memory as 运动记忆
import 主循环_完整的一拍 as 主循环

图高, 图宽 = 1080, 1920
前额叶细胞数 = 53200
条件 = [("红", (255, 0, 0)), ("蓝", (0, 0, 255)), ("绿", (0, 255, 0)), ("黑", (0, 0, 0))]


def 纯色(色):
    图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
    for k in range(3):
        图[:, :, k] = 色[k]
    return 图


def 跑一档(自压, 目标, 种子, 拍数=120, 学=False):
    """一档旋钮下，四种画面各跑一遍；返回 名 -> (每 20 拍的亮数, 走路点火拍数, 末了亮数)。"""
    本能.建网种子 = 种子
    脑 = 主循环.脑(学=学, 说=False)
    脑.网.前额叶自压 = 自压
    脑.网.前额叶自压目标 = 目标
    前段 = slice(脑.前起, 脑.前起 + 脑.前宽)
    时刻 = (脑.网.区起点["运动记忆"]
           + np.asarray(运动记忆.时刻们("前进1.2"), dtype=np.int64))
    出 = {}
    for 名, 色 in 条件:
        身 = 身体.身体()
        身.摆成站姿()
        身.走(0.5, None)
        脑.亮[:] = False
        脑.上一拍[:] = False
        图 = 纯色(色)
        采样, 点火 = [], 0
        for t in range(拍数):
            脑.一拍(图=图, 身=身)
            身.步进(脑.肌肉发力())
            if 脑.上一拍[时刻].any():
                点火 += 1
            if (t + 1) % 20 == 0:
                采样.append(int(脑.亮[前段].sum()))
        出[名] = (采样, 点火, int(脑.亮[前段].sum()))
    del 脑
    gc.collect()
    return 出


def main():
    种子 = 20260914
    档们 = [(0.0, 0.0), (0.001, 0.0), (0.004, 0.0), (0.01, 0.0), (0.004, 200.0)]
    if len(sys.argv) > 1 and sys.argv[1].strip():
        种子 = int(sys.argv[1])
    if len(sys.argv) > 2 and sys.argv[2].strip():
        目标0 = float(sys.argv[3]) if len(sys.argv) > 3 and sys.argv[3].strip() else 0.0
        档们 = [(float(sys.argv[2]), 目标0)]
    print("=" * 96)
    print("前额叶自压（动态整体抑制）：种子 %d，四种画面各 120 拍" % 种子)
    print("  读法：每 20 拍取一个数，看前额叶亮多少个细胞（前额叶一共 %d 个）" % 前额叶细胞数)
    print("=" * 96, flush=True)
    for 自压, 目标 in 档们:
        出 = 跑一档(自压, 目标, 种子)
        print("\n【前额叶自压 %.4g   目标 %.4g】" % (自压, 目标))
        for 名, _ in 条件:
            采样, 点火, 末 = 出[名]
            print("   %s：前额叶 %s（末了 %d）｜走路点火 %d/120"
                  % (名, " → ".join(str(x) for x in 采样), 末, 点火), flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())