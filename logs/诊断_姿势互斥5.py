# -*- coding: utf-8 -*-
"""诊断_姿势互斥5.py —— 站住之后再下"明确要坐"的令（第 60 拍才开始注入）。

  [1] 趴着不给东西 3 秒                  → 自己站起来
  [2] 站着看红 5 秒                      → 朝红走
  [3] 趴着起来站住，然后明确要坐(3.0)    → 站着压住，应该坐不下去
  [4] 趴着起来站住，然后明确要坐(7.0)    → 令够强，应该压不住、真坐下
  [5] 趴着，第 60 拍起明确要坐(3.0)      → 没站住（不在站姿），应该坐得下
另外顺带看一眼：站着的时候，身体那三个感觉区的名字哪些是亮的。
"""
from __future__ import annotations
import sys
import numpy as np

import 主循环_完整的一拍 as 主循环
import 本能工具_instincts as 本能
import 身体_go2 as 身体
import 运动记忆区_motor_memory as 记

标签 = sys.argv[1] if len(sys.argv) > 1 else "?"
帧秒 = 0.02
大脑 = 主循环.脑(学=True, 说=False)
网 = 大脑.网
名字 = 本能.读名字()
print("[%s] 本能 %s 根" % (标签, format(大脑.本能条数, ",")))

记起 = 网.区起点["运动记忆"]
听起 = 网.区起点["听觉"]
注入 = 听起 + 0
坐下入口 = 记起 + int(记.起手("坐下"))
时刻集 = {名: np.asarray(记.时刻们(名), dtype=np.int64) + 记起
          for 名 in ("坐下", "趴下去", "站姿", "站起来", "前进1.2")}
身体段 = {}
for 区 in ("本体感觉", "平衡感觉", "机身状态"):
    身体段[区] = {名: (np.asarray(idx, dtype=np.int64) + 网.区起点[区], 网.区起点[区])
                for 名, idx in 名字[区].items()}


def 跑(身, 秒, 图=None, 命令强度=0.0, 命令从第几拍=60, 报=True, 每=25):
    大脑.亮[:] = False
    网._待出.clear()
    起 = 身.数据.qpos[:2].copy()
    最高 = 身.机身高度()
    计数 = {名: 0 for 名 in 时刻集}
    最矮 = 9.9
    for k in range(int(秒 / 帧秒)):
        大脑.一拍(图=图, 身=身)
        if 命令强度 and k >= 命令从第几拍:
            大脑.亮[注入] = True
        身.步进(大脑.肌肉发力())
        最高 = max(最高, 身.机身高度())
        if k >= 命令从第几拍:
            最矮 = min(最矮, 身.机身高度())
        亮 = 大脑.亮
        for 名, 段 in 时刻集.items():
            if 亮[段].any():
                计数[名] += 1
        if 报 and k % 每 == 0:
            身体亮 = []
            for 区, 各 in 身体段.items():
                for 名, (段, 起i) in 各.items():
                    if 亮[段].any():
                        身体亮.append("%s:%s" % (区[:2], 名))
            print("   %-4s %4.1f秒 高%.3f 歪%3.0f 力%.2f~%.2f 跑[%s] 身体[%s]"
                  % (标签, k * 帧秒, 身.机身高度(), 身.机身歪了(),
                     float(np.min(大脑.肌肉发力())), float(np.max(大脑.肌肉发力())),
                     ",".join("%s%d" % (n, c) for n, c in 计数.items() if c),
                     ",".join(身体亮)))
    网._待出.clear()
    return dict(最高=最高, 末高=身.机身高度(), 最矮=最矮, 歪=身.机身歪了(),
                前进=float(身.数据.qpos[0] - 起[0]), 计数=计数,
                总拍=int(秒 / 帧秒), 命令从=命令从第几拍)


图 = np.zeros((1080, 1920, 3), dtype=np.uint8); 图[:, 640:1280, 0] = 255

身 = 身体.身体(); 身.摆成趴姿(); 身.走(0.5, None)
r1 = 跑(身, 3.0, 命令强度=0.0)
身 = 身体.身体(); 身.摆成站姿(); 身.走(0.5, None)
r2 = 跑(身, 5.0, 图=图, 命令强度=0.0)
身 = 身体.身体(); 身.摆成趴姿(); 身.走(0.5, None)
r3 = 跑(身, 6.0, 命令强度=3.0, 报=False)
身 = 身体.身体(); 身.摆成趴姿(); 身.走(0.5, None)
r4 = 跑(身, 6.0, 命令强度=7.0, 报=False)
身 = 身体.身体(); 身.摆成趴姿(); 身.走(0.5, None)
r5 = 跑(身, 6.0, 命令强度=3.0, 命令从第几拍=0, 报=False)

print()
def 行(t, r):
    n = r["总拍"] - r["命令从"]
    return ("[%s] %s 末高%.3f 歪%3.0f | 下命令后这些拍数里：坐下跑%d/%d 站姿跑%d 站起来跑%d 趴下去跑%d"
            % (标签, t, r["末高"], r["歪"], r["计数"]["坐下"], n,
               r["计数"]["站姿"], r["计数"]["站起来"], r["计数"]["趴下去"]))
print(行("[1] 趴着自己起来      ", r1))
print(行("[2] 站着看红(前进%.2f米)" % r2["前进"], r2))
print(行("[3] 起来站住→要坐3.0  ", r3))
print(行("[4] 起来站住→要坐7.0  ", r4))
print(行("[5] 一直趴着→要坐3.0  ", r5))
