# -*- coding: utf-8 -*-
"""诊断_摔是谁干的2.py —— 教过之后"听声音走"走久了到底摔在哪一步

现在的情况：5 个种子里 4 个能学会（出生 0/30 拍 → 考试 200/200 拍），
但考试走到第 42~101 拍开始慢慢歪倒。要分清是三件事里的哪一件：

  E0  还没教的时候：站着 + 红 + 同时响声音（学=False）200 拍
        → 天生的"看红→走"和天生的"响→原地踏步"混在一起，本身就稳不住？
  E1  教完之后考试：只放声音（学=True，和正式实验一样）
  E2  教完之后考试：只放声音（学=False —— 教完就不再学，看是不是"考试时还在学"把它学歪的）

命令：python 诊断_摔是谁干的2.py 20260915 20260918
"""
from __future__ import annotations

import sys

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 运动记忆区_motor_memory as 运动记忆
import 身体_go2 as 身体

图高, 图宽 = 主循环.图高, 主循环.图宽
黑图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
红图 = 主循环.红图("中")
动作名 = "前进1.2"
教学拍数 = 200
考试拍数 = 200
动作们 = ["前进1.2", "原地踏步", "站姿", "站起来", "坐下", "蹲"]


def 跑一个种子(种子, 不保留=False):
    本能.建网种子 = 种子
    脑 = 主循环.脑(学=True, 说=False, 前额叶不保留=不保留)
    身 = 身体.身体()
    网 = 脑.网
    运记起 = 网.区起点["运动记忆"]
    声 = np.asarray(本能.听觉例子["低频响"](), dtype=np.float64)
    时刻 = {a: 运记起 + np.asarray(运动记忆.时刻们(a), dtype=np.int64) for a in 动作们}

    def 走一段(拍数, 图, 声, 多巴胺=False, 要学=True):
        脑.要学 = 要学
        脑.多巴胺亮 = 多巴胺
        上一点 = 身.数据.qpos[:2].copy()
        路程 = 0.0
        翻在 = None
        在跑 = {a: 0 for a in 动作们}
        for k in range(1, 拍数 + 1):
            脑.一拍(图=图, 声=声, 身=身)
            身.步进(脑.肌肉发力())
            for a in 动作们:
                if 脑.亮[时刻[a]].any():
                    在跑[a] += 1
            p = 身.数据.qpos[:2]
            路程 += float(np.hypot(p[0] - 上一点[0], p[1] - 上一点[1]))
            上一点 = p.copy()
            if 翻在 is None and 身.机身歪了() > 75:
                翻在 = k
        return 路程, 翻在, 身.机身歪了(), 在跑

    def 摆好(姿):
        脑.多巴胺亮 = False
        脑.亮[:] = False
        脑.上一拍[:] = False
        if 姿 == "站":
            身.摆成站姿(); 身.走(0.5, None)
        else:
            身.摆成趴姿(); 身.走(0.3, None)

    # ---- E0：还没教，站着 + 红 + 声音（不学）----
    摆好("站")
    路0, 翻0, 歪0, 跑0 = 走一段(考试拍数, 红图, 声, 要学=False)

    # ---- 教学 ----
    摆好("站")
    走一段(教学拍数, 红图, 声, 多巴胺=True, 要学=True)

    # ---- E1：考试原样 ----
    摆好("趴")
    路1, 翻1, 歪1, 跑1 = 走一段(考试拍数, 黑图, 声, 要学=True)

    # ---- E2：考试但不再学 ----
    摆好("趴")
    路2, 翻2, 歪2, 跑2 = 走一段(考试拍数, 黑图, 声, 要学=False)

    print("### 种子 %d" % 种子, flush=True)
    for 名, 路, 翻, 歪, 跑 in (("E0 没教·站着看红+听声音(不学)", 路0, 翻0, 歪0, 跑0),
                              ("E1 教过·只放声音(学)", 路1, 翻1, 歪1, 跑1),
                              ("E2 教过·只放声音(不再学)", 路2, 翻2, 歪2, 跑2)):
        print("  %-30s 路程 %6.3f 米  %s  %s"
              % (名, 路, ("第 %d 拍翻" % 翻) if 翻 else "没翻(歪 %.0f 度)" % 歪,
                 " ".join("%s%d" % (a, n) for a, n in 跑.items() if n)), flush=True)
    print("", flush=True)


if __name__ == "__main__":
    # --无环 = 前额叶每拍重算（论文 R1~R8 用的那一档，见 主循环_完整的一拍.py 的 前额叶不保留）
    不保留 = "--无环" in sys.argv
    种子们 = [int(a) for a in sys.argv[1:] if not a.startswith("-")] or [20260915, 20260918]
    print("前额叶：%s" % ("每拍重算（不保留）" if 不保留 else "照常（带环、会累加）"), flush=True)
    for s in 种子们:
        跑一个种子(s, 不保留)