# -*- coding: utf-8 -*-
"""实验_本能表整体偏移.py —— 先天连线是"模糊的、粗略的"，那它整体偏掉一格还能用吗？

★ 用户的理论（2026-09-15）：
  "整体本能连接是模糊但有大致方向的，就像把一个有精确记忆的人的大脑连接模糊化。"

★ 这个实验比"随机改接"干净得多：把本能表里**所有按格子方向写的那些源**
  （细_列c / 痕迹_细_列c / 变化_细_列c / 接力k_细_列c）整体**平移 Δ 列**，
  别的一个字都不动。这模拟的是"继承下来的那张方位图整体偏了一点"。

★ 预测（很清楚，好证伪）：
  · Δ=0：眼睛把小球停在画面正中（原来那个"没有拉扯"的死角，第 7/8 列 ≈ 0 度）
  · Δ=+1：死角跟着挪到第 8/9 列 → 眼睛会**一直多转约 6.25 度**
  · Δ 越大，停的位置越偏，但**只要还追得住，行为就依然是有序的**
  也就是：先天连线粗略 → 行为**有序但有系统偏差**；不是"要么对要么全崩"。

命令：
    python 实验_本能表整体偏移.py            # Δ = -2 / -1 / 0 / +1 / +2 / +3
    python 实验_本能表整体偏移.py 0 1 2       # 只跑这几个
"""
from __future__ import annotations

import re
import sys

import numpy as np

import 本能工具_instincts as 本能
import 视觉前处理_visual_preprocess as 视觉
import 运动输出区_motor_output as 运动
import 主循环_完整的一拍 as 主循环
import 运动记忆区_motor_memory as 运动记忆
import 实验_眼睛跟随 as 跟随

真读本能表 = 本能.读本能表
列数 = int(视觉.大像素列数)
列宽 = 100.0 / 列数
帧秒 = 跟随.帧秒
偏移们 = [-2, -1, 0, 1, 2, 3]
球半径 = 0.05
球方位角 = 25.0
秒数 = 4.0
样本 = re.compile(r"^(.*细_列)(\d+)$")


def 平移(名, Δ):
    m = 样本.match(名)
    if not m:
        return None
    c = int(m.group(2)) + Δ
    if c < 0 or c >= 列数:
        return None
    return "%s%d" % (m.group(1), c)


def 偏移表(表, Δ, 名字):
    出 = []
    for 源块, 目标块, 权重, 固化, 行号 in 表:
        if ":" in 源块 and Δ:
            区, 名 = 源块.split(":", 1)
            区, 名 = 区.strip(), 名.strip()
            新 = 平移(名, Δ)
            # ★ 平移之后那个名字得真的存在 —— 第 7/8 列天生就没有名字（留的死角），
            #   挪过去就成空的了。这种就不动这一条（实测踩过这个坑）。
            if 新 is not None and 新 in 名字.get(区, {}):
                源块 = "%s:%s" % (区, 新)
        出.append((源块, 目标块, 权重, 固化, 行号))
    return 出


def 试(脑, 角=球方位角, 半径=球半径, 拍数=None):
    """摆一个不动的小球，让眼睛自己走，返回（末了眼角、末了球在视角里在哪）。"""
    w = 跟随.架好世界(球方位角=角, 球半径=半径)
    脑.亮[:] = False
    脑.上一拍[:] = False
    运起, 运宽 = 脑.运起, 脑.运宽
    for _ in range(int(round((拍数 or 秒数) / 帧秒))):
        脑.一拍(图=w.看())
        力 = 运动.解码眼球发力(脑.亮[运起:运起 + 运宽])
        w.眼肌发力 = 力
        w.走眼睛(帧秒)
        w.走物体(帧秒)
    方, 仰 = w.眼里在哪(0)
    return w.眼球水平, 方


def 探红(脑, 拍数=8):
    运记起 = 脑.网.区起点["运动记忆"]
    走 = 运记起 + np.asarray(运动记忆.时刻们("前进1.2"), dtype=np.int64)
    脑.亮[:] = False
    脑.上一拍[:] = False
    中 = 0
    for _ in range(拍数):
        脑.一拍(图=主循环.红图("中"))
        if 脑.上一拍[走].any():
            中 += 1
    return 中


def 跑一个(Δ):
    本能.读本能表 = 真读本能表
    表 = 真读本能表()
    名字 = 本能.读名字()
    新表 = 偏移表(表, Δ, 名字)
    改了几条 = sum(1 for a, b in zip(表, 新表) if a[0] != b[0])
    本能.读本能表 = (lambda 表=新表: 表)
    脑 = 主循环.脑(学=False, 说=False)
    走红 = 探红(脑)
    末眼, 球在 = 试(脑)
    return {"Δ": Δ, "改了几条": 改了几条, "走红": 走红, "末眼": 末眼, "球在": 球在}


def main():
    要跑 = [int(a) for a in sys.argv[1:]] or 偏移们
    print("=" * 92)
    print("把本能表里所有「细_列c」那一类的源整体平移 Δ 列（别的都不动）")
    print("小球固定摆在 %+.1f 度不动，看眼睛最后把它停在画面哪个位置" % 球方位角)
    print("=" * 92)
    结果 = []
    for Δ in 要跑:
        r = 跑一个(Δ)
        结果.append(r)
        print("【Δ = %+d 列（%.1f 度）】改了 %d 条；红→走路 %d/8；眼睛末了 %+.1f 度，球停在视角 %+.1f 度"
              % (Δ, Δ * 列宽, r["改了几条"], r["走红"], r["末眼"], r["球在"]), flush=True)
    print("\n" + "=" * 92)
    print("【总表】")
    print("%8s | %10s | %10s | %14s | %16s" % ("整体偏移", "改了条数", "红→走路", "眼睛末了朝哪", "球停在视角哪"))
    print("-" * 92)
    for r in 结果:
        print("%7d 列 | %10d | %10s | %+13.1f | %+15.1f"
              % (r["Δ"], r["改了几条"], "%d/8" % r["走红"], r["末眼"], r["球在"]))
    print()
    print("（Δ=0 那一行是基准：眼睛把球停在 0 度附近；Δ 越大停得越偏 = 行为还在、但带着系统偏差）")
    return 结果


if __name__ == "__main__":
    结果 = main()