# -*- coding: utf-8 -*-
"""实验_渐变_正式协议.py —— 颜色渐变习惯化的正式协议（论文用，多步长 × 开关学习 × 多种子）

★ 要证明的一件事（论文柱子三）：
  一个**没有误差信号、没有老师**的局部赫布规则，能让"眼前是红的所以往前走"这件事
  跟着颜色**慢慢漂移**过去 —— 就像每天看见同一个人，他慢慢变老，你还是认得出，
  而不是某一天突然认不出。

★ 协议（每一趟都一样）：
  · 色相从 0°（纯红）起，暖身 40 拍
  · 每挪一格 步长 度：先让它带着这个颜色走 25 拍（这是学习段），
    然后把动作停住、用新颜色**重新点一次**（8 拍），点着 >=6 拍就算"还认得出"
  · 认得出就往下挪一格；认不出就在原地最多再看 200 拍；再认不出就停在这儿
  · 指标 = **停在哪一度**（能漂多远还认得出）
  · 收尾对照：黑屏 / 回 0° / 跳到 120° / 跳到 180° / 再回停住那一格

★ 为什么要"停住再重新点一次"，而不是"看它还在不在走"：
  走路这个动作一旦点着，运动记忆区那条时间线会自己一拍一拍转下去（19.10.4 量过）。
  "它还在走"只能说明惯性还在，不能说明它认得现在这个颜色。所以必须先清空皮层，
  用当前颜色重新点一次。

★ 三个自变量：
  步长  3 / 6 / 12 度      —— 步子越小越"潜移默化"；预测：步子越大越早断
  学习  开 / 关           —— 关掉的是同一颗脑子（同一套本能），只把赫布学习关掉
  种子  建网种子 20260914 / 20260915 / 20260916 —— 随机的背景连接换一批

命令：
    python 实验_渐变_正式协议.py                # 3 个步长 × 学/不学 × 3 个种子
    python 实验_渐变_正式协议.py 3 1            # 只跑步长 3、只跑 1 个种子（先看看）
"""
from __future__ import annotations

import sys
import time

import numpy as np

import 本能工具_instincts as 本能
import 实验_颜色渐变 as 渐变
import 身体_go2 as 身体
import 主循环_完整的一拍 as 主循环

步长们 = [3, 6, 12]
种子们 = [20260914, 20260915, 20260916]
帧秒 = 主循环.帧秒


def 跑一趟(步长, 学, 种子, 终点=180, 每步预算=200, 学习段=25, 探头=8, 总拍上限=6000):
    本能.建网种子 = 种子
    脑 = 主循环.脑(学=学, 说=False)
    身 = 身体.身体()
    身.摆成站姿()
    身.走(0.5, None)
    时刻 = 渐变.拿时刻(脑)
    渐变.跑几拍(脑, 身, 渐变.彩色块(0), 40, 时刻, 渐变.空统计())
    总拍 = 40
    h = 0
    路上 = [0]
    while h < 终点 and 总拍 < 总拍上限:
        格拍 = 0
        点着 = 0
        while 格拍 < 每步预算 and 总拍 < 总拍上限:
            渐变.跑几拍(脑, 身, 渐变.彩色块(h), 学习段, 时刻, 渐变.空统计())
            格拍 += 学习段
            总拍 += 学习段
            脑.亮[:] = False
            脑.上一拍[:] = False
            统 = 渐变.跑几拍(脑, 身, 渐变.彩色块(min(h + 步长, 终点)), 探头, 时刻,
                          渐变.空统计())
            点着 = 统["前进1.2"]
            if 点着 >= 6:
                break
        if 点着 < 6:
            break
        h = min(h + 步长, 终点)
        路上.append(h)
    黑 = np.zeros((渐变.图高, 渐变.图宽, 3), dtype=np.uint8)
    对照 = []
    for 名, 图 in (("停在 %d°" % h, 渐变.彩色块(h)),
                  ("黑屏", 黑),
                  ("纯红 0°", 渐变.彩色块(0)),
                  ("跳到 120°", 渐变.彩色块(120)),
                  ("跳到 180°", 渐变.彩色块(180)),
                  ("再回 %d°" % h, 渐变.彩色块(h))):
        脑.亮[:] = False
        脑.上一拍[:] = False
        统 = 渐变.跑几拍(脑, 身, 图, 探头, 时刻, 渐变.空统计())
        对照.append((名, 统["前进1.2"], 探头))
    return {"步长": 步长, "学": 学, "种子": 种子, "停在哪": h, "总拍": 总拍,
            "格数": len(路上) - 1, "对照": 对照}


def main():
    步长要 = 步长们
    种子要 = 种子们
    if len(sys.argv) > 1:
        步长要 = [int(a) for a in sys.argv[1].split(",")]
    if len(sys.argv) > 2:
        要 = sys.argv[2]
        if "," in 要:
            种子要 = [int(a) for a in 要.split(",")]
        else:
            种子要 = 种子们[:int(要)]
    全部 = []
    print("=" * 100)
    print("颜色渐变正式协议：色相 0° 起，能重新点着就往下挪，点不着就停（终点 180°）")
    print("步长 %s；种子 %s" % (步长要, 种子要))
    print("=" * 100)
    for 步长 in 步长要:
        for 学 in (True, False):
            for 种子 in 种子要:
                起 = time.time()
                r = 跑一趟(步长, 学, 种子)
                全部.append(r)
                print("步长 %2d°，%s，种子 %d → 停在哪 %3d°（挪了 %d 格，共 %d 拍，%.0f 秒）"
                      % (步长, "开学习" if 学 else "关学习", 种子, r["停在哪"],
                         r["格数"], r["总拍"], time.time() - 起), flush=True)
    print("\n" + "=" * 100)
    print("【总表】每 步长/学习/种子 一趟，看它认到哪一度")
    print("%6s | %6s | %8s | %10s | %10s" % ("步长", "学习", "种子", "停在哪(度)", "花了多少拍"))
    print("-" * 100)
    for r in 全部:
        print("%6d | %6s | %8d | %10d | %10d"
              % (r["步长"], "开" if r["学"] else "关", r["种子"], r["停在哪"], r["总拍"]))
    print()
    print("【按步长汇总】")
    for 步长 in 步长要:
        for 学 in (True, False):
            组 = [r["停在哪"] for r in 全部 if r["步长"] == 步长 and r["学"] == 学]
            if 组:
                print("   步长 %2d°、%s：平均停在哪 %.0f 度（各趟 %s）"
                      % (步长, "开学习" if 学 else "关学习", sum(组) / len(组),
                         "、".join(str(a) for a in 组)))
    print()
    print("【收尾对照（每一趟都做，这里列出第一趟的）】")
    for 名, 点着, 探头 in 全部[0]["对照"]:
        print("   %-14s 走路 %d/%d" % (名, 点着, 探头))
    print()
    print("【收尾对照（全部趟，一趟一行）】")
    for r in 全部:
        小 = "；".join("%s 走路 %d/%d" % (名, 点着, 探头) for 名, 点着, 探头 in r["对照"])
        print("步长 %2d°、%s、种子 %d、停在哪 %3d°：%s"
              % (r["步长"], "开学习" if r["学"] else "关学习", r["种子"], r["停在哪"], 小))
    return 全部


if __name__ == "__main__":
    全部 = main()