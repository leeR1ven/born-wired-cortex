# -*- coding: utf-8 -*-
"""动作库_go2.py —— 把 Go2 能做出来的动作，一个一个试出来、登记下来。

★ 为什么要有这个文件

  模型不可能"只有一个动作"。但"所有可能的动作"也不存在 ——
  12 个关节、每个关节连续角度，组合是无穷多。能做的是一件实在的事：
  把**有名字、稳定、可用**的动作一个个试出来，登记成库。
  库里的每个动作 = 12 块肌肉的发力（静态姿势）或发力随时间的一串值（动作序列）。

★ Go2 的动作空间有多大

  它只有 12 个腿关节（4 条腿 × 髋/大腿/小腿），没有脖子、没有尾巴、没有脊椎。
  所以它的全部动作，都是"四条腿怎么摆、怎么动"：
      静态：站、趴、坐、蹲、抬腿、伸懒腰、前腿撑高、后腿收……
      时序：趴下、站起来、原地踏步、小跑、前后重心换……

★ 每个动作都要过物理这一关

  试出来不算数，得在真物理里跑一遍：站得住吗？会不会倒？脚踩在地上吗？
  过不了关的就不进库（见 验收）。

★ 每个动作怎么进模型

  库里的动作不直接连到肌肉上，而是：
    ① 「标定」把每个动作的发力翻译成运动皮层上的一片细胞（皮层名字.json）；
    ② 本能表里写「前额叶:某动作 → 运动:某动作」；
    ③ 装 把这条本能展开成一根一根的连接。
  也就是说：动作是"想起来的"，不是代码放出来的。
"""
from __future__ import annotations

import numpy as np

import 身体_go2 as 身体

肌肉数 = 身体.肌肉数
站 = 身体.站姿发力.copy()
趴 = 身体.趴姿发力.copy()


def _发力(覆盖: dict) -> np.ndarray:
    """按名字改几块肌肉，其余保持站姿。覆盖的键可以写 '左前' 这种前缀，一次改一条腿。"""
    a = 站.copy()
    for 名, 值 in 覆盖.items():
        if 名 in 身体.肌肉名:
            a[身体.肌肉名.index(名)] = 值
        else:                      # 前缀匹配：'左前' = 左前髋/左前大腿/左前小腿 一起改
            组 = [i for i, n in enumerate(身体.肌肉名) if n.startswith(名)]
            if not 组:
                raise KeyError("没有这块肌肉：" + 名)
            for i in 组:
                a[i] = 值[身体.肌肉名[i][len(名)]] if isinstance(值, dict) else 值
    return np.clip(a, 0.0, 1.0)


# ================= 静态姿势：试出来的能站住的"摆法" =================
静态 = {
    "站姿":    站.copy(),
    "趴姿":    趴.copy(),

    # 坐：后腿收到身下、屁股落地，前腿照样撑着（狗坐下那样）
    "坐":      _发力({"左后大腿": 0.30, "右后大腿": 0.30, "左后小腿": 0.00, "右后小腿": 0.00}),

    # 蹲：四条腿都折一点，身体压低但还站着
    "蹲":      _发力({"左前大腿": 0.42, "右前大腿": 0.42, "左前小腿": 0.35, "右前小腿": 0.35,
                       "左后大腿": 0.42, "右后大腿": 0.42, "左后小腿": 0.35, "右后小腿": 0.35}),

    # 站高：四条腿都伸直一些，身体抬起来（够高处的东西）
    # 站高：小腿一伸直，身体就抬起来了（实测 0.256 → 0.319 米，还稳）
    "站高":    _发力({"左前小腿": 0.72, "右前小腿": 0.72, "左后小腿": 0.72, "右后小腿": 0.72}),

    # 抬左前腿（像要握手）
    "抬左前腿": _发力({"左前大腿": 0.20, "左前小腿": 0.15}),
    "抬右前腿": _发力({"右前大腿": 0.20, "右前小腿": 0.15}),

    # 前腿撑起、后腿收着 —— 狗伸懒腰的姿势
    "伸懒腰":  _发力({"左前大腿": 0.66, "右前大腿": 0.66, "左前小腿": 0.62, "右前小腿": 0.62,
                       "左后大腿": 0.34, "右后大腿": 0.34, "左后小腿": 0.08, "右后小腿": 0.08}),

    # 重心前移 / 后移（准备起跳 / 准备坐下）
    "重心前":  _发力({"左前大腿": 0.56, "右前大腿": 0.56, "左后大腿": 0.44, "右后大腿": 0.44}),
    "重心后":  _发力({"左前大腿": 0.44, "右前大腿": 0.44, "左后大腿": 0.56, "右后大腿": 0.56}),
}


# ================= 动作序列：发力随时间的一串值 =================
def _淡入(起, 止, 秒=1.2, 帧率=50):
    """从姿势 起 平滑变到 止。"""
    帧 = max(1, int(秒 * 帧率))
    for k in range(帧):
        u = (k + 1) / 帧
        u = u * u * (3 - 2 * u)          # 平滑起停，不然会猛地一窜
        yield 起 + (止 - 起) * u


def _原地踏步(秒=3.0, 帧率=50, 频率=1.6, 摆幅大腿=0.14, 摆幅小腿=0.20):
    """四足小跑（trot）：对角两条腿一组，一组抬、一组蹬，交替。
    这只是"原地"的节奏 —— 真要走起来还得靠更复杂的控制（见 README 里的话）。"""
    for k in range(int(秒 * 帧率)):
        t = k / 帧率
        发 = 站.copy()
        相位 = {"左前": 0.0, "右前": 0.5, "左后": 0.5, "右后": 0.0}   # 对角同相
        for 腿, p in 相位.items():
            s = np.sin(2 * np.pi * 频率 * t + 2 * np.pi * p)
            发[身体.肌肉名.index(腿 + "大腿")] = 0.5 + 摆幅大腿 * s
            发[身体.肌肉名.index(腿 + "小腿")] = 0.5 + 摆幅小腿 * s
        yield np.clip(发, 0.0, 1.0)


序列 = {
    "站起来": lambda: _淡入(趴, 站, 秒=1.2),
    "趴下去": lambda: _淡入(站, 趴, 秒=1.2),
    "坐下":   lambda: _淡入(站, 静态["坐"], 秒=1.0),
    "原地踏步": _原地踏步,
}


# ================= 验收：能在真物理里跑住吗 =================
def 验收(动作, 秒=None, 起手="站姿", 说=False):
    """把动作在身体上跑一遍，返回（能不能用, 读数）。"""
    身 = 身体.身体()
    身.摆成站姿() if 起手 == "站姿" else 身.摆成趴姿()
    身.走(0.5, None)                     # 先自己稳住半秒
    历史 = []
    if hasattr(动作, "__next__"):        # 生成器 = 动作序列
        for 发 in 动作:
            身.步进(发)
            历史.append((身.机身高度(), 身.机身歪了(), float(np.nanmin(身.足高()))))
    else:
        for _ in range(int((秒 or 2.0) * 30)):
            身.步进(动作)
            历史.append((身.机身高度(), 身.机身歪了(), float(身.触地().sum())))
    高 = np.array([h for h, _, _ in 历史])
    歪 = np.array([w for _, w, _ in 历史])
    脚 = np.array([f for _, _, f in 历史])
    踩地 = int(脚[-1])
    好 = bool(高[-1] > 0.08 and 歪.max() < 60.0)
    if 说:
        print("   %-8s 机身 %.3f→%.3f 米  最大歪 %.0f 度  最低脚 %.3f 米  %s" %
              ("", 高[0], 高[-1], 歪.max(), 脚.min(), "可用" if 好 else "倒/趴了"))
    return 好, dict(起点高=float(高[0]), 终点高=float(高[-1]),
                    最大歪=float(歪.max()), 踩地=踩地)


if __name__ == "__main__":
    print("静态姿势验收：")
    for 名, 发 in 静态.items():
        好, 读 = 验收(发, 秒=2.0)
        print("  %-6s 终点机身 %.3f 米  最大歪 %4.0f 度  踩地 %d 只脚  %s" %
              (名, 读["终点高"], 读["最大歪"], 读["踩地"], "可用" if 好 else "不行"))
    print("\n动作序列验收：")
    for 名, 造 in 序列.items():
        好, 读 = 验收(造(), 起手=("趴姿" if 名 == "站起来" else "站姿"))
        print("  %-6s 起点 %.3f → 终点 %.3f 米  最大歪 %4.0f 度  %s" %
              (名, 读["起点高"], 读["终点高"], 读["最大歪"], "可用" if 好 else "不行"))
    print("\n共 %d 个静态动作、%d 个动作序列" % (len(静态), len(序列)))
