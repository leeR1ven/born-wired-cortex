# -*- coding: utf-8 -*-
"""实验_专注_无关就互压.py

一个"正在想的事"（前额叶一片细胞 P）和一个"外界信号激活的细胞"（视觉一片 A）
如果**从来没有一起亮过**，互相压多少？总是**一起亮**又压多少？

只读引擎里已有的那条规则（model/皮层连接_cortex_links.py 的 学习()）：
  · 两拍里最近都亮过（相关；痕迹 0.9 / 门限 0.05，约 28 拍）-> 之间抑制变弱、去抑制变强
  · 一个亮、另一个最近没亮过（无关）                     -> 之间抑制变强（每拍 +0.0005，封顶 0.6）
不额外写任何规则。读三样（都是"这条网自己算出来的"）：
  (1) P -> A 抑制边的权重：出生 -> 训练后（到顶比例、归零比例）
  (2) 想的细胞压在外界信号细胞上的抑制电流（有想 - 无想，前向算出来的整数电流）
  (3) 想的细胞给外界信号细胞的净驱动变化 = 兴奋差 - 抑制差

用法：cd model; python 实验_专注_无关就互压.py [--真实规模] [--种子 20260914,20260915] [--轮数 8]
"""
from __future__ import annotations

import gc
import json
import sys
import time

import numpy as np

from 皮层连接_cortex_links import 皮层连接网

小球宽 = {"视觉": 2000, "听觉": 500, "前额叶": 2000, "运动": 200}
真实宽 = {"视觉": 23040, "听觉": 30000, "前额叶": 57040, "运动": 4000}

想细胞数 = 60        # 前额叶里"正在想的事"那一小片
信号细胞数 = 200     # 外界信号点亮的视觉细胞
亮拍 = 30            # 每一段亮多久
间隔 = 40            # 两段之间歇多久（痕迹约 28 拍淡没，所以这时算"没一起亮过"）
测拍 = 20


def 取组(网):
    p起, p宽 = 网.区起点["前额叶"], 网.区宽["前额叶"]
    v起, v宽 = 网.区起点["视觉"], 网.区宽["视觉"]
    想 = np.arange(p起, p起 + min(想细胞数, p宽), dtype=np.int64)
    信号 = np.arange(v起, v起 + min(信号细胞数, v宽), dtype=np.int64)
    return 想, 信号


def 段(网, 上, 钉住, 步数):
    for _ in range(步数):
        这 = 网.步进(上)
        if 钉住.size:
            这[钉住] = True
        网.学习(上, 这)
        上 = 这
    return 上


def 读电流(网, 想, 信号):
    """想的细胞压在外界信号细胞上的抑制电流 / 给它们的净驱动变化。"""
    无 = np.zeros(网.总数, dtype=bool)
    无[信号] = True
    有 = 无.copy()
    有[想] = True
    抑差 = float(网._抑制电流(有)[信号].sum() - 网._抑制电流(无)[信号].sum())
    兴差 = float(网._兴奋电流(有)[信号].sum() - 网._兴奋电流(无)[信号].sum())
    抑无 = float(网._抑制电流(无)[信号].sum())
    抑有 = float(网._抑制电流(有)[信号].sum())
    净无 = float(网._兴奋电流(无)[信号].sum()) - 抑无
    净有 = float(网._兴奋电流(有)[信号].sum()) - 抑有
    return dict(抑制差=抑差, 兴奋差=兴差, 净变化=净有 - 净无,
                净无想=净无, 净有想=净有, 抑制无想=抑无, 抑制有想=抑有)


def 一条(宽, seed, 轮数, 无关):
    网 = 皮层连接网(宽, seed=seed)
    想, 信号 = 取组(网)
    遮 = np.isin(网._抑制源, 想) & np.isin(网._抑制目, 信号)
    边数 = int(遮.sum())
    出生 = float(网._抑制权[遮].mean()) if 边数 else float("nan")
    出生顶 = float((网._抑制权[遮] >= 0.6 - 1e-6).mean()) if 边数 else float("nan")
    上 = np.zeros(网.总数, dtype=bool)
    空 = np.empty(0, dtype=np.int64)
    for _ in range(轮数):
        if 无关:
            上 = 段(网, 上, 想, 亮拍)
            上 = 段(网, 上, 空, 间隔)
            上 = 段(网, 上, 信号, 亮拍)
            上 = 段(网, 上, 空, 间隔)
        else:
            上 = 段(网, 上, np.union1d(想, 信号), 亮拍)
            上 = 段(网, 上, 空, 间隔)
    出 = dict(边数=边数, 出生抑制=出生, 出生到顶=出生顶,
              训练后抑制=float(网._抑制权[遮].mean()),
              训练后到顶=float((网._抑制权[遮] >= 0.6 - 1e-6).mean()),
              训练后归零=float((网._抑制权[遮] <= 1e-9).mean()),
              去抑变强的细胞=int((网.去抑权重 > 0).sum()))
    出.update(读电流(网, 想, 信号))
    # 附带看一眼：信号钉住时视觉区除输入外还亮几个
    上 = np.zeros(网.总数, dtype=bool)
    for t in range(测拍):
        这 = 网.步进(上); 这[信号] = True; 上 = 这
    v起, v宽 = 网.区起点["视觉"], 网.区宽["视觉"]
    d = np.nonzero(上[v起:v起 + v宽])[0]
    出["信号外还亮"] = int(d.size - 信号.size)
    del 网
    gc.collect()
    return 出


def 基线(宽, seed):
    网 = 皮层连接网(宽, seed=seed)
    想, 信号 = 取组(网)
    遮 = np.isin(网._抑制源, 想) & np.isin(网._抑制目, 信号)
    出 = dict(边数=int(遮.sum()),
              出生抑制=float(网._抑制权[遮].mean()),
              出生到顶=float((网._抑制权[遮] >= 0.6 - 1e-6).mean()))
    出.update(读电流(网, 想, 信号))
    del 网
    gc.collect()
    return 出


def main():
    真实 = "--真实规模" in sys.argv
    宽 = 真实宽 if 真实 else 小球宽
    轮数 = 8
    种子们 = [20260914, 20260915]
    for i, a in enumerate(sys.argv):
        if a == "--轮数" and i + 1 < len(sys.argv):
            轮数 = int(sys.argv[i + 1])
        if a == "--种子" and i + 1 < len(sys.argv):
            种子们 = [int(x) for x in sys.argv[i + 1].split(",")]
    行 = []
    def 记(s):
        print(s, flush=True)
        行.append(s)
    记("=" * 100)
    记("实验_专注_无关就互压：想的细胞 与 外界信号细胞，无关 vs 相关")
    记(f"规模 {'真实' if 真实 else '小球'} {宽}")
    记(f"想的细胞 {想细胞数} 个（前额叶）   外界信号细胞 {信号细胞数} 个（视觉）   轮数 {轮数}"
       f"（每轮：想{亮拍}拍 -> 歇{间隔}拍 -> 信号{亮拍}拍 -> 歇{间隔}拍）")
    记("=" * 100)
    结果 = {}
    for seed in 种子们:
        t0 = time.perf_counter()
        b = 基线(宽, seed)
        无 = 一条(宽, seed, 轮数, True)
        关 = 一条(宽, seed, 轮数, False)
        记(f"\n种子 {seed}   用 {time.perf_counter() - t0:.0f} 秒    P->A 抑制边 {b['边数']} 条")
        记(f"  出生(不训练)  权重 {b['出生抑制']:.4f}(到顶 {100 * b['出生到顶']:.1f}%)"
           f"   压制电流 {b['抑制差']:.1f}   净驱动变化 {b['净变化']:+.1f}")
        记(f"  无关臂        权重 {无['出生抑制']:.4f} -> {无['训练后抑制']:.4f}"
           f"(到顶 {100 * 无['训练后到顶']:.1f}%  归零 {100 * 无['训练后归零']:.1f}%)"
           f"   压制电流 {无['抑制差']:.1f}   净驱动变化 {无['净变化']:+.1f}"
           f"   去抑细胞 {无['去抑变强的细胞']}")
        记(f"  相关臂        权重 {关['出生抑制']:.4f} -> {关['训练后抑制']:.4f}"
           f"(到顶 {100 * 关['训练后到顶']:.1f}%  归零 {100 * 关['训练后归零']:.1f}%)"
           f"   压制电流 {关['抑制差']:.1f}   净驱动变化 {关['净变化']:+.1f}"
           f"   去抑细胞 {关['去抑变强的细胞']}")
        if 无['抑制差'] > 0:
            记(f"  -> 无关臂的压制电流是相关臂的 {无['抑制差'] / max(关['抑制差'], 1e-9):.1f} 倍"
               f"（权重 {无['训练后抑制'] / max(关['训练后抑制'], 1e-9):.1f} 倍）；"
               f"信号钉住时视觉区除输入外还亮：出生 {b.get('信号外还亮', -1)} / 无关 {无['信号外还亮']} / 相关 {关['信号外还亮']}")
        结果[str(seed)] = dict(基线=b, 无关=无, 相关=关)
    记("")
    with open("日志_专注_无关就互压.log", "w", encoding="utf-8") as f:
        f.write("\n".join(行) + "\n")
    with open("日志_专注_无关就互压.json", "w", encoding="utf-8") as f:
        json.dump(结果, f, ensure_ascii=False, indent=1)


if __name__ == "__main__":
    main()