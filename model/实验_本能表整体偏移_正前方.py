"""实验_本能表整体偏移_正前方.py —— 把球摆到正前方（0 度）再跑一遍整体偏移。

★ 为什么要加这一份。
  原来那份把小球摆在 +25 度，Δ 往正的方向走得好好的（一格对一格），可是 Δ 往负的
  方向走时，眼睛要停的位置超过了眼球 30 度的机械极限 —— 于是 Δ=-1、-2 都被卡在 +30 度，
  看不出偏移。把球挪到正前方以后，Δ = -3 ~ +3 全都在眼球能转到的范围里，
  一整条曲线就都看得见了。

命令：python 实验_本能表整体偏移_正前方.py
"""
from __future__ import annotations

import sys

import 实验_本能表整体偏移 as 偏

真试 = 偏.试


def 试(脑, 角=0.0, 半径=0.05, 拍数=None):
    return 真试(脑, 角=角, 半径=半径, 拍数=拍数)


偏.试 = 试
偏.球方位角 = 0.0
偏.球半径 = 0.05
偏.偏移们 = [-3, -2, -1, 0, 1, 2, 3]
sys.argv = sys.argv[:1]
偏.main()