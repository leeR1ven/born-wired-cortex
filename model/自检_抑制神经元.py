# -*- coding: utf-8 -*-
"""自检_抑制神经元.py —— 证明「压住」是靠**抑制神经元**干的，不是靠负权重。

拿"前进0.8"这个动作，只看右边那条前小腿（0~1 的发力）。
用的身体情况挑「往左歪得厉害」（它在本能表里没有规则，干净）：

  甲：什么都不加，计划自己走
  乙：再加一条「至少8档」——常态本能：源 → 目标，直接点亮
  丙：再加一条「不超过4档」——抑制本能：源 → **抑制神经元** → 目标，把它压住
  丁：两条一起，看谁赢

命令：python 自检_抑制神经元.py
"""
from __future__ import annotations

import numpy as np

import 运动输出区_motor_output as 运动
import 本能工具_instincts as 本能

情况 = "往左歪得厉害"
看哪块 = "右前小腿"
肌肉号 = 运动.肌肉名.index(看哪块)


def main():
    print("=" * 74)
    名字 = 本能.读名字()
    网, _ = 本能.装(说=False)
    print("网建好：皮层 %s 个神经元（含「抑制」%d 个）\n"
          % (format(网.总数, ","), 网.区宽["抑制"]))
    前起, 本起, 运起 = 网.区起点["运动记忆"], 网.区起点["平衡感觉"], 网.区起点["运动"]
    前块 = 前起 + np.array(名字["运动记忆"]["前进0.8"], dtype=int)
    本块 = 本起 + np.array(名字["平衡感觉"][情况], dtype=int)

    def 跑(加成=None, 减成=None, 前=8):
        抑制起 = 网.区起点["抑制"]
        if 减成 is not None:
            中继 = 抑制起 + (0 if 加成 is None else 1)
            区源, 源 = 本能.解析(名字, "平衡感觉:" + 情况)
            区目, 目 = 本能.解析(名字, "运动:%s不超过%d档" % (看哪块, 减成))
            网.写入连接(源 + 网.区起点[区源], np.full(源.size, 中继, dtype=np.int64),
                     本能.抑制力度 / 源.size, True)
            网.写入抑制连接(np.array([中继]), 目 + 运起, 本能.抑制权重, True)
        if 加成 is not None:
            中继2 = 抑制起 + 5
            区源, 源 = 本能.解析(名字, "平衡感觉:" + 情况)
            区目, 目 = 本能.解析(名字, "运动:%s至少%d档" % (看哪块, 加成))
            网.写入连接(np.repeat(源 + 网.区起点[区源], 目.size),
                     np.tile(目 + 运起, 源.size), 本能.抑制力度 / 源.size, True)
        亮 = np.zeros(网.总数, dtype=bool)
        亮[前块] = True
        亮[本块] = True
        出力 = []
        for _ in range(前):
            出 = 网.步进(亮)
            发力 = 运动.解码发力(出[运起:运起 + 运动.运动区宽度])
            出力.append(float(发力[肌肉号]))
            亮 = 出
            亮[本块] = True
        return 出力

    def 报(标签, 力):
        print("   %-34s 每一拍 %s" % (标签, " ".join("%.1f" % v for v in 力)))

    print("（%s 这块肌肉在皮层上有 10 个档位细胞，亮几个就是几档）\n" % 看哪块)
    报("甲 什么都不加（计划自己走）", 跑())
    print("\n   甲：让一个抑制神经元去压「不超过4档」")
    报("丙 加「不超过4档」", 跑(减成=4))
    print("\n   乙：让连接直接把「至少8档」点亮")
    报("乙 加「至少8档」", 跑(加成=8))
    print("\n   丁：两条一起（抑制神经元 + 直接点亮）")
    报("丁 至少8档 且 不超过4档", 跑(加成=8, 减成=4))

    print("\n结论：")
    print("   · 「点亮」= 源直接连到目标（常态本能）；「压住」= 源连到一个抑制神经元，")
    print("     抑制神经元再去压目标。皮层里没有「负的连接」这回事。")
    print("   · 抑制神经元的力气（%.1f × 抑制强度）大于目标那几档细胞收到的兴奋，" % 本能.抑制权重)
    print("     所以它们被压到阈值 1.0 以下、点不着 —— 这就是「不超过N档」。")


if __name__ == "__main__":
    main()