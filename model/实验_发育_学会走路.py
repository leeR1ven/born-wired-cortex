# -*- coding: utf-8 -*-
"""实验_发育_学会走路.py —— 出生时不会的行为，靠"活着"自己长出来

★ 这是论文自己承认缺的那一个实验（4.3 与 4.6 第 1 条：没有任何实验跟着一个脑
  在它活着的过程中长出新东西）。

★ 要证的事：一个**出生时跟走路毫无关系**的刺激，在"一边听它一边走路"地活过一段
  时间之后，光凭它自己就能把走路点起来。

★ 为什么选声音、为什么干净：
    本能表（本能表.txt）里听觉一共只有三条规则 ——
        听觉:响 -> 运动记忆:原地踏步   3.00
        听觉:停 -> 运动记忆:站姿       1.50
        听觉:停 -> 运动记忆:前进1.2   -4.50（压住走路）
    没有任何一条是"某个声音 -> 走路"。
    而且 运动记忆 区在出生时**不接收随机兴奋连接**（皮层连接_cortex_links.py 的
    不接收随机兴奋的区）。也就是说，声音在出生时根本**没有一条路**能走到
    运动记忆区。要看它能不能自己长出来，这是最干净的底子。

★ 三个对照（同一批种子、同一个身体、同样的时长、同样的探测）：
    配对     —— 生活段：一边听声音一边走路（红在眼前）
    只听不走 —— 生活段：听同样久的声音，但眼前是黑的，它不走
    只走不听 —— 生活段：走同样久，但不放声音
  三者的探测完全一样：清空皮层 -> 黑屏 + 只放这个声音 -> 数走路那串时刻亮了几拍。

命令： python 实验_发育_学会走路.py [种子,种子,...] [生活秒数]
"""
from __future__ import annotations

import sys
import time

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 身体_go2 as 身体
import 运动记忆区_motor_memory as 运动记忆

图高, 图宽 = 主循环.图高, 主循环.图宽
帧秒 = 主循环.帧秒
看点 = ["前进1.2", "左转1.5", "右转0.75", "站起来", "原地踏步", "站姿"]
路 = "前进1.2"
黑图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)


def 红图():
    图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
    图[:, 图宽 // 3: 2 * 图宽 // 3, 0] = 255
    return 图


def 拿声音(名="低频响"):
    声道 = 本能.听觉例子[名]()
    return np.asarray(声道, dtype=np.float64).copy()


def 拿时刻(脑):
    运记起 = 脑.网.区起点["运动记忆"]
    return {a: 运记起 + np.asarray(运动记忆.时刻们(a), dtype=np.int64) for a in 看点}


def 跑几拍(脑, 身, 图, 声, 拍数, 时刻):
    统 = {a: 0 for a in 看点}
    统["拍"] = 0
    for _ in range(拍数):
        脑.一拍(图=图, 声=声, 身=身)
        身.步进(脑.肌肉发力())
        for a in 看点:
            if 脑.上一拍[时刻[a]].any():
                统[a] += 1
        统["拍"] += 1
    return 统


def 探一次(脑, 身, 时刻, 声, 拍数=8):
    """清空皮层，只给这个声音（黑屏），看它能不能**重新点着**走路。

    为什么必须先清空：走路这串时刻一旦点着，会自己一拍接一拍转下去（R8）。
    「还在走」说明不了是它认出了这个声音。要问"这个声音能不能点着它"，
    就得先把它停住，再用这个声音重新点一次。
    """
    脑.亮[:] = False
    脑.上一拍[:] = False
    return 跑几拍(脑, 身, 黑图, 声, 拍数, 时刻)


def 探测(脑, 身, 时刻, 声, 次数=5, 拍数=8):
    出 = [探一次(脑, 身, 时刻, 声, 拍数) for _ in range(次数)]
    前进 = [o[路] for o in 出]
    return {"前进": 前进, "点着": int(sum(a >= 6 for a in 前进)), "次数": 次数}


def 活一段(脑, 身, 时刻, 图, 声, 拍数, 曲线, 探间隔=0, 曲线声=None):
    """生活段：一边给 图/声 一边活 拍数 拍；探间隔>0 时每隔那么多拍探一次（记进 曲线）"""
    for k in range(拍数):
        脑.一拍(图=图, 声=声, 身=身)
        身.步进(脑.肌肉发力())
        if 探间隔 and (k + 1) % 探间隔 == 0:
            曲线.append(探测(脑, 身, 时刻, 曲线声, 次数=3)["前进"])


def 跑一趟(种子, 条件, 生活拍数, 曲线点数=20, 说=True):
    本能.建网种子 = 种子
    脑 = 主循环.脑(学=True, 说=False)
    身 = 身体.身体()
    身.摆成站姿()
    身.走(0.5, None)
    时刻 = 拿时刻(脑)
    声 = 拿声音("低频响")
    # 先把身子稳住、让走路点着，再开始记
    跑几拍(脑, 身, 红图(), None, 40, 时刻)
    # [0] 出生时：只给声音，能不能点着走路？
    出生 = 探测(脑, 身, 时刻, 声, 次数=5)
    # [1] 生活段
    生活图 = 红图() if 条件 in ("配对", "只走不听") else 黑图
    生活声 = 声 if 条件 in ("配对", "只听不走") else None
    曲线 = []
    探间隔 = max(1, 生活拍数 // 曲线点数) if 曲线点数 else 0
    起 = time.time()
    活一段(脑, 身, 时刻, 生活图, 生活声, 生活拍数, 曲线, 探间隔=探间隔, 曲线声=声)
    用时 = time.time() - 起
    # [2] 生活之后：同样的探测
    之后 = 探测(脑, 身, 时刻, 声, 次数=5)
    # 顺便量一下：这个声音现在能不能把**站姿/原地踏步**点着（说明学的是"走路"这一件）
    其它 = {}
    for a in ("原地踏步",):
        脑.亮[:] = False; 脑.上一拍[:] = False
        统 = 跑几拍(脑, 身, 黑图, 声, 8, 时刻)
        其它[a] = 统[a]
    if 说:
        print("   [%s] 种子 %d：出生时 %d/5 点着 %s -> 生活后 %d/5 点着 %s"
              "（生活段用时 %.0f 秒；出生时那 5 次分别 %s，之后分别 %s）"
              % (条件, 种子, 出生["点着"], 出生["前进"], 之后["点着"], 之后["前进"],
                 用时, 出生["前进"], 之后["前进"]), flush=True)
    return {"种子": 种子, "条件": 条件, "出生": 出生, "之后": 之后,
            "曲线": 曲线, "其它": 其它, "生活段秒": 生活拍数 * 帧秒}


def main():
    种子们 = [20260914]
    生活秒 = 40.0
    参 = [a for a in sys.argv[1:] if a.strip()]
    if 参:
        种子们 = [int(a) for a in 参[0].split(",")]
    if len(参) > 1:
        生活秒 = float(参[1])
    生活拍数 = int(round(生活秒 / 帧秒))
    print("=" * 104)
    print("发育实验：出生时没有的行为，能不能靠生活自己长出来")
    print("  声音 = 低频响（本能表里没有任何一条规则碰过它）")
    print("  生活段 = %.0f 秒（%d 拍）；生活之后测：黑屏 + 只放这个声音，清空皮层重新点 8 拍"
          % (生活秒, 生活拍数))
    print("  种子 = %s；每组对照 %d 个" % (种子们, 3))
    print("=" * 104)
    出 = []
    for 条件 in ("配对", "只听不走", "只走不听"):
        for s in 种子们:
            r = 跑一趟(s, 条件, 生活拍数)
            出.append(r)
    print()
    print("=" * 104)
    print("【总表】黑屏 + 只放这个声音：清空皮层后重新点 8 拍，走路那串时刻亮了几拍（>=6 算点着）")
    print("  %-10s %-14s %-14s %s" % ("条件", "出生时 5 次", "生活后 5 次", "生活后曲线（每 %d 拍探一次 3 遍取中位）"
                                     % max(1, 生活拍数 // 20)))
    print("-" * 104)
    for 条件 in ("配对", "只听不走", "只走不听"):
        组 = [r for r in 出 if r["条件"] == 条件]
        生 = [r["出生"]["点着"] for r in 组]
        后 = [r["之后"]["点着"] for r in 组]
        print("  %-10s %-14s %-14s" % (条件, "%d/5（%d 个种子）" % (sum(生), len(生)),
                                      "%d/5（%d 个种子）" % (sum(后), len(后))))
    print()
    for r in 出:
        p = r["曲线"]
        print("  [%s] 种子 %d 生活段曲线（每个探测点 3 次的点数）:" % (r["条件"], r["种子"]))
        for i in range(0, len(p), 4):
            print("     %s" % "  ".join("%d/3" % sum(1 for a in g if a >= 6) for g in p[i:i + 4]))
    return 出


if __name__ == "__main__":
    出 = main()