# -*- coding: utf-8 -*-
"""闭环_身体go2.py —— 大脑皮层驱动真身体（宇树 Go2）。

★ 这条闭环在做什么

  皮层亮 → 运动皮层（肌群神经元）→ 12 块肌肉发力 → 真物理里的 Go2 动起来。
  中间没有任何"做动作"的代码。狗站起来，是因为皮层上"想一下站起来"那一片亮了，
  沿着一出生就写好的本能连接，这串动作就在皮层里一拍一拍自己走下去，
  每一拍再把运动皮层里对应那些肌肉细胞点着。

★ 两种"想"

  · 一直想（1 拍的姿势）：运动记忆区那一拍持续亮着 —— 相当于"保持这个姿势"。
  · 想一下（多拍的动作）：只点亮头一拍，之后**不再给任何输入** ——
    这串动作自己在皮层里转下去（循环的会一直走，不循环的放完就停）。
    这就是"节奏"本身：不是代码在打拍子，是神经元你点我、我点你转出来的。

★ 这次要看到的事

  1. 一直想"趴姿"     → 狗趴下去（机身 0.26 → 0.10 米）
  2. 想一下"站起来"   → 狗自己站起来（0.10 → 0.25 米）
  3. 一直想"坐"、"蹲"、"抬左前腿" 等 → 摆出对应姿势
  4. 想一下"前进0.4"     → 步态自己转圈，狗往前走
  5. 什么都不想       → 肌肉放松，狗瘫掉（说明动作确实是皮层下的令）
"""
from __future__ import annotations

import numpy as np

import 身体_go2 as 身体
import 运动输出区_motor_output as 运动
import 本能工具_instincts as 本能
import 感觉区_共同 as 感觉

帧秒 = 1.0 / 50.0


def 灌身体感觉(亮, 网, 身):
    """把身体的当前状态编码成皮层激活，写进这一拍的"输入"里。

    视觉/听觉是外界感觉，本体感觉是身体自己的感觉 —— 对这个架构来说都是
    "从外往内"的信号，一起灌进皮层。写了"什么情况做什么"的本能以后，
    这一段就是模型自己感觉到"我趴着 / 我要往前倒"的那一步。
    """
    感觉.灌感觉(亮, 网, 身)          # 三个身体感觉区一起灌
    return 亮


def 建好一切(说=True):
    名字 = 本能.读名字()
    网, 条 = 本能.装(说=说)
    return 网, 名字, 网.区起点


def 一段(网, 名字, 身体对象, 想什么=None, 秒=3.0, 方式="一直", 说=True, 每几拍报=10):
    """跑一段时间。

    想什么 = 名字（运动记忆区里的动作名）或 None
    方式   = "一直"（持续点亮，姿势用）/"一下"（只点一拍，多拍动作用）
    """
    前 = 网.区起点["运动记忆"]
    运起 = 网.区起点["运动"]
    亮 = np.zeros(网.总数, dtype=bool)
    if 想什么:
        亮[前 + np.array(名字["运动记忆"][想什么], dtype=int)] = True
    行 = []
    起点 = 身体对象.数据.qpos[:2].copy()
    for k in range(int(秒 / 帧秒)):
        灌身体感觉(亮, 网, 身体对象)
        出 = 网.步进(亮)
        发力 = 运动.解码发力(出[运起:运起 + 运动.运动区宽度])
        身体对象.步进(发力)
        if 方式 == "一直" and 想什么:            # 一直想：这一片每拍都亮着
            出[前 + np.array(名字["运动记忆"][想什么], dtype=int)] = True
        亮 = 出                                  # 想一下：只给过头一拍，之后全靠皮层自己
        if k % 每几拍报 == 0:
            p = 身体对象.数据.qpos
            行.append((k * 帧秒, 身体对象.机身高度(), 身体对象.机身歪了(),
                       float(发力.max() - 发力.min()), p[0] - 起点[0], p[1] - 起点[1]))
            if 说:
                print("   %4.1f 秒  机身 %.3f 米  歪 %3.0f 度  发力跨度 %.2f  走了 (%.2f, %.2f)"
                      % 行[-1])
    return 行


def main():
    print("=" * 72)
    网, 名字, 起点 = 建好一切()
    身 = 身体.身体()

    print("\n[1] 一直想「趴姿」—— 狗趴下去")
    身.摆成站姿()
    一段(网, 名字, 身, "趴姿", 1.2)
    print("    -> 机身 %.3f 米" % 身.机身高度())

    print("\n[2] 想一下「站起来」—— 只点一拍，之后不给任何输入，看它自己站起来")
    一段(网, 名字, 身, "站起来", 2.4, 方式="一下")
    print("    -> 机身 %.3f 米（站姿约 0.26 米）" % 身.机身高度())

    print("\n[3] 一直想「坐」—— 坐下")
    一段(网, 名字, 身, "坐", 1.0)
    print("    -> 机身 %.3f 米" % 身.机身高度())

    print("\n[4] 想一下「站起来」，再想一下「前进0.4」—— 只各点一拍")
    一段(网, 名字, 身, "站起来", 2.0, 方式="一下")
    起 = 身.数据.qpos[:2].copy()
    一段(网, 名字, 身, "前进0.4", 4.0, 方式="一下")
    print("    -> 机身 %.3f 米，向前走了 %.2f 米"
          % (身.机身高度(), 身.数据.qpos[0] - 起[0]))

    print("\n[5] 什么都不想 —— 皮层不再给运动指令")
    一段(网, 名字, 身, None, 1.5)
    print("    -> 机身 %.3f 米  歪 %.0f 度" % (身.机身高度(), 身.机身歪了()))
    print("\n每段都对上，就说明动作确实是皮层下的令，中间没有一行『做动作』的代码。")


def 主流程(帧数=1):
    """接线自检用的短版闭环：建网 → 装本能 → 想一下 → 身体真的动。"""
    网, 名字, _ = 建好一切(说=False)
    身 = 身体.身体()
    一段(网, 名字, 身, "站姿", 0.2, 说=False)
    一段(网, 名字, 身, "前进0.4", 0.2, 方式="一下", 说=False)
    return 身


if __name__ == "__main__":
    main()