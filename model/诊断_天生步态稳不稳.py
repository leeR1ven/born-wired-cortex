"""诊断_天生步态稳不稳.py —— 还没学任何东西，光靠天生本能走，走久了会不会自己歪倒？

为什么问：发育实验里 5 个种子有 4 个在考试走到第 42~101 拍时歪倒。
上一步的对照（诊断_摔是谁干的2.py）已经说明：**不是学出来的连接干的** ——
同一个脑，还没教（E0）站在那里看红、听着声音就已经在第 76 拍歪倒了。
所以问题在天生的步态本身。这一步把范围再缩小：

  A  站着 + 红 + 无声，前额叶**照常**（带环，会累加）      200 拍
  B  站着 + 红 + 无声，前额叶**每拍重算**（等于加环之前）    200 拍
  C  站着 + 红 + 有声，前额叶照常                           200 拍

  A 稳、B 也稳 → 本能步态本来就稳，是别的（声音）在捣乱
  A 歪、B 不歪 → 是**前额叶会累加**这件事把天生步态带歪的
  A 歪、B 也歪 → 这条天生步态在某些种子上本来就只稳一小会儿

命令：python 诊断_天生步态稳不稳.py 20260914 20260915
"""
from __future__ import annotations

import sys

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 运动记忆区_motor_memory as 运动记忆
import 身体_go2 as 身体

图高, 图宽 = 主循环.图高, 主循环.图宽
黑图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
红图 = 主循环.红图("中")
拍数 = 200
动作们 = ["前进1.2", "原地踏步", "站姿", "站起来", "坐下", "蹲"]


def 跑一个种子(种子):
    本能.建网种子 = 种子
    声 = np.asarray(本能.听觉例子["低频响"](), dtype=np.float64)

    def 一幕(名, 图, 声用, 保留):
        脑 = 主循环.脑(学=False, 说=False, 前额叶不保留=(not 保留))
        身 = 身体.身体()
        运记起 = 脑.网.区起点["运动记忆"]
        时刻 = {a: 运记起 + np.asarray(运动记忆.时刻们(a), dtype=np.int64) for a in 动作们}
        身.摆成站姿(); 身.走(0.5, None)
        脑.亮[:] = False; 脑.上一拍[:] = False
        上一点 = 身.数据.qpos[:2].copy()
        路程 = 0.0
        翻在 = None
        在跑 = {a: 0 for a in 动作们}
        前额叶 = []
        for k in range(1, 拍数 + 1):
            脑.一拍(图=图, 声=声用, 身=身)
            身.步进(脑.肌肉发力())
            for a in 动作们:
                if 脑.亮[时刻[a]].any():
                    在跑[a] += 1
            前额叶.append(int(脑.亮[脑.段["前额叶"]].sum()))
            p = 身.数据.qpos[:2]
            路程 += float(np.hypot(p[0] - 上一点[0], p[1] - 上一点[1]))
            上一点 = p.copy()
            if 翻在 is None and 身.机身歪了() > 75:
                翻在 = k
        print("  %-26s 路程 %6.3f 米  %s  前额叶亮 %d→%d 个  %s"
              % (名, 路程, ("第 %d 拍翻" % 翻在) if 翻在 else "没翻(歪 %.0f 度)" % 身.机身歪了(),
                 前额叶[0], max(前额叶),
                 " ".join("%s%d" % (a, n) for a, n in 在跑.items() if n)), flush=True)

    print("### 种子 %d" % 种子, flush=True)
    一幕("A 红/无声·前额叶照常", 红图, None, True)
    一幕("B 红/无声·前额叶每拍重算", 红图, None, False)
    一幕("C 红/有声·前额叶照常", 红图, 声, True)
    print("", flush=True)


if __name__ == "__main__":
    种子们 = [int(a) for a in sys.argv[1:]] or [20260914, 20260915]
    for s in 种子们:
        跑一个种子(s)