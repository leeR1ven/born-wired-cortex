# -*- coding: utf-8 -*-
"""实验_本能模糊化.py —— 本能连接只要"模糊的大致方向"就够用，还是必须精确？

★ 用户的理论（2026-09-15）：
  "本能连接既是很多有直系血缘长辈的大脑连接模糊化，也是有直系血缘长辈的总体混合记忆……"
  "整体本能连接是模糊但有大致方向的，就像把一个有精确记忆的人的大脑连接模糊化。"
  他同时要求："我希望不是假设而是有明确证据或者实验来证明。"

★ 这个实验就是去量它。把本能表里每条规则的**源**换掉，两种换法：
    · 随机乱接：换到同一个区里随便哪个名字（= 接线错了，方向也没了）
    · 挪一格  ：如果是「细_列7」这种有方向的，就换成隔壁那一列（= 模糊了，但大致方向还在）
  然后看三条完全不同的通路还剩多少：
    ① 正前方一片红 → 走路      （视觉 0.55 + 前额叶 0.80 两半凑够才走）
    ② 听到一声响   → 原地踏步   （听觉 → 动作）
    ③ 小球横着飘   → 眼睛跟住   （第 1 层 16 列 → 眼肌，一共 322 条）

★ 预测：
  如果"模糊但方向对"比"随机接错"耐得多 → 支持用户的说法；
  如果两者差不多 → 本能必须精确才行。两个结果都照实报。

★ 为什么这三个探针不用物理身体：这三条路要的电流都来自感觉区 + 前额叶
  （见 本能表.txt 零、那一节），身体那三个区在这几条上不出力。身体那一套（站起来、
  走路）另有 闭环_前提.py。

命令：
    python 实验_本能模糊化.py                       # 随机乱接，p = 0/10/20/35/50/75/100
    python 实验_本能模糊化.py 挪一格                # 相邻模糊，同样这些 p
    python 实验_本能模糊化.py 挪一格 0 50 100       # 只跑这几个
"""
from __future__ import annotations

import re
import sys

import numpy as np

import 本能工具_instincts as 本能
import 运动记忆区_motor_memory as 运动记忆
import 主循环_完整的一拍 as 主循环
import 实验_眼睛跟随 as 跟随

真读本能表 = 本能.读本能表
随机数 = np.random.default_rng(20260915)
百分比们 = [0, 10, 20, 35, 50, 75, 100]
挪表 = re.compile(r"^(.*_?细_[列])(\d+)$")


def 挪名字(区, 名, rng):
    """把名字换成"隔壁那一个"：细_列7 → 细_列6 或 细_列8（痕迹_/变化_/接力k_ 也一样）。"""
    m = 挪表.match(名)
    if m:
        c = int(m.group(2))
        新 = c + (1 if rng.random() < 0.5 else -1)
        新 = max(0, min(int(视觉列数()) - 1, 新))
        if 新 != c:
            候选 = "%s%d" % (m.group(1), 新)
            if 候选 in 本能.读名字().get(区, {}):
                return 候选
    if 名 == "细_高行":
        return "细_低行"
    if 名 == "细_低行":
        return "细_高行"
    return None


def 视觉列数():
    import 视觉前处理_visual_preprocess as 视觉
    return int(视觉.大像素列数)


def 模糊表(表, 名字, p, rng, 方式):
    出 = []
    for 源块, 目标块, 权重, 固化, 行号 in 表:
        换 = None
        if ":" in 源块 and rng.random() < p:
            区, 名 = 源块.split(":", 1)
            区, 名 = 区.strip(), 名.strip()
            if 方式 == "挪一格":
                换 = 挪名字(区, 名, rng)
            if 换 is None:
                候选 = [n for n in 名字.get(区, {}) if n != 名 and len(名字[区][n])]
                if 候选:
                    换 = 候选[int(rng.integers(len(候选)))]
        出.append(("%s:%s" % (源块.split(":", 1)[0].strip(), 换) if 换 else 源块,
                  目标块, 权重, 固化, 行号))
    return 出


def 探一遍(脑, 拍数=8):
    """同一个脑子上两条通路各点一次，返回"这 拍数 拍里点着了几拍"。"""
    运记起 = 脑.网.区起点["运动记忆"]
    走 = 运记起 + np.asarray(运动记忆.时刻们("前进1.2"), dtype=np.int64)
    踏 = 运记起 + np.asarray(运动记忆.时刻们("原地踏步"), dtype=np.int64)
    红 = 主循环.红图("中")
    谱 = 本能.听觉例子["响"]()
    出 = {}
    for 名, 图, 声, 时刻 in (("走红", 红, None, 走), ("听响", None, 谱, 踏)):
        脑.亮[:] = False
        脑.上一拍[:] = False
        中 = 0
        for _ in range(拍数):
            脑.一拍(图=图, 声=声)
            if 脑.上一拍[时刻].any():
                中 += 1
        出[名] = 中
    return 出, 拍数


def 两半还在吗(新表):
    """走路那条路由两半凑起来（视觉 0.55 + 前额叶 0.80），看这次模糊后还剩几半。"""
    n = 0
    for 源块, 目标块, 权重, 固化, 行号 in 新表:
        if 目标块.strip() == "运动记忆:前进1.2" and 源块.strip() in ("视觉:中有红", "前额叶:看着红"):
            n += 1
    return n


def 跑一个(p百分, 方式):
    p = p百分 / 100.0
    名字 = 本能.读名字()
    表 = 真读本能表()
    新表 = 模糊表(表, 名字, p, 随机数, 方式)
    改了几条 = sum(1 for a, b in zip(表, 新表) if a[0] != b[0])
    本能.读本能表 = (lambda 表=新表: 表)
    脑 = 主循环.脑(学=False, 说=False)
    出, 拍数 = 探一遍(脑)
    记 = 跟随.跑("模糊化 %d%%" % p百分, 球方位角=-25.0, 球半径=0.05, 球横速=0.5,
                秒数=5.0, 说=False)
    偏 = [max(abs(r[1]), abs(r[2])) for r in 记 if abs(r[1]) <= 45 and abs(r[2]) <= 35]
    平均 = sum(偏) / len(偏) if 偏 else float("nan")
    return {"p": p百分, "改了几条": 改了几条, "条数": len(表),
            "走红": 出["走红"], "听响": 出["听响"], "拍数": 拍数,
            "平均偏": 平均, "末眼": 记[-1][3], "两半": 两半还在吗(新表)}


def main():
    参 = sys.argv[1:]
    方式 = "随机乱接"
    if 参 and 参[0] in ("随机", "随机乱接", "挪一格"):
        方式 = "随机乱接" if 参[0].startswith("随机") else "挪一格"
        参 = 参[1:]
    要跑 = [int(a) for a in 参] or 百分比们
    print("=" * 96)
    print("把本能表里的接线按比例换掉（方式：%s），再量三条通路：走路 / 踏步 / 眼睛跟住" % 方式)
    print("=" * 96)
    结果 = []
    for p in 要跑:
        r = 跑一个(p, 方式)
        结果.append(r)
        print("【%s %3d%%】本能表 %d 条，换掉 %d 条；走路两半还剩 %d/2"
              % (方式, p, r["条数"], r["改了几条"], r["两半"]))
        print("        ① 红 → 走路 %d/%d   ② 响 → 踏步 %d/%d   ③ 小球 → 眼睛 平均偏离 %.1f 度（末了眼 %+.1f）"
              % (r["走红"], r["拍数"], r["听响"], r["拍数"], r["平均偏"], r["末眼"]), flush=True)
    print("\n" + "=" * 96)
    print("【总表 · %s】" % 方式)
    print("%8s | %10s | %12s | %12s | %12s" % ("换掉比例", "换掉条数", "红→走路", "响→踏步", "眼睛平均偏离"))
    print("-" * 96)
    for r in 结果:
        print("%7d%% | %10s | %12s | %12s | %11.1f 度"
              % (r["p"], "%d/%d" % (r["改了几条"], r["条数"]),
                 "%d/%d" % (r["走红"], r["拍数"]), "%d/%d" % (r["听响"], r["拍数"]), r["平均偏"]))
    print()
    print("（红→走路、响→踏步满分 %d 拍；眼睛偏离越小越好：接对了 5.6 度，完全不接 15.3 度）"
          % 结果[0]["拍数"] if 结果 else "")
    return 结果


if __name__ == "__main__":
    结果 = main()