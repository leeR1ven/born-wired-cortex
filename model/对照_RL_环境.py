# -*- coding: utf-8 -*-
"""对照_RL_环境.py —— 给"跟别人比"用的两个任务：同一个身体、同一件事、同一个判据。

为什么要有这个（用户 2026-09-16："同一个身体、同一个任务，强化学习要多少样本"）：

  我们这个系统做下面这两件事是 **0 步训练** —— 本能表是人手写的（论文 R1）。
  强化学习要做同样的事，只能自己试出来。所以这个文件把"同样的事"写成环境的
  复位 / 观测 / 奖励 / 判据，**判据照搬论文里我们自己那一套**，不然比较没有意义。

两个任务：

  站起来（= 论文 R1 的 righting）
      复位：趴姿（`摆成趴姿`），什么都不给。一集 150 拍（3 秒）。
      判据：末了机身高度 >= 0.25 米、机身歪 < 30 度
            （论文：3/3 个种子站住，末了 0.261 米）

  看见红（= 论文 R1 的 visually guided approach）
      复位：站姿，正前方 1.2 米有一个红色的东西（红块是画在眼前的，不随身体动，
            所以"看见红"和"朝红走过去"是同一个方向）。
      一集 200 拍（4 秒）。
      判据：朝目标走了 >= 1.0 米、而且末了还站着（歪 < 40 度）
            （论文：5/5 个种子走过去，中位 1.73 米）

观测：尽量给我们自己那套的**同一份信息**，不让强化学习吃亏。
  站起来：12 个关节相对站姿的偏差 + 12 个角速度 + 机身朝向(3) + 高度(1) + 脚高(4) = 32 维
  看见红：上面这些 + 目标在身体坐标里的方向(2) + 距离(1) = 35 维

动作：12 块肌肉的发力 0~1（和大脑给身体的一模一样，一个字节都没换）
"""
from __future__ import annotations

import numpy as np

import 身体_go2 as 身体

每帧秒 = 身体.每帧秒
肌肉数 = 身体.肌肉数
# ★ 为什么势函数的差**不乘折扣**（2026-09-16 踩的坑，第三个）：
#   教科书上写的是 r = γΦ(下一拍) − Φ(这一拍)（Ng et al., 1999）。那是对**无限折扣**目标的
#   写法；我们是一集 150~200 拍的**有限**回合，γ=0.99 会额外带进来一个每拍 −(1−γ)Φ 的项，
#   于是"分越高的状态、每拍罚得越多"，而有限回合里这个罚是**数得出来的**：
#   实测站着不动（Φ=1.5）一整集 −3.18，塌下去（Φ 更低）反而 −2.53 —— 奖励在教它放下。
#   直接用 Φ(下一拍) − Φ(这一拍)：加起来正好是 Φ(末了) − Φ(开头)，和"离做成还有多远"完全一致。


class 任务:
    """一个任务 = 一个身体 + 一套复位/观测/奖励/判据。"""

    def __init__(self, 名="站起来"):
        if 名 not in ("站起来", "看见红"):
            raise SystemExit("任务只有两个：站起来 / 看见红。收到的是「%s」" % 名)
        self.名 = 名
        self.身 = 身体.身体()
        if 名 == "站起来":
            self.拍数上限 = 150
        else:
            self.拍数上限 = 200
        self.目标距离 = 1.2                 # 正前方 1.2 米
        self.目标 = np.array([self.目标距离, 0.0])   # 世界坐标 (x, y)
        self.拍 = 0
        self._上次高度 = 0.0
        self._上次离目标 = 0.0

    # ---------------- 复位 ----------------
    def 复位(self):
        if self.名 == "站起来":
            self.身.摆成趴姿()
        else:
            self.身.摆成站姿()
        self.拍 = 0
        self._上次高度 = self.身.机身高度()
        self._上次离目标 = self._离目标()
        self._势上次 = self._势()
        self.掉倒 = False
        return self.观测()

    # ---------------- 观测 ----------------
    def _离目标(self):
        位 = self.身.数据.qpos[:2]
        return float(np.linalg.norm(self.目标 - 位))

    def 观测(self):
        身 = self.身
        基 = np.concatenate([
            身.关节偏差(),                      # 12
            身.关节角速度() * 0.2,              # 12（缩一下，和上面量级差不多）
            身.上方向(),                        # 3
            [身.机身高度()],                    # 1
            np.nan_to_num(身.足高(), nan=0.0),  # 4
        ])
        if self.名 == "站起来":
            return 基.astype(np.float32)
        位 = 身.数据.qpos[:2]
        差 = self.目标 - 位
        距 = float(np.linalg.norm(差))
        单位 = 差 / max(距, 1e-6)
        # 世界方向 -> 身体坐标系（绕 z 转 -yaw）
        w, x, y, z = 身.数据.qpos[3:7]
        yaw = np.arctan2(2 * (w * z + x * y), 1 - 2 * (y * y + z * z))
        c, s = np.cos(-yaw), np.sin(-yaw)
        体 = np.array([c * 单位[0] - s * 单位[1], s * 单位[0] + c * 单位[1]])
        return np.concatenate([基, 体, [距]]).astype(np.float32)

    def 观测维(self):
        return self.观测().size

    # ---------------- 一帧 ----------------
    def 步进(self, 发力):
        发力 = np.clip(np.asarray(发力, dtype=np.float64).reshape(肌肉数), 0.0, 1.0)
        self.身.步进(发力)
        self.拍 += 1
        高 = self.身.机身高度()
        歪 = self.身.机身歪了()
        前势 = self._势上次
        self._势上次 = self._势()

        # 奖励 = 势函数的差（"离做成还有多远"往前挪了多少），再扣一点使劲的代价。
        # 为什么用势函数：这样"把这一集的总奖励做到最大"和"把这件事做成"是同一件事，
        # 而且是**唯一**保证不会把聪明劲儿用歪的写法（Ng et al., 1999）。
        # 踩过的坑：第一版把 6.0×(长高多少) 和 0.4×cos(歪) 加在一起，趴着不动也有
        # 每拍 0.4（趴平的 cos 也是 1）—— 一集趴着 60 分、站着 95 分，差得太小，
        # PPO 学了几万步还在原地。（实测见 日志_RL对照_站起来.log 前两行。）
        奖 = self._势() - 前势 - 0.002 * float(np.mean(发力))
        self._上次高度 = 高

        结束 = self.拍 >= self.拍数上限
        self.掉倒 = False
        if self.名 == "看见红" and self.拍 > 5 and (高 < 0.15 or 歪 > 70.0):
            # ★ 摔倒 = 这一集当场结束（2026-09-16 加的，不加不行）。
            #   不这么写的话，"往前蹭"和"走过去"在奖励里是一样的：实测种子 0 跑到 100 万步，
            #   学会了**趴在地上把身体蹭出 0.98 米**（机身高只剩 0.086 米）—— 奖励被钻了空子。
            #   论文里我们自己那条路是**站着走过去**的（全程 0.26 米），所以对照也必须这么判。
            #   这是运动控制里的标准做法（摔倒终止），不是给我们自己开后门。
            结束 = True
            self.掉倒 = True
        信息 = {"机身高度": 高, "歪": 歪, "走了": self._走了多远(), "离目标": self._离目标(),
              "掉倒": self.掉倒}
        return self.观测(), float(奖), bool(结束), 信息

    def _势(self):
        """这一拍"离做成还有多远"的分数（越大越好）。只看得见现在，看不见历史。"""
        高 = self.身.机身高度()
        歪 = self.身.机身歪了()
        基 = 0.6 * min(高 / 0.261, 1.0) - 0.3 * min(歪, 90.0) / 90.0
        if self.名 == "站起来":
            return 3.0 * min(高 / 0.261, 1.0) - 0.3 * min(歪, 90.0) / 90.0
        return (2.0 * (self.目标距离 - self._离目标())
                + 1.5 * min(高 / 0.261, 1.0) - 0.6 * min(歪, 90.0) / 90.0)

    def _走了多远(self):
        return float(np.linalg.norm(self.身.数据.qpos[:2]))

    # ---------------- 判据（和论文里我们自己那一套一样） ----------------
    def 成功(self, 最后一拍):
        if self.名 == "站起来":
            return 最后一拍["机身高度"] >= 0.25 and 最后一拍["歪"] < 30.0
        return 最后一拍["走了"] >= 1.0 and 最后一拍["歪"] < 40.0


if __name__ == "__main__":
    import time
    for 名 in ("站起来", "看见红"):
        环 = 任务(名)
        o = 环.复位()
        print("任务「%s」：观测 %d 维，一集 %d 拍" % (名, o.size, 环.拍数上限))
        起 = time.time()
        n = 0
        for k in range(300):
            o, r, d, i = 环.步进(np.full(肌肉数, 0.5))
            n += 1
            if d:
                break
        print("   空转 300 拍用了 %.2f 秒 = %.0f 拍/秒" % (time.time() - 起, n / (time.time() - 起)))
        print("   随便给 0.5 的结果：", {k: round(v, 3) for k, v in i.items()})