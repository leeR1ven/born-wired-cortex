# -*- coding: utf-8 -*-
"""实验_追踪靠的是哪一层.py —— 「眼睛自动跟着小东西跑」这条本能，接在视觉网哪一层上才行？

★ 要证明的一件事（论文柱子四：分层的用处是压缩，压缩掉的细节就没了）：
  把**同一条**注视本能分别接在视觉网第 1 / 2 / 3 层上，每一层都**照同一套做法重新标定名字**
  （只是换一层去量），再拿**同一个**小东西去试 16 个方向，看眼睛转不转得过去。

★ 先把层号说清楚（2026-09-15 实测）：
  视觉网一共 4 层，但 普通层激活 只暴露 3 个：普通层激活[0]=第1层、[1]=第2层、[2]=**压缩完的输出层**，
  而 前向传播() 的返回值就是 普通层激活[2] 那一层（实测 np.array_equal = True）。
  所以真正不同的层只有 **3 个**：第1层（没压缩）、第2层、第3层（压缩完的）。
  以前文档里写的"第4层"其实是第3层，这一版把它改对了。

★ 标定用的是**真小球**（半径 0.05 米、3 米远 → 张角 1.9 度 = 0.31 个格子），
  不是"把一格涂满"——涂满一格各层都看得见，那就测不出压缩的代价了。

命令：
    python 实验_追踪靠的是哪一层.py            # 不接 + 第1/2/3层
    python 实验_追踪靠的是哪一层.py 1           # 只跑第 1 层
"""
from __future__ import annotations

import pathlib
import sys

import numpy as np

import 本能工具_instincts as 本能
import 视觉前处理_visual_preprocess as 视觉
import 运动输出区_motor_output as 运动
import 实验_眼睛跟随 as 跟随

根 = pathlib.Path(__file__).resolve().parent
列数 = int(视觉.大像素列数)
视场 = 100.0
列宽 = 视场 / 列数
球半径 = 0.05
测试秒数 = 3.0
帧秒 = 跟随.帧秒
要跑的 = [0, 1, 2, 3]
真灌视觉 = 本能.灌视觉
真读本能表 = 本能.读本能表
空 = {}


def 列中心角(c):
    return -视场 / 2 + 列宽 * (c + 0.5)


def 层激活(图, k):
    """第 k 层的激活。k=1/2 取普通层激活，k=3 是压缩完的输出层。"""
    末 = np.asarray(视觉.网.前向传播(视觉.图像转信号(图)), dtype=bool)
    if k == 3:
        return 末
    return np.asarray(视觉.网.普通层激活[k - 1], dtype=bool).copy()


视觉.网.前向传播(视觉.图像转信号(本能._空画面()))
for _k in (1, 2, 3):
    空[_k] = 层激活(本能._空画面(), _k)


def 造例子():
    """名字改用真小球标定：第 c 列 = 把小球摆在那一列的正中间。"""
    例子 = {}
    for c in range(列数):
        角 = 列中心角(c)
        例子["细_列%d" % c] = (lambda a=角: 本能._球在(np.radians(a), 半径=球半径))
    例子["细_高行"] = lambda: 本能._球在(0.0, 高度=0.95, 半径=球半径)
    例子["细_低行"] = lambda: 本能._球在(0.0, 高度=0.25, 半径=球半径)
    return 例子


def 有细胞(名字, 块):
    if ":" not in 块:
        return False
    区, 名 = 块.split(":", 1)
    return len(名字.get(区.strip(), {}).get(名.strip(), [])) > 0


def 试一个方向(大脑, 角):
    """眼前摆一个小球不动，让眼睛自己走 测试秒数 秒，返回末了的眼睛角度。"""
    w = 跟随.架好世界(球方位角=角, 球半径=球半径)
    大脑.亮[:] = False
    大脑.上一拍[:] = False
    运起, 运宽 = 大脑.运起, 大脑.运宽
    for _ in range(int(round(测试秒数 / 帧秒))):
        图 = w.看()
        大脑.一拍(图=图)
        力 = 运动.解码眼球发力(大脑.亮[运起:运起 + 运宽])
        w.眼肌发力 = 力
        w.走眼睛(帧秒)
        w.走物体(帧秒)
    return w.眼球水平


def 跑一层(k):
    本能._细节皮层 = ((lambda 图: np.nonzero(层激活(图, k) & ~空[k])[0]) if k
                   else (lambda 图: np.zeros(0, dtype=np.int64)))
    本能.读本能表 = 真读本能表
    本能.灌视觉 = 真灌视觉
    本能.视觉细节例子 = 造例子()
    if k:
        本能.名字文件 = 根 / ("皮层名字_小球_第%d层.json" % k)
        名字 = 本能.标定(说=False)
        细 = {n: len(v) for n, v in 名字["视觉细节"].items()}
    else:
        本能.名字文件 = 根 / "皮层名字.json"
        名字 = 本能.读名字()
        细 = {}
    原规则 = 真读本能表()
    if k:
        保 = [r for r in 原规则 if 有细胞(名字, r[0]) and 有细胞(名字, r[1])]
    else:
        保 = [r for r in 原规则 if not r[0].startswith("视觉细节:")
              and not r[0].startswith("视觉运动:") and not r[1].startswith("运动:眼")]
    本能.读本能表 = (lambda 表=保: 表)
    if k:
        def 灌(亮, 网, 图=None, 第4层=None, 第1层=None, _k=k):
            if 图 is None:
                真灌视觉(亮, 网, None, 第4层=None, 第1层=None)
                return
            末 = np.asarray(视觉.网.前向传播(视觉.图像转信号(图)), dtype=bool)
            真灌视觉(亮, 网, None, 第4层=末, 第1层=层激活(图, _k))
        本能.灌视觉 = 灌
    大脑 = 跟随.主循环.脑(学=False, 说=False)
    表 = []
    for c in range(列数):
        角 = 列中心角(c)
        末眼 = 试一个方向(大脑, 角)
        列名 = "细_列%d" % c
        细胞 = 细.get(列名, 0)
        表.append((c, 角, 细胞, 末眼))
    return {"层": k, "写进去": len(保), "总规则": len(原规则), "细": 细, "表": 表}


def main():
    要跑 = [int(a) for a in sys.argv[1:]] or 要跑的
    print("=" * 100)
    print("同一条注视本能接在不同层上；小东西（半径 %.2f 米 = %.2f 个格子）摆在 16 个方向，各试 3 秒"
          % (球半径, np.degrees(2 * np.arctan2(球半径, 3.0)) / 列宽))
    print("=" * 100)
    结果 = []
    for k in 要跑:
        print("\n" + "-" * 100)
        print("【%s】" % ("完全不接（对照）" if not k else "接在第 %d 层" % k))
        r = 跑一层(k)
        结果.append(r)
        print("  本能表写进去 %d/%d 条" % (r["写进去"], r["总规则"]))
        print("  %4s | %8s | %10s | %12s | %s" % ("列", "中心角", "这层有细胞", "末了眼朝哪", "眼睛转过去了吗"))
        for c, 角, 细胞, 末眼 in r["表"]:
            对 = (角 < 0 and 末眼 < -3.0) or (角 > 0 and 末眼 > 3.0)
            print("  %4d | %+7.1f度 | %10d | %+11.1f度 | %s"
                  % (c, 角, 细胞, 末眼, "转了" if 对 else "没转"))
    print("\n" + "=" * 100)
    print("【总表】「这一层对这个方向有细胞」和「眼睛转得过去」是不是同一件事")
    print("%10s | %18s | %18s | %s" % ("接在哪层", "有细胞的方向", "眼睛转过去的方向", "对得上吗"))
    print("-" * 100)
    for r in 结果:
        有 = [c for c, 角, 细胞, _ in r["表"] if 细胞 > 0]
        转 = [c for c, 角, 细胞, 末眼 in r["表"]
              if (角 < 0 and 末眼 < -3.0) or (角 > 0 and 末眼 > 3.0)]
        print("%10s | %18s | %18s | %s"
              % ("不接" if not r["层"] else "第%d层" % r["层"],
                 "%d 个: %s" % (len(有), 有), "%d 个: %s" % (len(转), 转),
                 "✓" if set(转) <= set(有) else "✗ 有转过去但没细胞的"))
    return 结果


if __name__ == "__main__":
    结果 = main()