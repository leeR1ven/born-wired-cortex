def 试(网, 源块="视觉:红", 拍数=6):
    名字 = 读名字()
    区源, 源 = 解析(名字, 源块)
    起 = 网.区起点[区源]
    拍 = np.zeros(网.总数, dtype=bool)
    拍[起 + 源] = True
    print(f"\n试一下：把「{源块}」的 {源.size} 个皮层细胞点亮（相当于模型'看到红色'），看这张网下一步怎么走")
    print(f"   第 0 拍：{源.size} 个（只给了视觉）")
    for i in range(1, 拍数 + 1):
        出 = 网.步进(拍)
        出[起 + 源] = True                  # 红色一直在，视觉一直亮着
        各 = "、".join(f"{区}{int(出[网.区段(区)].sum())}" for 区 in 各区宽度)
        print(f"   第 {i} 拍：共 {int(出.sum()):>6} 个   （{各}）")
        拍 = 出
    print("   若运动那一片被带亮，说明'看到红色 → 动起来'这条路是通的")


