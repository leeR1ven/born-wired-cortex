# ================= 「东西刚动过」那片回路（2026-09-15 加） =================
# 用户 2026-09-15 的描述（A -> a -> e -> f）：
#   "当第一帧时，物体激活了神经元A，第二帧物体移动了一点激活了神经元B，
#    第二帧时在上一帧被激活的神经元A又激活了神经元a，第三帧时神经元B与神经元a
#    又共同激活了神经元e，神经元e激活了控制眼部肌肉往右上移动的神经元f，
#    最后眼睛自动就往右上角的移动物体看去了。这件事本质上是把时间上连续但弱的信号，
#    转换成了某一刻的强的信号。"
#
# 我们这儿就是照这个搭的，一个方向两个小块（都是普通皮层神经元，不是代码）：
#   · 「痕迹」= 上一拍这个方向有东西   ← 名字 -> 痕迹（隔一拍才到，这就是那个"a"）
#   · 「变化」= 这一拍刚有、上一拍还没有
#               ← 名字给 1.2 的兴奋、痕迹给 -1.2 的压制，两路相减
#   · 「变化」-> 眼往那个方向（这就是那个"f"）
# 为什么"变化"要用痕迹压一下：不然东西只要在眼前，每一拍都算"刚有"，那就不叫"刚动过"了。
def _痕(名):
    """「痕迹」= 上一拍这个名字亮过。"""
    i = 细节名字们.index(名)
    return list(range(i * 每名字细胞, i * 每名字细胞 + 每方向细胞))


def _变(名):
    """「变化」= 这一拍亮、上一拍还没亮（名字减痕迹）。"""
    i = 细节名字们.index(名)
    return list(range(i * 每名字细胞 + 每方向细胞, i * 每名字细胞 + 2 * 每方向细胞))


