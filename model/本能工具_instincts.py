def 装(网=None, 说=True):
    """读 本能表.txt，把每条规则展开成一根一根的连接，写进皮层网。

    源如果写的是「运动记忆:某动作」（就是那个动作的头一拍），不写成一根死连接，而是展开成：
        · 第 0 拍 → 第 1 拍 → 第 2 拍 ……（一圈一拐的小电流，这就是"节奏"本身）
        · 每一拍 → 那一拍该用哪些肌肉细胞（肌肉记忆）
      于是只要"想一下"第 0 拍，这串动作就自己在皮层里走下去。
    """
    名字 = 读名字()
    规则 = 读本能表()
    动作库 = 读动作库()
    if not 规则:
        raise SystemExit("本能表是空的，一条规则都没有")
    if 网 is None:
        网 = 建网()
    rng = np.random.default_rng(建网种子)
    源段, 目段, 权段, 固段 = [], [], [], []
    抑源段, 抑目段, 抑权段 = [], [], []
    抑制游标 = [网.区起点["抑制"]]
    合计 = 0
    明细 = []

    def 取抑制细胞():
        """借一个抑制神经元来做「压住」这件事。"""
        i = 抑制游标[0]
        抑制游标[0] += 1
        if 抑制游标[0] > 网.区起点["抑制"] + 网.区宽["抑制"]:
            raise SystemExit("抑制神经元不够用了：把 本能工具_instincts.py 里「抑制」那一片调大一点")
        return i

    def 加(对源, 对目, 每股, 固化):
        对源 = np.asarray(对源, dtype=np.int64).ravel()
        对目 = np.asarray(对目, dtype=np.int64).ravel()
        源段.append(对源)
        目段.append(对目)
        权段.append(np.full(对源.shape, float(每股), dtype=np.float32))
        固段.append(np.full(对源.shape, bool(固化), dtype=bool))
        return 对源.size

    def 交叉(A, B, 权重, 固化):
        """A 里每个细胞连到 B 里每个细胞（力度平均分到每根上）。"""
        组合数 = A.size * B.size
        if 组合数 <= 一次最多写:
            对源 = np.repeat(A, B.size)
            对目 = np.tile(B, A.size)
            截 = ""
        else:
            对源 = rng.choice(A, 一次最多写)
            对目 = rng.choice(B, 一次最多写)
            截 = f"（组合 {组合数:,} 太多，随机抽了 {一次最多写:,} 根）"
        return 加(对源, 对目, 权重 / max(A.size, 1), 固化), 截

    for 源块, 目标块, 权重, 固化, 行号 in 规则:
        区源, 源 = 解析(名字, 源块)
        源 = 源 + 网.区起点[区源]
        区目标名, 目名字 = (目标块.split(":", 1) + [""])[:2]
        动作名 = 源块.split(":", 1)[1].strip() if 区源 == "运动记忆" else ""
        多拍 = (动作名 in 动作库 and len(动作库[动作名]["拍"]) > 1)
        if not 多拍:
            区目, 目标 = 解析(名字, 目标块)
            目标 = 目标 + 网.区起点[区目]
            压制 = 权重 < 0
            if 压制:
                # 力度写负数 = 「这条本能是压住的」：借一个抑制神经元来做。
                # 源 -> 抑制神经元（普通兴奋连接，把它点亮）
                # 抑制神经元 -> 目标（抑制连接，把目标压到点不着）
                中继 = 取抑制细胞()
                条, 截 = 交叉(源, np.array([中继], dtype=np.int64), -权重, 固化)
                抑源段.append(np.full(max(目标.size, 1), 中继, dtype=np.int64))
                抑目段.append(目标 if 目标.size else np.zeros(1, dtype=np.int64))
                # ★ 2026-09-15 实测后改的（用户要的"听到固定声音就停止移动"）：
                #   原来这里写死 抑制权重 = 1.0 → 实际只压掉 1.0 × 抑制强度1.5 = 1.5 的电流。
                #   可"走路"那个头细胞在走的时候收到的是
                #     视觉 0.95 + 前额叶 0.80 + 机身状态:在往前走 1.50 = 3.25
                #   → 压不住，实测"放了停音它照样一直走"（走路 100%）。
                #   根子不在音上，在"力度写多大都只压 1.5"。
                #   改成正路：**写多少力度，就压住多少电流**。
                压 = abs(float(权重)) / float(getattr(网, "抑制强度", 1.5) or 1.5)
                抑权段.append(np.full(max(目标.size, 1), 压, dtype=np.float32))
                合计 += 条
                if 说:
                    print(f"   {行号}  {源块}({源.size}个) -> [抑制神经元#{中继 - 网.区起点['抑制']}]"
                          f" -> {目标块}({目标.size}个)  压住电流 {abs(float(权重)):.2f}"
                          f"（权重 {压:.3f} × 抑制强度）"
                          f" -> 写 {条} 根兴奋 + {max(目标.size, 1)} 根抑制")
            else:
                条, 截 = 交叉(源, 目标, 权重, 固化)
                合计 += 条
                if 说:
                    print(f"   {行号}  {源块}({源.size}个) -> {目标块}({目标.size}个)"
                          f"  力度{权重}（每根 {权重 / max(源.size, 1):.5f}）"
                          f"  {'固化' if 固化 else '可塑'}  = 写入 {条:,} 根{截}")
            continue
        # ---- 多拍动作：在**运动记忆区这条时间线**上展开成一串时刻 ----
        拍表 = 动作库[动作名]["拍"]
        循环 = bool(动作库[动作名]["循环"])
        运起 = 网.区起点["运动"]
        记起 = 网.区起点["运动记忆"]
        时刻 = 记起 + 运动记忆.时刻们(动作名)          # 这个动作占的一串时刻（一个时刻一个神经元）
        if 源.size != 1 or 源[0] != 时刻[0]:
            条, _ = 交叉(源, 时刻[:1], 权重, 固化)     # 源不是第一时刻，就先接到第一时刻
            合计 += 条
        for j in range(len(拍表) - 1):                 # 这一时刻 → 下一时刻（时间往前走）
            合计 += 加(时刻[j:j + 1], 时刻[j + 1:j + 2], 权重, 固化)
        if 循环:                                       # 循环的动作：最后时刻接回第一时刻
            合计 += 加(时刻[-1:], 时刻[:1], 权重, 固化)
        # ★ 关键的一条：**新的时刻，把「刚才那一刻」压下去**。
        #   为什么非有不可：感觉是**一直**在的（红色一直在眼前、人一直趴在地上），
        #   触发每一拍都会把"头一刻"重新点一次。没有这条压制，整串动作就会
        #   一拍一拍**全部堆在一起亮**，出来的就是一坨叠加的力，而不是一串动作。
        #
        #   ★★ 而且必须**直连**，不能绕中继（2026-09-15 实测）：
        #      原来让"这一刻"先点一个抑制神经元、再由它去压"刚才那一刻"。
        #      中继多绕一步 → 压制要晚两拍才到 → "上上拍"永远压不掉，
        #      结果同一时间**稳定亮 3 个时刻**（实测：一直亮着 2447/2448/2449）。
        #      改成时刻神经元**自己直接发一根抑制连接**去压前一刻：
        #      压制和新生是同一拍到的 → 同一时间只剩 1 个时刻（"现在"）。
        #      这不是负权重 —— 就是一根普通的抑制连接。皮层里每个神经元
        #      出生本来就带抑制出边（见 皮层连接_cortex_links.py 的 _生抑制），
        #      这里只是给"时刻"这根线指定好它该压谁。
        def 直接压(源们, 目标, 力度=None):
            """源们这些时刻神经元，每个都直接发一根抑制连接去压 目标。

            一多一少就在这里摊平（59 个源压 1 个目标 = 重复 59 遍），
            因为最后是把所有规则拼成一个大数组一次性写进去的。
            """
            对源 = np.asarray(源们, dtype=np.int64).ravel()
            对目 = np.asarray(目标, dtype=np.int64).ravel()
            if 对源.size == 1 and 对目.size > 1:
                对源 = np.repeat(对源, 对目.size)
            elif 对目.size == 1 and 对源.size > 1:
                对目 = np.repeat(对目, 对源.size)
            elif 对源.size != 对目.size:
                raise SystemExit("直接压：源和目标数量对不上，%d vs %d" % (对源.size, 对目.size))
            抑源段.append(对源)
            抑目段.append(对目)
            抑权段.append(np.full(对源.size,
                                  float(链子抑制权重 if 力度 is None else 力度),
                                  dtype=np.float32))
            return 对源.size

        # (丙) 每个时刻亮一下，就把**自己**按下去（见 自己压自己权重 的说明）：
        #      "现在"只亮一拍，下一拍自动灭、让位给"下一拍"。同一瞬间只有 1 个时刻亮。
        合计 += 直接压(时刻, 时刻, 自己压自己权重)

        # (甲) 头一刻：**只要这串动作已经在跑了，就不许头一刻重新点火**。
        #      没有这条，感觉会每一拍都把整串从头点一次，越跑越多串叠在一起
        #      （实测：20 拍之后 20 个时刻一起亮，出来的是一坨叠加的力）。
        #
        #      ★ 循环动作要**把最后一刻排除在外**（2026-09-15 实测）：
        #        循环动作靠"最后一刻 → 头一刻"转圈。要是最后一刻也去压头一刻，
        #        头一刻就点不着了 —— 站姿/趴姿这种只有 2 拍的姿势最惨：
        #        A 压 B、B 压 A（B 既是"后面还有一刻"又是"转圈点火的那一下"），
        #        两拍互相压死，站起来跑完 1.2 秒后一接站姿就断，机器人当场塌下去。
        #        所以：循环动作只让**中间那些时刻**压头一刻。
        甲源 = 时刻[1:-1] if 循环 else 时刻[1:]
        if 甲源.size:
            合计 += 直接压(甲源, 时刻[:1], 头一刻抑制权重)
        # (乙) 「新的这一刻压住刚才那一刻」这一条**不要**（2026-09-15 实测后删掉）。
        #      实测：不写它，同一时间照样只亮 2 个时刻（"现在" + 刚过去那一刻），
        #      写了它也是 2 个 —— 因为"下一拍"本来就没有兴奋往里送，自己会灭。
        #      但它会**掐死只有 2 拍的循环动作**：站姿/趴姿这种 A→B→A 的转圈，
        #      A 压 B、B 压 A 互相压住 → 两拍都点不着 → 动作直接断（实测：
        #      站起来跑完 1.2 秒后要接"站姿"，结果运动记忆变成 0，机器人塌下去）。
        #      所以：只留 (甲)（那是防"感觉一直点火"的），这条去掉。
        接 = 动作库[动作名].get("接")
        if 接 and 接 in 运动记忆.时刻段:               # 做完这个动作，接着保持「接」的那个姿势
            合计 += 加(时刻[-1:], 记起 + np.array([运动记忆.起手(接)], dtype=np.int64), 权重, 固化)
        for j, 发 in enumerate(拍表):                  # 每一时刻 → 那一刻该动的肌肉细胞
            胞 = 运动.发力转激活(np.array(发, dtype=float))
            目标 = np.nonzero(胞)[0] + 运起
            if 目标.size == 0:
                continue
            合计 += 加(np.repeat(时刻[j:j + 1], 目标.size), 目标, 权重, 固化)
        if 说:
            print(f"   {行号}  {源块} -> {目标块}  力度{权重}  "
                  f"{'固化' if 固化 else '可塑'}  = 展开成 {len(拍表)} 拍"
                  f"{'（转圈）' if 循环 else '（放完就停）'}  共 {合计} 根")
    # ============ 「一段神经元自动首尾接成环」（2026-09-16）============
    # 用户原话："任何一段神经元被激活后，我们直接手动给这段神经元连接一个循环……
    #   我们让'声音'激活的神经元的开头和结尾连起来，自动能让声音在大脑里被持续激活，
    #   让人所有的记忆都可以被循环持续激活，这些循环持续激活只存在前额叶，
    #   所以不影响记忆区的按顺序激活。"
    #
    # 做法（一条通用规则，不用一条条点名）：
    #   凡是**标定过名字**的那些组神经元，取它们在本区里的编号、从小到大排好：
    #   第 0 个接第 1 个、第 1 个接第 2 个……最后一个接回第 0 个。
    #   每一根力度 = 环力度（> 兴奋阈值 1.0）。于是这一段里**任意一个**细胞亮起来，
    #   就会把下一个点亮、再下一个……很快整段都亮；整段都亮之后，每个细胞都从
    #   它前面那个收到电流，于是**整段一起亮着、不灭** —— 这就是"持续激活"。
    #
    # 为什么"一段"的单位是名字：连接是出生前写死的，写的时候不知道将来哪一段会被
    #   点亮，所以只能按"已经标定过的东西"成环。这是自动的，不用一条条点名。
    #
    # 为什么只给前额叶写（不给感觉区、也不给运动记忆区）：用户说了"只存在前额叶"。
    #   运动记忆区那条按顺序走的链子必须保持"一拍只亮一个"，加了环会把它堵死。
    #
    # ★ 为什么不顺手加"亮一下把自己按下去"：运动记忆那条链子是一拍只亮一个，
    #   所以要自压来让位给下一拍。这里的环要的是**整段一起亮、然后赖着不走**，
    #   自压会把整段自己压灭（算式：环给的兴奋 2.0 < 自压的抑制 2.0×1.5=3.0）。
    # ★ 2026-09-16 补一个**对照开关**：不写环=1 时不写这些环。
    #   用途：分清"R4 的色相边界变了"到底是环带来的，还是别的东西带来的。
    #   （这不是架构的一部分，和 前额叶不保留 一样，只是做对照用。）
    环力度 = 2.0
    环条数, 环组数 = 0, 0
    _不写环 = os.environ.get("不写环") == "1"
    for _名, _胞 in ({} if _不写环 else 名字.get("前额叶", {})).items():
        _胞 = np.sort(np.asarray(_胞, dtype=np.int64))
        if _胞.size < 2:
            continue
        _胞 = _胞 + 网.区起点["前额叶"]
        环条数 += 加(_胞, np.roll(_胞, -1), 环力度, True)
        环组数 += 1
    合计 += 环条数
    if 说 and 环组数:
        print(f"   环：前额叶 {环组数} 段名字自动首尾接成环，共 {环条数:,} 根"
              f"（{'、'.join(名字.get('前额叶', {}).keys())}）")

    # ============ 「动作内部的时刻不接学习」（2026-09-16）============
    # 运动记忆区那条时间线上，每个动作占连续一串时刻。**头一拍 = 这个动作的入口**
    # （本能表里外面的东西一律只接到头一拍，见上面「源不是第一时刻，就先接到第一时刻」）。
    # 动作内部那些时刻是"这套动作自己怎么走"的固定走法（自压 + 头一刻抑制，都是写死的），
    # 所以：**学习（含多巴胺）只许连到入口，内部时刻一律不许连。**
    # 为什么非加不可（2026-09-16 实测）：不加的话，声音会把走路那 15 个时刻**全**连上，
    # 一放声音 15 个时刻一起亮、力全部叠在一起，身体一动不动（实测挪 0.002 米）。
    _掩 = np.ones(网.总数, dtype=bool)
    _记起 = 网.区起点["运动记忆"]
    for _名, _时刻 in 运动记忆.时刻段.items():
        if len(_时刻) > 1:
            _掩[_记起 + np.asarray(_时刻[1:], dtype=np.int64)] = False
    网.可学习目标 = _掩

    条数 = 网.写入连接(np.concatenate(源段), np.concatenate(目段),
                      np.concatenate(权段), np.concatenate(固段))
    抑条 = 0
    if 抑源段:
        # 源和目标数量可能不一样（例如"后面每一刻" 59 个源去压"头一刻" 1 个目标），
        # 一多一少由 写入抑制连接 自己摊开（它会把少的一边重复到位）。
        抑条 = 网.写入抑制连接(np.concatenate(抑源段),
                             np.concatenate(抑目段),
                             np.concatenate(抑权段), True, 允许自压=True)
    if 说:
        print(f"本能装完：一共写进 {条数:,} 根兴奋连接 + {抑条:,} 根抑制连接"
              f"（用了 {抑制游标[0] - 网.区起点['抑制']} 个抑制神经元）")
    return 网, 条数


