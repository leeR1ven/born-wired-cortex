def _图(通道=None, 值=255, 起=None, 止=None):
    图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
    if 通道 is None:
        图[:, :] = 值
    elif 起 is None:
        图[:, :, 通道] = 值
    else:
        图[:, 起:止, 通道] = 值
    return 图


def _谱(起, 止):
    a = np.zeros(谱长)
    a[起:止] = 1.0
    return a


