def _球在(方位角=0.0, 高度=0.60, 距离=3.0, 半径=0.30, 色=(230, 30, 30)):
    """让「世界」真渲染一张第一人称画面：眼前某个方向摆一个球，别的什么都不放。

    为什么必须用真画面标定：本能连接要写的是「皮层上哪些细胞代表什么」，
    这件事只能拿眼睛**真看到**的那张图去问。拿"上半屏红"这种画出来的方块去标，
    跟真画面差太远，标出来的细胞到真画面里可能一个都不亮。
    方位角：0 = 正前方，正 = 画面上偏右（和 世界_world.眼里在哪 一个口径）。
    高度 0.60 米 = 和眼睛一样高（正好在画面正中那条线上）。
    """
    w = 世界.世界()
    w.摆成站着()
    w.清空物体()
    w.加物体(距离 * np.cos(方位角), 距离 * np.sin(方位角), 高度, 半径, 色)
    return w.看()


