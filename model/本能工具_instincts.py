def _读一个表(路径, 规则):
    for 行号, 原行 in enumerate(路径.read_text(encoding="utf-8").splitlines(), 1):
        行 = 原行.split("#")[0].strip()
        if not 行:
            continue
        if "->" not in 行:
            print(f"   {路径.name} 第 {行号} 行看不懂（没有 ->），跳过：{原行.strip()}")
            continue
        左, 右 = 行.split("->", 1)
        字段 = 右.split()
        if not 字段:
            print(f"   {路径.name} 第 {行号} 行目标为空，跳过")
            continue
        目标 = 字段[0]
        权重 = float(字段[1]) if len(字段) > 1 else 1.0
        固化 = len(字段) > 2 and 字段[2].strip() in ("是", "1", "true", "True", "对")
        规则.append((左.strip(), 目标, 权重, 固化, "%s 第%d行" % (路径.name, 行号)))
    return 规则


