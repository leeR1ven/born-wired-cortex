def 抠(文本, 正则):
    m = re.search(正则, 文本)
    if not m:
        return None
    if m.groups():
        return " / ".join(g for g in m.groups() if g is not None)
    return "有"


def 比(拿到, 期望):
    if 拿到 is None:
        return False
    if isinstance(期望, (int, float)):
        try:
            return abs(float(拿到) - float(期望)) < 1e-6
        except ValueError:
            return False
    return 拿到.strip() == str(期望).strip()


def 翻日志():
    通过, 失败 = [], []
    for c in 检查们:
        路 = 找日志(c["日志"])
        if not 路.exists():
            失败.append((c, "找不到日志 %s" % c["日志"]))
            continue
        拿到 = 抠(io.open(路, encoding="utf-8", errors="replace").read(), c["正则"])
        (通过 if 比(拿到, c["期望"]) else 失败).append(
            (c, 拿到 if 拿到 is not None else "（日志里没找到这一段）"))
    print("=" * 96)
    print("论文数字 <-> 日志：一共 %d 条" % len(检查们))
    print("=" * 96)
    for c, 拿到 in 通过:
        print("  ✓ [%-4s] %s" % (c["位置"], c["说明"]))
    for c, 拿到 in 失败:
        print("  ✗ [%-4s] %s" % (c["位置"], c["说明"]))
        print("        期望 %s，日志里抠到 %s（%s）" % (c["期望"], 拿到, c["日志"]))
    print()
    print("  对上 %d 条，对不上 %d 条 —— %s"
          % (len(通过), len(失败), "全部一致 ✓" if not 失败 else "有对不上的，见上 ✗"))
    return len(失败) == 0


