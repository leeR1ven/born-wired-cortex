#   后果一：那几片"哪个方向有东西"的名字被这片糊垫亮了 20~30%，本能连接于是在
#          "什么都没有"的时候也在拉，**眼睛自己往一边飘**（实验_眼睛跟随.py 第一次实测）。
#   后果二：想象出来的画面和真看到的画面**一样亮**，分不出哪些是外面真有东西。
#   实测这一片有多敏感（眼前什么都没有时）：
#     0.30 → 塞 5133 个细胞；0.32 → 3790；0.35 → 2239；0.40 → 1074；0.45 → 371；0.50 → 155。
#   取 0.40：提示还在（1074 个细胞，"心里能看见一点"），但已经压到不够触发本能（见下）。
返回保留比例 = 0.40   # 天生互惠线门限：回传信号 >= 这一路峰值 x 该比例 才亮（越小提示越多越粗）
返回线 = 天生互惠返回线(前额网, 返回保留比例=返回保留比例)


