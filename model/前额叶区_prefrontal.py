def 扩散(模式, 段宽, 半宽):
    """把每个亮着的神经元连同段内前后 ±半宽 一起点亮（每段内首尾成环）"""
    if 半宽 <= 0:
        return np.asarray(模式, dtype=bool)
    out = np.zeros(段宽, dtype=bool)
    for p in np.nonzero(模式)[0]:
        for d in range(-半宽, 半宽 + 1):
            out[(p + d) % 段宽] = True
    return out


class 前额叶神经网络:
    """前额叶网络：几路稀疏激活拼成输入，局部连接成环、阈值放电（和其他区一样的稀疏网络）。

    每一层的每个细胞，从前後各 连接半径 个细胞里收 2*连接半径+1 根固定连接。
    中间层用 隐藏层阈值，最后一层（输出层）用更高的 输出层阈值，
    保证整片只亮少量细胞 —— 这就是"把很多信号再压成很少信号"。
    """

    def __init__(self, 输入路, 层数=3, 连接半径=10, 权重范围=0.1,
                 隐藏层阈值=0.55, 输出层阈值=1.2):
        """输入路 = [(区名, 这一路多少个细胞, 这一路的扩散半宽, 这一路有没有返回线), ...]；顺序就是拼接顺序。"""
        self.输入路 = [(名, int(宽), int(半), bool(可回)) for 名, 宽, 半, 可回 in 输入路]
        self.输入数量 = sum(宽 for _, 宽, _, _ in self.输入路)
        self.路偏移 = {}
        起 = 0
        for 名, 宽, _, _ in self.输入路:
            self.路偏移[名] = 起
            起 += 宽
        self.每层数 = self.输入数量
        self.输出层数量 = self.输入数量
        self.层数 = 层数
        self.半径 = 连接半径
        连接数 = 2 * 连接半径 + 1
        目标 = np.arange(self.输入数量)
        偏移 = np.arange(-连接半径, 连接半径 + 1)
        self.来源 = []
        self.权重 = []
        self.阈值 = []
        出生随机 = np.random.default_rng(出生种子)
        for k in range(层数 - 1):
            局部来源 = (目标[:, None] + 偏移[None, :]) % self.输入数量
            局部权重 = 出生随机.uniform(0, 权重范围, size=(self.输入数量, 连接数))
            用哪个阈值 = 输出层阈值 if k == 层数 - 2 else 隐藏层阈值
            self.阈值.append(np.full(self.输入数量, 用哪个阈值))
            self.来源.append(局部来源)
            self.权重.append(局部权重)
        self.普通层激活 = [np.zeros(self.输入数量, dtype=bool) for _ in range(层数 - 1)]
        self.输入激活 = np.zeros(self.输入数量, dtype=bool)
        # 这一拍各路**原样**拼起来的输入（没有扩散过）。返回线要用它：
        # 见 天生互惠返回线._按路切开 的"只维持、不点火"。
        self.原始输入 = np.zeros(self.输入数量, dtype=bool)

    def 拼输入(self, 各路):
        """{区名: 0/1 数组} → 一条长度 = 输入数量 的 0/1 输入（每一路先各自扩散）。

        没给到的区当"这一路现在静着"（比如没给声音、没在放动作）。
        """
        拼 = np.zeros(self.输入数量, dtype=bool)
        原 = np.zeros(self.输入数量, dtype=bool)
        for 名, 宽, 半, _ in self.输入路:
            这路 = 各路.get(名)
            if 这路 is None:
                continue
            这路 = np.asarray(这路, dtype=bool).ravel()
            if 这路.size != 宽:
                raise ValueError("「%s」这一路应该是 %d 个细胞，给了 %d 个 —— "
                                 "前额叶的输入路表和区宽度对不上了" % (名, 宽, 这路.size))
            起 = self.路偏移[名]
            原[起:起 + 宽] = 这路
            拼[起:起 + 宽] = 扩散(这路, 宽, 半)
        self.原始输入 = 原
        return 拼

    def 前向传播(self, 各路, 输入衰减=0.0):
        """各路 = {区名: 0/1 数组}（见 拼输入）。返回输出层（= 前额叶皮层）的 0/1。"""
        self.输入激活[:] = self.拼输入(各路)
        当前激活 = self.输入激活.astype(float) * (1.0 - 输入衰减)  # 需要时可以把外界信号整体压弱一点
        for k in range(self.层数 - 1):
            加权和 = (self.权重[k] * 当前激活[self.来源[k]]).sum(axis=1)
            当前激活 = 加权和 >= self.阈值[k]
            self.普通层激活[k] = 当前激活
            当前激活 = 当前激活.astype(float)
        return 当前激活


class 天生互惠返回线:
    """前额叶 → 各区的回程：出生接好、固定不动、不学习、不遗忘（天生互惠）。

    做法：把正向那张邻居表方向倒过来用 —— 输出层亮着谁，就把出生时连着它的那些浅层
    细胞点亮，一层一层倒着走回输入层；走回输入层以后**按路切开，谁的路还给谁**。

    粗就粗在：它只是把"大概在想什么"送回各区，做不了逐细胞精确还原 —— 这正是用户说的
    "不要通过具体激活的字确定具体想了什么，只能确定一个大致的思考范围"。
    """

    def __init__(self, 前额网, 返回保留比例=0.40):
        self.输入路 = 前额网.输入路
        self.路偏移 = 前额网.路偏移
        self.输入数量 = 前额网.输入数量
        self.每层数 = 前额网.每层数
        self.层数 = 前额网.层数
        # 直接借用正向的邻居表与出生权重（只读），方向倒过来用就是互惠回路
        self.来源 = 前额网.来源
        self.权重 = 前额网.权重
        self.返回保留比例 = 返回保留比例
        self.上次峰值 = {}          # 诊断用：上一次返回时，每一路回传信号的峰值
        self.网 = 前额网            # 只读：拿"这一拍各路原样是什么"
        # ★★ 2026-09-18：**只维持、不点火**的那几路。
        #   为什么单独给运动记忆开这个口子（同一条规律）：运动记忆是一条时间线，
        #   **一个细胞 = 一整套动作**（60 拍）。返回线是"大概在想什么"那种粗信号，
        #   经网络的 连接半径 一散，落在时间线上就会跨过动作边界 —— 实测：趴着自己
        #   站起来，第 51 拍返回线把邻着的"趴下去"（头一拍就在"站起来"尾巴后面）
        #   送回了运动记忆，那套 60 拍动作当场跑起来；运动区是"亮几个神经元就是多大力"，
        #   两套动作同时亮 = 每块肌肉取最大值，于是"趴下去"的力一点点把身体从 0.265 米
        #   拽到 0.180 米。把这一路干脆砍掉是**错的**（用户 2026-09-18："你把运动记忆/
        #   运动也不设返回线，那前额叶怎么发信息给运动区？"）—— 前额叶要发信息给运动区
        #   这条通路必须留着。所以这里不是砍掉，而是**把粗信号限制在"正在做的那套动作"
        #   里面**：回传的细胞必须同时是这一拍这一路**真的亮着的**（没扩散过的原始输入）。
        #   效果 = 用户说的"有其他神经元持续激活站姿相关的神经元"：返回线在运动记忆里
        #   只起"维持"，起不了"凭空点着一套新动作"。想真正挑一个动作，走本能表里那条
        #   精确的路（前额叶:看着红 → 运动记忆:前进1.2，以及赫布学习长出来的那些）。
        self.只维持的区 = ("运动记忆",)

    def 空(self):
        return {名: np.zeros(宽, dtype=bool) for 名, 宽, _, _ in self.输入路}

    def 返回(self, 输出激活, 抑制量=0.0):
        """前额叶输出层 0/1 → {区名: 0/1 数组}（每一路各按各的门限）"""
        深层激活 = np.asarray(输出激活, dtype=bool)
        if not 深层激活.any():
            return self.空()
        for k in range(self.层数 - 2, -1, -1):
            深层们 = np.nonzero(深层激活)[0]   # 这一轮亮着的深层神经元
            if 深层们.size == 0:
                break
            浅层们 = self.来源[k][深层们]       # 它们出生时连着的浅层神经元
            固定权重 = self.权重[k][深层们]     # 每条连线出生时的固定权重
            信号 = np.zeros(self.每层数)
            np.add.at(信号, 浅层们.ravel(), 固定权重.ravel())
            # 门限参考未受抑制的峰值；若先衰减再取峰值，比例门限会把
            # 0~1 之间的部分抑制完全抵消，使抑制只能全开/全关。
            峰值 = 信号.max()
            if 峰值 <= 0:
                break
            信号 = 信号 * (1.0 - 抑制量)   # 需要时可以整条压弱（抑制量 0~1）
            if k == 0:
                return self._按路切开(信号)     # 走到输入层了：切开还给各区
            深层激活 = 信号 >= self.返回保留比例 * 峰值
        return self.空()

    def _按路切开(self, 信号):
        """每一路各按各的峰值算门限：一路大的（视觉）不该把一路小的盖死。

        另外：**没有返回线的那几路（身体那三个感觉区）在这里直接被丢掉**，
        一个细胞都不往回送 —— 见 输入路 那张表最后一列的说明。
        """
        出 = {}
        for 名, 宽, _, 可回 in self.输入路:
            起 = self.路偏移[名]
            if not 可回:
                出[名] = np.zeros(宽, dtype=bool)
                continue
            段 = 信号[起:起 + 宽]
            峰 = float(段.max()) if 段.size else 0.0
            self.上次峰值[名] = 峰        # 诊断用：这一路回传信号的峰值
            出[名] = (段 >= self.返回保留比例 * 峰) if 峰 > 0 else np.zeros(宽, dtype=bool)
            if 名 in self.只维持的区:      # 只维持、不点火（见 __init__ 那段说明）
                现在 = getattr(self.网, "原始输入", None)
                if 现在 is not None:
                    出[名] = 出[名] & 现在[起:起 + 宽]
        return 出


