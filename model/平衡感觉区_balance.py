def 读身体(身):
    """从真身体上读出这 6 个特征（每个 -1~1）。"""
    p = 身.数据.qpos
    v = 身.数据.qvel
    上 = 身.上方向()
    return np.array([
        np.clip(上[2], -1, 1),                # 站直
        np.clip(上[0] / 0.6, -1, 1),          # 前倾
        np.clip(上[1] / 0.6, -1, 1),          # 侧倾
        np.clip(v[4] / 3.0, -1, 1),           # 前后角速度
        np.clip(v[3] / 3.0, -1, 1),           # 左右角速度
        np.clip(v[5] / 3.0, -1, 1),           # 打转角速度
    ])


