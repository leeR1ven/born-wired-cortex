# -*- coding: utf-8 -*-
"""感觉区_共同.py —— 三个"身体感觉区"共用的零件。

★ 为什么身体感觉不像视觉/听觉那样用一张随机压缩网

  像素、频点的编号本身没有意义，压完以后哪个细胞代表什么，只能靠"给例子标定"。
  身体感觉不一样：关节角、倾角、角速度这些量本来就**有意义**，
  所以直接排好：一个细胞 = 某个特征在第几档（负半 10 档 + 正半 10 档）。
  这些名字天生认得出来，本能表可以直接写。

★ 2026-09-15：把原来混在一起的那一片拆成三个区（用户："本体感觉确实该拆开"）

  · 本体感觉区_proprioception = 真本体感觉：12 个关节角 + 12 个关节角速度
                                （关节、肌肉那一路）
  · 平衡感觉区_balance       = 前庭/耳石那一路：站直程度、前后倾、左右倾
                                + 三个角速度（前后翻 / 左右翻 / 打转）
  · 机身状态区_bodystate     = **身体其实感觉不到的**三个量：机身高度、前后速度、左右速度。
                                它们是"算出来的"（机器人拿关节角 + 重力方向就能推出来），
                                不是长在身上的传感器。先单独放一个区，
                                方便以后决定要不要留 —— 以前它们跟真本体感觉混在一堆，
                                是这次拆开的直接原因。

★ 一个特征怎么编码

  一个特征占 每特征细胞 = 20 个细胞：前 10 个是负半（-1~0），后 10 个是正半（0~1）。
  值是 v 时，亮它所在那一半、档位附近的三个细胞 —— 所以
  **相近的状态点亮的细胞重叠（模糊），差得远的状态几乎不重叠（分得开）**。
"""
from __future__ import annotations

import numpy as np

每档 = 10                 # 正/负各分几档
每特征细胞 = 每档 * 2     # 一个特征占多少细胞


class 调谐感觉区:
    """一个感觉区：特征名定下来，细胞排布就定下来了。"""

    def __init__(self, 区名, 特征名):
        self.区名 = 区名
        self.特征名 = list(特征名)
        self.特征数 = len(self.特征名)
        self.输出层数量 = self.特征数 * 每特征细胞
        self.总数 = self.输出层数量
        self.情况 = {}

    # ---------------- 编码 / 解码 ----------------
    def _起点(self, 特征下标):
        return 特征下标 * 每特征细胞

    def 状态转激活(self, 状态):
        """一串特征（每个 -1~1）-> 皮层上该亮哪些细胞。"""
        值 = np.clip(np.asarray(状态, dtype=float).ravel(), -1.0, 1.0)
        if 值.size != self.特征数:
            raise ValueError("%s 要 %d 个特征，给了 %d 个"
                             % (self.区名, self.特征数, 值.size))
        激活 = np.zeros(self.输出层数量, dtype=bool)
        for i in range(self.特征数):
            v = 值[i]
            if v == 0.0:
                continue
            档 = int(np.clip(round(abs(v) * 每档), 1, 每档))
            偏 = 0 if v > 0 else 每档          # 正半在前、负半在后
            for d in (-1, 0, 1):               # 邻近档也点着 = 模糊
                j = 档 - 1 + d
                if 0 <= j < 每档:
                    激活[self._起点(i) + 偏 + j] = True
        return 激活

    def 解码特征(self, 激活):
        """从皮层读回每个特征（-1~1），用来检查编码。"""
        激活 = np.asarray(激活, dtype=bool)
        出 = np.zeros(self.特征数)
        for i in range(self.特征数):
            段 = 激活[self._起点(i): self._起点(i) + 每特征细胞]
            正 = int(段[:每档].sum()); 负 = int(段[每档:].sum())
            出[i] = (正 - 负) / 每档
        return 出

    # ---------------- 情况 = 一组名字 ----------------
    def 块(self, 特征, 方向, 档起, 档止):
        """某个特征的某一半、第 档起~档止 档（含两端）用到的细胞。

        只盯**一个档位**最好用：真实状态在每个特征上只点亮"那一档附近的 3 个细胞"。
        要是画成"第 6~10 档"这么宽一块（十几个细胞），真实状态顶多填满其中三四个，
        整块亮起来的力气凑不够，本能永远不触发（这个坑踩过）。
        只盯一档时：对上了就是整块亮（触发干脆），差一档还能亮 2/3（模糊、有余量），
        差两档就完全不重叠（不串味）。
        """
        i = self.特征名.index(特征) if isinstance(特征, str) else int(特征)
        偏 = 0 if 方向 > 0 else 每档
        出 = []
        for 档 in range(档起, 档止 + 1):
            for d in (-1, 0, 1):
                j = 档 - 1 + d
                if 0 <= j < 每档:
                    出.append(self._起点(i) + 偏 + j)
        return sorted(set(出))

    def 加情况(self, 名, *块们):
        """把一个"情况"登记成名字：几块并起来（比如"趴着"= 四条腿都蜷着）。"""
        集 = set()
        for 块 in 块们:
            集 |= set(块)
        self.情况[名] = sorted(集)
        return self.情况[名]

    def 皮层(self, 状态):
        return np.nonzero(self.状态转激活(状态))[0]

    # ---------------- 自检 ----------------
    def 自检(self):
        print("%s：%d 个特征，每个 %d 个细胞，一共 %d 个皮层细胞"
              % (self.区名, self.特征数, 每特征细胞, self.输出层数量))
        名字 = list(self.情况)
        集 = {名: set(self.情况[名]) for 名 in 名字}
        print("  情况 %d 个：%s" % (len(名字), "、".join(名字)))
        最坏, 对 = 0.0, None
        for i in range(len(名字)):
            for j in range(len(名字)):
                if i == j:
                    continue
                比 = len(集[名字[i]] & 集[名字[j]]) / max(len(集[名字[i]]), 1)
                if 比 > 最坏:
                    最坏, 对 = 比, (名字[j], 名字[i])
        if 对 is None:
            print("  互相误亮：0% —— 这些情况一个细胞都不重叠")
        else:
            print("  互相误亮：最坏是「%s」会把「%s」点亮 %.0f%%（力度 1.5 要 67%% 以上才误触发）"
                  % (对[0], 对[1], 最坏 * 100))


# ================= 三个感觉区一起用 =================
def 三个感觉区():
    import 本体感觉区_proprioception as 本体感觉
    import 平衡感觉区_balance as 平衡感觉
    import 机身状态区_bodystate as 机身状态
    return [("本体感觉", 本体感觉), ("平衡感觉", 平衡感觉), ("机身状态", 机身状态)]


def 读身体特征(身):
    """按顺序拼出全部 33 个特征（-1~1）。要给"整体状态"打分的地方用（比如 算反射.py）。"""
    return np.concatenate([区.读身体(身) for _, 区 in 三个感觉区()])


def 灌感觉(亮, 网, 身):
    """把身体的当前状态灌进三个感觉区（亮 是整张网上的 0/1 数组，就地改）。"""
    for 区名, 区 in 三个感觉区():
        起 = 网.区起点[区名]
        亮[起:起 + 区.输出层数量] = 区.状态转激活(区.读身体(身))
    return 亮
