帧秒 = 1.0 / 50.0
真读本能表 = 本能.读本能表
组头 = re.compile(r"^#\s*=+\s*(.+?)\s*=*$")
条目式 = re.compile(r"^(\S+)\s*->\s*(\S+)\s+(-?[\d.]+)\s*(\S*)")

种子们默认 = [20260914, 20260915, 20260916]


def 读表带组(路径):
    """读一张本能表，给每条打上它属于哪一组（靠 # ==== 那一行的标题）。"""
    if not 路径.exists():
        return []
    行们 = io.open(路径, encoding="utf-8").read().split("\n")
    组 = None
    出 = []
    for i, x in enumerate(行们, 1):
        m = 组头.match(x.strip())
        if m:
            组 = m.group(1)
            continue
        s = x.strip()
        if not s or s.startswith("#"):
            continue
        m2 = 条目式.match(s)
        if not m2:
            continue
        出.append({"源": m2.group(1), "目标": m2.group(2), "力度": float(m2.group(3)),
                   "固化": (m2.group(4) == "是"), "行号": i, "组": 组 or "反射表"})
    return 出


def 全部条目():
    出 = 读表带组(本能.本能表文件)
    表 = 本能.根 / "反射表.txt"
    if 表.exists():
        出 = 出 + 读表带组(表)
    return 出


def 分前提(条们):
    """把「零、动作前提」那 15 条按**源在哪个区**分成三堆。"""
    平, 红, 听 = [], [], []
    for c in 条们:
        区 = c["源"].split(":")[0]
        if 区 in ("机身状态", "本体感觉", "平衡感觉"):
            平.append(c)
        elif 区 in ("视觉", "前额叶"):
            红.append(c)
        elif 区 == "听觉":
            听.append(c)
        else:
            平.append(c)
    return 平, 红, 听


def 是运动库(组):
    return 组 is not None and 组[0] in "一二三四五六" and 组[1:2] == "、"


def 造五阶段():
    全部 = 全部条目()
    运动库 = [c for c in 全部 if 是运动库(c["组"])]
    前提 = [c for c in 全部 if c["组"].startswith("零、")]
    注视 = [c for c in 全部 if c["组"].startswith("零之二") or c["组"].startswith("零之三")]
    反射 = [c for c in 全部 if c["组"] == "反射表"]
    平, 红, 听 = 分前提(前提)
    阶段 = []
    阶段.append(("A_只有运动库", 运动库))
    阶段.append(("B_加平衡起身", 运动库 + 平 + 反射))
    阶段.append(("C_加看见红走", 运动库 + 平 + 反射 + 红))
    阶段.append(("D_加听觉", 运动库 + 平 + 反射 + 红 + 听))
    阶段.append(("E_加眼睛注视", 运动库 + 平 + 反射 + 红 + 听 + 注视))
    return 阶段, {"运动库": len(运动库), "平衡起身": len(平) + len(反射),
                  "看见红": len(红), "听觉": len(听), "注视": len(注视)}


def 装阶段(条们):
    表 = [(c["源"], c["目标"], c["力度"], c["固化"], c["行号"]) for c in 条们]
    本能.读本能表 = lambda 表=表: 表
    try:
        return 主循环.脑(学=False, 说=False)
    finally:
        本能.读本能表 = 真读本能表


def 清脑(脑):
    脑.亮[:] = False
    脑.上一拍[:] = False


# ================= 七个行为，每个都只看"外界给了什么、身体做了什么" =================

def 跑身体(脑, 身, 秒, 图=None, 声=None, 用感觉=True, 盯=None):
    """闭环跑一段。

    盯 = 要数的那个动作名。数两样（2026-09-15 改过一次）：
      · 点火   = 那串时刻里**有没有亮着**（和 验证_前额叶.py 同一个判据；走路这个动作
                 一旦跑起来，整串时刻几乎每一拍都有亮的）
      · 头点火 = **只有头一拍**亮了几拍（= 这一串动作这一拍是不是刚"重新起头"）
    原来只数头一拍，结果和 R2 那张表的判据对不上（199/200 vs 14/200），所以两个都留着报。
    """
    起 = 身.数据.qpos[:2].copy()
    最高 = 身.机身高度()
    点火 = 0
    头点火 = 0
    时刻 = None
    if 盯:
        时刻 = 脑.网.区起点["运动记忆"] + np.asarray(运动记忆.时刻们(盯), dtype=np.int64)
    for _ in range(int(round(秒 / 帧秒))):
        脑.一拍(图=图, 声=声, 身=(身 if 用感觉 else None))
        身.步进(脑.肌肉发力())
        最高 = max(最高, 身.机身高度())
        if 时刻 is not None:
            if bool(脑.上一拍[时刻].any()):
                点火 += 1
            if bool(脑.上一拍[时刻[0]]):
                头点火 += 1
    return {"末高": 身.机身高度(), "最高": 最高, "歪": 身.机身歪了(),
            "前": float(身.数据.qpos[0] - 起[0]),
            "走": float(np.hypot(身.数据.qpos[0] - 起[0], 身.数据.qpos[1] - 起[1])),
            "点火": 点火, "头点火": 头点火}


def 测_起身(脑, 身):
    清脑(脑)
    身.摆成趴姿()
    身.走(0.5, None)
    起高 = 身.机身高度()
    r = 跑身体(脑, 身, 3.0)
    r["起手高"] = 起高
    return r


def 测_站住(脑, 身):
    """对照：把身体直接摆成站姿、**什么动作都不点** —— 应该倒（肌肉要靠皮层下令才绷得住）。"""
    清脑(脑)
    身.摆成站姿()
    身.走(0.5, None)
    return 跑身体(脑, 身, 3.0)


def 测_见红走(脑, 身):
    清脑(脑)
    身.摆成站姿()
    身.走(0.5, None)
    return 跑身体(脑, 身, 4.0, 图=主循环.红图("中"), 盯="前进1.2")


def 测_听响(脑, 身):
    清脑(脑)
    身.摆成站姿()
    身.走(0.5, None)
    return 跑身体(脑, 身, 4.0, 声=本能.听觉例子["响"](), 盯="原地踏步")


def 测_红加停(脑, 身):
    """眼前有红（本来该往前走），同时给一声「停」——该不该停得住。"""
    清脑(脑)
    身.摆成站姿()
    身.走(0.5, None)
    return 跑身体(脑, 身, 4.0, 图=主循环.红图("中"), 声=本能.听觉例子["停"](), 盯="前进1.2")


def 测_瘫掉(脑, 身):
    """连感觉都不给（对照：动作确实是皮层下的令）。"""
    清脑(脑)
    身.摆成站姿()
    return 跑身体(脑, 身, 1.5, 用感觉=False)


def 测_盯球(脑, 球方位角=-25.0, 球半径=0.05, 球横速=0.0, 秒数=4.0):
    """摆一个球，让眼睛自己走，返回眼睛末了朝哪、球末了停在视角哪。"""
    清脑(脑)
    w = 跟随.架好世界(球方位角=球方位角, 球高度=0.60,
                      球横向速度=球横速, 球半径=球半径)
    运起, 运宽 = 脑.运起, 脑.运宽
    偏 = []
    for _ in range(int(round(秒数 / 帧秒))):
        脑.一拍(图=w.看())
        力 = 运动.解码眼球发力(脑.亮[运起:运起 + 运宽])
        w.眼肌发力 = 力
        w.走眼睛(帧秒)
        w.走物体(帧秒)
        方, 仰 = w.眼里在哪(0)
        if 方 == 方 and abs(方) <= 45 and abs(仰) <= 35:
            偏.append(max(abs(方), abs(仰)))
    return {"末眼": w.眼球水平, "平均偏离": (sum(偏) / len(偏) if 偏 else float("nan"))}


def 跑一阶段(名, 条们, 身):
    t0 = time.time()
    脑 = 装阶段(条们)
    建好 = time.time() - t0
    r = {}
    r["起身"] = 测_起身(脑, 身)
    r["站住"] = 测_站住(脑, 身)
    r["见红走"] = 测_见红走(脑, 身)
    r["听响"] = 测_听响(脑, 身)
    r["红加停"] = 测_红加停(脑, 身)
    r["瘫掉"] = 测_瘫掉(脑, 身)
    r["盯球"] = 测_盯球(脑, 球方位角=-25.0, 球半径=0.05, 球横速=0.5, 秒数=5.0)
    r["本能条数"] = len(条们)
    r["建网秒"] = 建好
    r["总共秒"] = time.time() - t0
    return r


走路够 = 40      # 4 秒 = 200 拍，走路那串时刻里亮着 >= 40 拍才算"走起来了"
听力够 = 40      # 响声那 4 秒里，原地踏步那串时刻亮着 >= 40 拍
眼睛够 = 12.0

判据 = [
    ("自己站起来", lambda r: r["起身"]["末高"] > 0.20, "末高"),
    ("看见红往前走", lambda r: r["见红走"]["点火"] >= 走路够 and r["见红走"]["前"] > 0.30, "点火"),
    ("听见响动一动", lambda r: r["听响"]["点火"] >= 听力够, "点火"),
    ("红+停 停得住", lambda r: r["见红走"]["点火"] >= 走路够 and r["红加停"]["点火"] <= 走路够 // 4, "点火"),
    ("眼睛跟住球", lambda r: r["盯球"]["平均偏离"] <= 眼睛够, "平均偏离"),
]


def main():
    种子们 = 种子们默认
    if len(sys.argv) > 1 and sys.argv[1].strip():
        种子们 = [int(a) for a in sys.argv[1].split(",")]
    阶段, 账 = 造五阶段()
    print("=" * 100)
    print("本能一批一批加上去：每一阶段都重测全部行为")
