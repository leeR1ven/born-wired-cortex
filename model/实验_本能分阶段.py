"""实验_本能分阶段.py —— 一次只加一组本能，看能力是不是一批一批长出来的。

★ 用户 2026-09-15 的说法：
  "缺能力就加本能，本质上是上没有一次性加完所有所需本能，而不是一缺能力就加本能；
   如果一开始所有所需本能都加上了，就不需要缺能力就加本能连接。"

★ 这个实验就是把"本能是一批一批装上去的"变成数据。五个阶段，每一阶段都用**同一套
  随机背景连接**（同一个建网种子），只把本能表换成它的一个子集：

    阶段 A：只有运动库 —— 姿势 10 + 慢动作 4 + 各种走法 207 = 221 条（看得出它自己能做什么？）
    阶段 B：A + 平衡/起身那 6 条前提 + 反射表 4 条
    阶段 C：B + "看见红就走"那 6 条前提（视觉给一半、前额叶给一半）
    阶段 D：C + 听觉那 3 条前提（响→动一动、停→站住）
    阶段 E：D + 眼睛注视那 345 条（粗 9 + 细 14 + 刚动过 322）

  每一阶段都把**全部**行为重测一遍，回答两件事：
    · 新加的这一组，是不是真的长出了一个新能力；
    · 已经有的能力，有没有被弄坏。

命令：python 实验_本能分阶段.py [种子,种子,...]
"""
