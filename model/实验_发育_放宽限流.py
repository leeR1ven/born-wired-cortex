# -*- coding: utf-8 -*-
"""实验_发育_放宽限流.py —— 出生时没有的行为，能不能靠生活长出来；卡在哪一个参数上

★ 这是论文自己承认缺的那一个实验（4.3 与 4.6 第 1 条）。

★ 要证的事：一个**出生时跟走路毫无关系**的刺激（「低频响」这个声音；本能表里
  听觉一共只有三条规则，没有一条碰过走路），在"一边听它一边走路"地活过一段
  时间之后，能不能只靠它自己就把走路点起来。

★ 为什么这条路最干净：
  运动记忆区在出生时**不接收随机兴奋连接**（皮层连接_cortex_links.py 里
  不接收随机兴奋的区）。也就是说，声音在出生时**根本没有一条路**能走到走路那串
  时刻上。要让这个声音能点着走路，局部赫布规则必须**真长出一批新连接**。

★ 两条臂（同一个种子、同一个身体、同样的生活时长、同样的探测）：
  甲 论文默认：一次最多配对 4000，候选上限 50000，需要共激活次数 4，每步最多新建 200
  乙 只放宽"记性"：一次最多配对 40000，候选上限 4000000（其余一律不动，包括
     「同一对要反复见过 4 次才算数」这条生物学味道最重的规则）
  乙臂要回答的是：规则本身行不行？还是被"配对预算太小 + 候选表满了丢一半"卡死的？

★ 三个数（每 N 拍量一次）：
  ① 听觉 -> 走路那 15 个时刻 的**新连接条数**与权重和（结构长出来没有）
  ② 只放这个声音时，走路那 15 个时刻收到的**电流最大值**（过 1.0 才点得着）
     对照：本能给的是 0.80（视觉:中有红那一半）
  ③ 行为探测：清空皮层 -> 黑屏 + 只放这个声音 -> 8 拍里走路那串亮了几拍

命令： python 实验_发育_放宽限流.py [种子] [生活秒数]
"""
from __future__ import annotations

import sys

import numpy as np

import 皮层连接_cortex_links as 皮层连接
import 听觉前处理_auditory_preprocess as 听觉
import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 身体_go2 as 身体
import 运动记忆区_motor_memory as 运动记忆

图高, 图宽 = 主循环.图高, 主循环.图宽
帧秒 = 主循环.帧秒
探头 = 8
走路动作 = "前进1.2"


def 红图():
    图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
    图[:, 图宽 // 3: 2 * 图宽 // 3, 0] = 255
    return 图


黑图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)


def 走路时刻们(脑):
    return (脑.网.区起点["运动记忆"]
            + np.asarray(运动记忆.时刻们(走路动作), dtype=np.int64))


def 只放声音时皮层亮成什么样(脑, 声):
    网 = 脑.网
    亮 = np.zeros(网.总数, dtype=bool)
    亮[脑.听起: 脑.听起 + 脑.听宽] = np.asarray(
        听觉.网.前向传播(听觉.频谱转信号(声)), dtype=bool)
    return 亮


def 量结构(脑):
    """临时表里 听觉 -> 走路那 15 个时刻 的新连接"""
    网 = 脑.网
    时 = set(int(x) for x in 走路时刻们(脑))
    条 = 0
    权和 = 0.0
    for s, d in 网._待出.items():
        s = int(s)
        if not (脑.听起 <= s < 脑.听起 + 脑.听宽):
            continue
        for t, w in d.items():
            if int(t) in 时:
                条 += 1
                权和 += float(w)
    return 条, 权和


def 量电流(脑, 声):
    网 = 脑.网
    亮 = 只放声音时皮层亮成什么样(脑, 声)
    电流 = 网._兴奋电流(亮) - 网._抑制电流(亮)
    return float(电流[走路时刻们(脑)].max())


def 探行为(脑, 身, 声, 次数=5):
    """清空皮层，黑屏 + 只放这个声音，8 拍里走路那串亮几拍"""
    统 = 0
    for _ in range(次数):
        脑.亮[:] = False
        脑.上一拍[:] = False
        亮拍 = 0
        for _ in range(探头):
            脑.一拍(图=黑图, 声=声, 身=身)
            身.步进(脑.肌肉发力())
            if 脑.上一拍[走路时刻们(脑)].any():
                亮拍 += 1
        统 += 1 if 亮拍 >= 6 else 0
    return 统


def 跑一臂(名, 种子, 生活拍数, 每多少拍, 覆盖):
    旧 = {k: getattr(皮层连接, k) for k in 覆盖}
    for k, v in 覆盖.items():
        setattr(皮层连接, k, v)
    print("\n" + "=" * 112)
    print("【%s】一次最多配对=%d，候选上限=%d，需要共激活次数=%d，每步最多新建=%d"
          % (名, 皮层连接.一次最多配对, 皮层连接.候选上限,
             皮层连接.需要共激活次数, 皮层连接.每步最多新建))
    print("=" * 112)
    本能.建网种子 = 种子
    脑 = 主循环.脑(学=True, 说=False)
    身 = 身体.身体()
    身.摆成站姿()
    身.走(0.5, None)
    声 = np.asarray(本能.听觉例子["低频响"](), dtype=np.float64)
    红 = 红图()
    出 = []
    print("   拍   听->走路新边  权和   走路时刻最大电流   出生/现在 行为探测（5 次里点着几次）")
    print("-" * 112)
    for k in range(生活拍数 + 1):
        if k % 每多少拍 == 0:
            条, 权和 = 量结构(脑)
            电 = 量电流(脑, 声)
            点 = 探行为(脑, 身, 声) if k % (每多少拍 * 4) == 0 else None
            出.append((k, 条, 权和, 电, 点))
            print("  %5d %12d %8.3f %14.3f   %s"
                  % (k, 条, 权和, 电, "-" if 点 is None else "%d/5" % 点), flush=True)
        if k >= 生活拍数:
            break
        脑.一拍(图=红, 声=声, 身=身)
        身.步进(脑.肌肉发力())
    for k, v in 旧.items():
        setattr(皮层连接, k, v)
    return 出


def main():
    种子 = int(sys.argv[1]) if len(sys.argv) > 1 else 20260914
    生活秒 = float(sys.argv[2]) if len(sys.argv) > 2 else 40.0
    每多少拍 = int(sys.argv[3]) if len(sys.argv) > 3 else 200
    生活拍数 = int(round(生活秒 / 帧秒))
    默认 = {"一次最多配对": 4000, "候选上限": 50000, "需要共激活次数": 4, "每步最多新建": 200}
    放宽 = {"一次最多配对": 40000, "候选上限": 4000000, "需要共激活次数": 4, "每步最多新建": 300}
    print("=" * 112)
    print("发育实验：出生时不会的行为，靠一边听一边走路地活着，能不能长出来")
    print("  声音 = 低频响（本能表里没有任何一条规则碰过它）")
    print("  种子 %d；生活 %.0f 秒 = %d 拍；每 %d 拍量一次结构/电流，每 4 个量点探一次行为"
          % (种子, 生活秒, 生活拍数, 每多少拍))
    print("=" * 112)
    甲 = 跑一臂("甲 论文默认参数", 种子, 生活拍数, 每多少拍, 默认)
    乙 = 跑一臂("乙 只放宽记性", 种子, 生活拍数, 每多少拍, 放宽)
    再宽 = {"一次最多配对": 100000, "候选上限": 4000000,
            "需要共激活次数": 1, "每步最多新建": 1000}
    丙 = 跑一臂("丙 再放宽「见过几次」", 种子, 生活拍数, 每多少拍, 再宽)
    print()
    print("=" * 112)
    print("【两臂对照】")
    for 名, 出 in (("甲 默认", 甲), ("乙 放宽记性", 乙), ("丙 再放宽次数", 丙)):
        if not 出:
            continue
        头 = 出[0]
        尾 = 出[-1]
        探 = [x for x in 出 if x[4] is not None]
        print("  %s：起点 新边 %d（权和 %.3f，最大电流 %.3f）；终点 新边 %d（权和 %.3f，最大电流 %.3f）"
              % (名, 头[1], 头[2], 头[3], 尾[1], 尾[2], 尾[3]))
        print("        行为探测：%s" % "、".join("%d拍时 %d/5" % (x[0], x[4]) for x in 探))
    return 甲, 乙, 丙


if __name__ == "__main__":
    甲, 乙, 丙 = main()