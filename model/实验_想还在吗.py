# -*- coding: utf-8 -*-
"""实验_想还在吗.py —— 刺激撤掉以后，皮层里那个「想法」还在不在？

★ 为什么又要重做一版（2026-09-15 晚）
  上一版（实验_刺激撤掉还走吗.py）量到「红撤掉以后照样走满 2 秒」。
  但那条**证明不了任何事**：走路的动作自己就是一条转圈的链子（19.10.4），
  点着一次就永远走，跟眼前有没有红没关系。所以「还走」只是惯性。

★ 这一版把惯性掐掉，只问一句话：
    「红」这个想法，在红撤掉以后，还在皮层里吗？还能重新点着走路吗？

  做法：每一幕跑 3 秒
     幕 A 一直红（基准）
     幕 B 红 0~0.5 秒，之后全黑
     幕 C 红 0~0.5 秒，之后全黑；到 1.0 秒那一拍，把「运动记忆」整段清零一次
     幕 D 一直黑；到 1.0 秒那一拍，同样把「运动记忆」整段清零一次（对照）
     幕 E 一直黑，也不打断（对照：什么都不给本来就不该动）

  ★ 关键：幕 C 打断之后如果走路**自己重新点着了**，那只能是因为皮层里别的地方
    还留着「红」这件事（画面每拍都被黑屏覆盖掉了，视觉皮层自己不可能亮）。
    幕 D 是同一套手法、只是从没见过红 —— 它必须点不着，否则说明是打断本身点着的。

★ 同时每一拍都记三样：
    视觉:中有红 / 前额叶:看着红 / 运动记忆:前进1.2（那一串时刻）
  逐拍明细写到 日志_想还在吗_轨迹.csv，给画图用。

命令：python 实验_想还在吗.py [种子,种子,...]
"""
from __future__ import annotations

import io
import os
import pathlib
import sys

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 身体_go2 as 身体
import 运动记忆区_motor_memory as 运动记忆

帧秒 = 主循环.帧秒
根 = pathlib.Path(__file__).resolve().parent
种子们默认 = [20260914, 20260915, 20260916, 20260917, 20260918]
红图 = 主循环.红图("中")
黑图 = np.zeros_like(红图)
名字块 = ["视觉:中有红", "前额叶:看着红"]

#       名                    红给到第几秒   第几秒打断运动记忆   总长
幕们 = [
    ("A 一直红",                3.0,        None, 3.0),
    ("B 红0.5秒后全黑",         0.5,        None, 3.0),
    ("C 同B+1.0秒打断运动记忆",  0.5,        1.0,  3.0),
    ("D 一直黑+1.0秒同样打断",   0.0,        1.0,  3.0),
    ("E 一直黑(不给红也不打断)",  0.0,        None, 3.0),
]


def 取块(脑, 块名):
    名字 = 本能.读名字()
    区, 名 = 块名.split(":", 1)
    起 = 脑.网.区起点[区.strip()]
    return 起 + np.asarray(名字[区.strip()][名.strip()], dtype=np.int64)


def 一幕(脑, 身, 红到秒, 打断于, 秒):
    身.摆成站姿()
    身.走(0.5, None)
    脑.亮[:] = False
    脑.上一拍[:] = False
    运记段 = 脑.段["运动记忆"]
    走 = 脑.网.区起点["运动记忆"] + np.asarray(运动记忆.时刻们("前进1.2"), dtype=np.int64)
    块 = {b: 取块(脑, b) for b in 名字块}
    打断拍 = None if 打断于 is None else int(round(打断于 / 帧秒))
    红到 = int(round(红到秒 / 帧秒))
    总拍 = int(round(秒 / 帧秒))
    前段 = 脑.段["前额叶"]
    轨迹 = []
    for k in range(总拍):
        图 = 红图 if k < 红到 else 黑图
        脑.一拍(图=图, 身=身)
        身.步进(脑.肌肉发力())
        动 = bool(脑.上一拍[走].any())
        视数 = int(np.count_nonzero(脑.上一拍[块["视觉:中有红"]]))
        前数 = int(np.count_nonzero(脑.上一拍[块["前额叶:看着红"]]))
        轨迹.append(dict(
            幕=k * 帧秒, 走=int(动),
            视觉红=int(视数 > 0), 视觉红数=视数, 视觉红块=len(块["视觉:中有红"]),
            前额叶红=int(前数 > 0), 前额叶红数=前数, 前额叶红块=len(块["前额叶:看着红"]),
            前额叶亮=int(np.count_nonzero(脑.上一拍[前段])),
            高度=float(身.机身高度()),
        ))
        if 打断拍 is not None and k == 打断拍:
            脑.亮[运记段] = False
            脑.上一拍[运记段] = False
    return dict(轨迹=轨迹)


def main():
    种子们 = 种子们默认
    if len(sys.argv) > 1 and sys.argv[1].strip():
        种子们 = [int(a) for a in sys.argv[1].split(",")]
    print("=" * 100)
    print("红撤掉以后，皮层里那个「想法」还在不在？（每幕 3 秒；1.0 秒那一拍打断运动记忆）")
    print("=" * 100, flush=True)
    身 = 身体.身体()
    出 = []
    全部轨迹 = []
    for s in 种子们:
        本能.建网种子 = s
        脑 = 主循环.脑(学=False, 说=False)
        for 名, 红到秒, 打断于, 秒 in 幕们:
            r = 一幕(脑, 身, 红到秒, 打断于, 秒)
            轨迹 = r["轨迹"]
            for t in 轨迹:
                t["种子"] = s
                t["幕名"] = 名
            全部轨迹 += 轨迹
            前1 = [t for t in 轨迹 if 0.5 <= t["幕"] < 1.0]
            后 = [t for t in 轨迹 if t["幕"] >= 1.5]
            出.append(dict(种子=s, 幕=名, r=r, 轨迹=轨迹))
            def 均(列, 们):
                return (sum(t[列] for t in 们) / len(们)) if 们 else float("nan")
            print("种子 %d  %-24s | 0.5~1.0秒：走路 %2d/%d 视觉红 %3.0f/%d 前额叶红 %4.0f/%d"
                  " | 1.5秒后：走路 %2d/%d 视觉红 %3.0f/%d 前额叶红 %4.0f/%d"
                  % (s, 名,
                     sum(t["走"] for t in 前1), len(前1),
                     均("视觉红数", 前1), 前1[0]["视觉红块"] if 前1 else 0,
                     均("前额叶红数", 前1), 前1[0]["前额叶红块"] if 前1 else 0,
                     sum(t["走"] for t in 后), len(后),
                     均("视觉红数", 后), 后[0]["视觉红块"] if 后 else 0,
                     均("前额叶红数", 后), 后[0]["前额叶红块"] if 后 else 0), flush=True)
    print("\n" + "=" * 100)
    print("【汇总】打断之后那 2 秒（1.0 秒 ~ 3.0 秒）")
    print("%-26s | %-16s | %-16s | %-16s" % ("幕", "走路点着", "视觉:中有红", "前额叶:看着红"))
    print("-" * 100)
    print("%-26s | %-14s | %-14s | %-18s | %-18s"
          % ("幕", "0.5~1.0秒 走路", "1.0秒后 走路", "1.0秒后 视觉红细胞数", "1.0秒后 前额叶红细胞数"))
    print("-" * 104)
    for 名, _, _, _ in 幕们:
        行 = [x for x in 出 if x["幕"] == 名]
        中 = [t for x in 行 for t in x["轨迹"] if 0.5 <= t["幕"] < 1.0]
        后 = [t for x in 行 for t in x["轨迹"] if t["幕"] > 1.0]
        print("%-26s | %-14s | %-14s | %-18s | %-18s"
              % (名,
                 "%d/%d 拍" % (sum(t["走"] for t in 中), len(中)),
                 "%d/%d 拍" % (sum(t["走"] for t in 后), len(后)),
                 "%.0f / %d 个" % (sum(t["视觉红数"] for t in 后) / max(1, len(后)), 后[0]["视觉红块"] if 后 else 0),
                 "%.0f / %d 个" % (sum(t["前额叶红数"] for t in 后) / max(1, len(后)), 后[0]["前额叶红块"] if 后 else 0)))
    # 逐拍明细
    p = 根 / os.environ.get("轨迹名", "日志_想还在吗_轨迹.csv")
    with io.open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write("种子,幕名,秒,走路,视觉红,视觉红数,视觉红块,前额叶红,前额叶红数,前额叶红块,前额叶亮,高度\n")
        for t in 全部轨迹:
            f.write("%d,%s,%.2f,%d,%d,%d,%d,%d,%d,%d,%d,%.4f\n"
                    % (t["种子"], t["幕名"], t["幕"], t["走"],
                       t["视觉红"], t["视觉红数"], t["视觉红块"],
                       t["前额叶红"], t["前额叶红数"], t["前额叶红块"],
                       t["前额叶亮"], t["高度"]))
    print("\n逐拍明细：%s" % p)
    return 出


if __name__ == "__main__":
    出 = main()