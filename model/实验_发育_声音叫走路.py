# -*- coding: utf-8 -*-
"""实验_发育_声音叫走路.py —— 用「前额叶成环 + 多巴胺」教模型：听到低频响 → 走路

★ 用户 2026-09-16 交代的原理（原话大意）：
   · 模型还没形成复杂网络，一段神经元被激活后亮一下就没了，没法循环持续激活，
     所以「声音」和「走路」永远碰不到一起。要**自动给前额叶每一段神经元首尾接成环**，
     让它亮起来之后赖着不走（就像以前那个文字网络）。
   · 再加一个**多巴胺区**：它一亮，这一拍「刚刚先后亮起来的」神经元之间的连接
     **当场连起来/加强**（不用再等赫布那套"反复见过几次"）。
   · 于是可以像训练动物一样：一边放声音、一边让它走路，走对了就摸它（点亮多巴胺），
     下次再放声音，它自己就会想起来走路。

★ 四步（像教小狗）：
   ① 出生     趴着 + 只放声音            → 预期：一动不动
   ② 天生会的 站着 + 眼前有红             → 预期：自己往前走（这是本能，跟声音无关）
   ③ 教学     站着 + 眼前有红 + 同时响声音 + 点亮多巴胺
   ④ 考试     重新趴下 + 黑屏 + 只放声音   → 预期：自己先站起来，然后走

命令：python 实验_发育_声音叫走路.py
"""
from __future__ import annotations

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 运动记忆区_motor_memory as 运动记忆
import 皮层连接_cortex_links as 皮层连接
import 身体_go2 as 身体

图高, 图宽 = 主循环.图高, 主循环.图宽
黑图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
红图 = 主循环.红图("中")
动作名 = "前进1.2"

出生拍数 = 50
对照拍数 = 50
教学拍数 = 200
考试拍数 = 150


def main():
    名字 = 本能.读名字()
    脑 = 主循环.脑(学=True, 说=False)
    身 = 身体.身体()
    网 = 脑.网

    运记起 = 网.区起点["运动记忆"]
    走 = 运记起 + 运动记忆.时刻们(动作名)
    走起 = int(走[0])
    声 = np.asarray(本能.听觉例子["低频响"](), dtype=np.float64)

    前起, 前宽 = 网.区起点["前额叶"], 网.区宽["前额叶"]
    听起, 听宽 = 网.区起点["听觉"], 网.区宽["听觉"]
    声段 = 听起 + np.asarray(名字["听觉"]["低频响"], dtype=np.int64)

    print("=" * 104)
    print("走路「%s」= 运动记忆区 %d 个时刻神经元，入口 = 第 %d 号（点亮入口，整串自己走）"
          % (动作名, 走.size, 走起))
    print("声音「低频响」= 听觉区 %d 个细胞；前额叶「听到低频响」那一段 1097 个" % 声段.size)
    print("多巴胺：一次「奖励」给一个目标细胞一共 %.2f 的电流（摊平到每一根连接上）"
          % 皮层连接.多巴胺强化权重)
    print("=" * 104)

    看动作 = [n for n in ("前进1.2", "原地踏步", "站姿", "站起来", "坐下", "蹲", "左转1.5", "右转0.75")
              if n in 运动记忆.时刻段]
    入口 = {n: 运记起 + 运动记忆.起手(n) for n in 看动作}

    def 谁在跑():
        return "、".join(n for n in 看动作 if 脑.亮[入口[n]]) or "没动"

    def 走链():
        return int(脑.亮[走].sum())

    def 走到哪():
        return int(np.nonzero(脑.亮[走])[0][0]) if 走链() else -1

    表头 = "      拍   整片亮  走路链  听觉亮   前额叶亮     机身高      路程       走路链在跑吗  哪些动作在跑"

    def 走一段(拍数, 图, 声, 多巴胺=False, 每隔=15, 报点火=False):
        脑.多巴胺亮 = 多巴胺
        上一点 = 身.数据.qpos[:2].copy()
        路程 = 0.0
        最高 = 身.机身高度()
        点火 = 0
        第一拍电 = None
        for k in range(1, 拍数 + 1):
            头上一拍亮 = bool(脑.上一拍[走起])
            脑.一拍(图=图, 声=声, 身=身)
            if 脑.亮[走起] and not 头上一拍亮:
                点火 += 1
            if k == 1:
                电1 = 网._兴奋电流(脑.亮) - 网._抑制电流(脑.亮)
                第一拍电 = float(电1[走起])
            身.步进(脑.肌肉发力())
            p = 身.数据.qpos[:2]
            路程 += float(np.hypot(p[0] - 上一点[0], p[1] - 上一点[1]))
            上一点 = p.copy()
            最高 = max(最高, 身.机身高度())
            if k % 每隔 == 0:
                print("    %4d %8d %7d %8d %10d   %6.3f 米  %8.3f 米   %-10s %s"
                      % (k, int(脑.亮.sum()), 走链(),
                         int(脑.亮[声段].sum()),
                         int(脑.亮[前起:前起 + 前宽].sum()),
                         身.机身高度(), 路程,
                         ("时刻 %d" % 走到哪()) if 走链() else "没动", 谁在跑()), flush=True)
        return 路程, 最高, 点火, 第一拍电

    # ---------------- ① 出生 ----------------
    身.摆成趴姿()
    身.走(0.3, None)
    print("\n[1] 出生：趴在地上，只放声音、黑屏，走 %d 拍（预期：一动不动）" % 出生拍数)
    print(表头)
    路程, 最高, _, _ = 走一段(出生拍数, 黑图, 声)
    print("    → 挪了 %.3f 米，最高只有 %.3f 米（趴着的高度）：听声音它不会走" % (路程, 最高))

    # ---------------- ② 天生就会的 ----------------
    身.摆成站姿()
    身.走(0.5, None)
    脑.亮[:] = False
    脑.上一拍[:] = False
    print("\n[2] 天生就会的：站着，眼前有一块红、不放声音，走 %d 拍（预期：自己往前走）" % 对照拍数)
    print(表头)
    路程, 最高, _, _ = 走一段(对照拍数, 红图, None)
    print("    → 挪了 %.3f 米：这是出生就写好的本能（看红 → 走），还没学过声音" % 路程)

    # ---------------- ③ 教学 ----------------
    身.摆成站姿()
    身.走(0.5, None)
    脑.亮[:] = False
    脑.上一拍[:] = False
    print("\n[3] 教学：站着，眼前有一块红 + 同时响声音 + 点亮多巴胺，走 %d 拍" % 教学拍数)
    print(表头)
    路程, 最高, 点火, _ = 走一段(教学拍数, 红图, 声, 多巴胺=True)
    出生条 = 网.统计.get("出生兴奋连接", 0)
    print("    → 「走路入口刚亮」的瞬间 %d 次；学出来的连接：%d → %d（真长了 %d 根）"
          % (点火, 出生条, 网._兴奋键.size, 网._兴奋键.size - 出生条))
    电 = 网._兴奋电流(脑.亮) - 网._抑制电流(脑.亮)
    print("    → 教学最后那一拍：走路入口收到的电流 %.3f（门槛 1.0）" % float(电[走起]))

    # ---------------- ④ 考试 ----------------
    脑.多巴胺亮 = False
    脑.亮[:] = False
    脑.上一拍[:] = False
    身.摆成趴姿()
    身.走(0.3, None)
    print("\n[4] 考试：把皮层全清空、重新趴下，黑屏、只放声音，走 %d 拍" % 考试拍数)
    print(表头)
    路程, 最高, _, 第一拍电 = 走一段(考试拍数, 黑图, 声)
    print("    → 考试第一拍：走路入口收到的电流 %.3f（门槛 1.0）" % 第一拍电)
    print("    → 考试结果：挪了 %.3f 米；最高站到 %.3f 米；机身歪 %.0f 度"
          % (路程, 最高, 身.机身歪了()))


if __name__ == "__main__":
    main()