# -*- coding: utf-8 -*-
"""实验_眼睛跟随.py —— 视角中心自己转过去盯住东西（全是本能连接在拉，没有一行"让眼睛转"的代码）。

★ 用户 2026-09-15："接下来做视角中心自动跟随移动物体的本能连接。"

★ 现在有两条路一起干这件事（都是本能连接，见 本能工具_instincts.py）：

  ① 「那个方向有东西」→ 转眼看它（本能表 零之二、注视）
     源 = 视觉:看球在某方向（视觉网**第 4 层**，压缩完的整体感觉，拿大球标定）
  ② 「那个方向**刚刚**有东西」→ 转眼看它（本能表 零之三、东西刚动过）
     源 = 视觉细节:细_某方向（视觉网**第 1 层**，没压缩的细节，拿最小的东西标定）
     名字 → 痕迹（隔一拍）→ 变化 = 名字亮、上一拍的痕迹不亮
     这就是用户说的 A → a → e → f："把时间上连续但弱的信号，转换成某一刻的强的信号"。

  ★ 为什么要第 ② 条（实测，见 实验_前几层看得见小东西吗.py）：
    第 4 层对小东西是瞎的 —— 一个格子那么大的小球，第 4 层只挑得出 0~8 个细胞，
    "正中"方向直接是 0 个；第 1 层能挑出 5~11 个，而且正好落在小球那一列。

★ 命令

    python 实验_眼睛跟随.py 不动            # 大球摆在右边 25 度不动
    python 实验_眼睛跟随.py 不动 -30        # 摆在左边 30 度
    python 实验_眼睛跟随.py 横着飘          # 大球从左边飘到右边
    python 实验_眼睛跟随.py 竖着飘          # 大球从下往上飘
    python 实验_眼睛跟随.py 小不动          # **小球**（一个格子那么大）摆着不动
    python 实验_眼睛跟随.py 小横着飘        # **小球**从左边飘到右边
    python 实验_眼睛跟随.py 小突然出现      # 眼前本来空的，第 2 秒**小球**冒出来
    python 实验_眼睛跟随.py 空场            # 什么都不放（对照：眼睛该一动不动）

★ 这一版为了先把"眼睛"这一件事看清楚：**身体站着不动**（不跑身体的物理），
  只有眼球和球在动。身体那套（站起来、走路、平衡）在 MuJoCo 那边单独验。
"""
from __future__ import annotations

import sys

import numpy as np

import 本能工具_instincts as 本能
import 运动输出区_motor_output as 运动
import 世界_world as 世界
import 主循环_完整的一拍 as 主循环

帧秒 = 1.0 / 50.0
观察距离 = 3.0
看球名 = ["看球在正中", "看球在右1", "看球在右2", "看球在右3",
        "看球在左1", "看球在左2", "看球在左3",
        "看球在上1", "看球在上2", "看球在下1"]
细名 = list(本能.细节名字们)


def 架好世界(球方位角=25.0, 球高度=0.60, 球横向速度=0.0, 球竖直速度=0.0,
          球半径=0.30, 先不放球=False):
    """摆一个站着不动的身体，眼前放一个红球（可以给它一个速度让它自己飘）。"""
    w = 世界.世界()
    w.摆成站着()
    w.清空物体()
    if not 先不放球:
        放球(w, 球方位角, 球高度, 球半径, 球横向速度, 球竖直速度)
    return w


def 放球(w, 球方位角, 球高度, 球半径, 球横向速度, 球竖直速度):
    角 = np.radians(球方位角)
    w.加物体(观察距离 * np.cos(角), 观察距离 * np.sin(角), 球高度, 球半径,
            (230, 30, 30), 速度=(0.0, 球横向速度, 球竖直速度))


世界_用 = None
空画面 = None
名字 = None
段 = {}


def 亮成几成(块列表, 亮拍):
    """这些名字里，哪几个亮到一半以上。"""
    出 = []
    for 名, 块 in 块列表:
        if 块.size and 亮拍[块].mean() >= 0.5:
            出.append(名)
    return "、".join(出) if 出 else "（都不亮）"


def 跑(事="不动", 球方位角=25.0, 球高度=0.60, 球横速=0.0, 球竖速=0.0,
      秒数=6.0, 学=False, 说=True, 每多少拍报一次=10, 球半径=0.30, 出现时刻=None):
    global 世界_用, 空画面, 名字, 段
    先不放球 = 出现时刻 is not None
    世界_用 = 架好世界(球方位角, 球高度, 球横速, 球竖速, 球半径, 先不放球)
    名字 = 本能.读名字()
    空画面 = 本能._看出去的(本能._空画面())

    大脑 = 主循环.脑(学=学, 说=False)
    运起 = 大脑.网.区起点["运动"]
    运宽 = 大脑.网.区宽["运动"]
    段 = {"粗": [(n, 大脑.网.区起点["视觉"] + np.asarray(名字["视觉"][n], dtype=np.int64))
                for n in 看球名 if n in 名字["视觉"]],
          "细": [(n, 大脑.网.区起点["视觉细节"] + np.asarray(名字["视觉细节"][n], dtype=np.int64))
                for n in 细名 if n in 名字["视觉细节"]],
          "动": [(d[3:], 大脑.网.区起点["视觉运动"] + np.asarray(名字["视觉运动"]["变化_" + d], dtype=np.int64))
                for d in 细名 if "变化_" + d in 名字["视觉运动"]]}

    print("=" * 108)
    print("【%s】球：方位 %+.0f 度、高 %.2f 米、半径 %.2f 米；横速 %+.2f、竖速 %+.2f 米/秒；"
          "眼睛一开始朝 %+.0f 度" % (事, 球方位角, 球高度, 球半径, 球横速, 球竖速, 世界_用.眼球水平))
    print("本能连接 %s 根；皮层 %s 个神经元" % (format(大脑.本能条数, ","), format(大脑.网.总数, ",")))
    print("-" * 108)
    print("%6s | %-14s | %-14s | %-13s | %-22s | %s"
          % ("时间", "球在视角里", "眼睛朝哪", "眼肌档(右左上下)", "第4层名字(看球在…)", "第1层名字(细_…)｜刚动过"))

    记 = []
    for k in range(int(round(秒数 / 帧秒))):
        if 出现时刻 is not None and k == int(round(出现时刻 / 帧秒)):
            放球(世界_用, 球方位角, 球高度, 球半径, 球横速, 球竖速)
        图 = 世界_用.看()
        大脑.一拍(图=图)
        力 = 运动.解码眼球发力(大脑.亮[运起:运起 + 运宽])
        世界_用.眼肌发力 = 力
        世界_用.走眼睛(帧秒)
        世界_用.走物体(帧秒)
        方, 仰 = 世界_用.眼里在哪(0)
        档 = np.rint(力 * 运动.每块眼球肌肉神经元).astype(int)
        亮拍 = 大脑.上一拍
        记.append((k * 帧秒, 方, 仰, 世界_用.眼球水平, 世界_用.眼球竖直,
                  int(档[0]), int(档[1]), int(档[2]), int(档[3])))
        if 说 and k % 每多少拍报一次 == 0:
            变 = [n for n, b in 段["动"] if 亮拍[b].any()]
            球说 = ("左右 %+5.1f 上下 %+4.1f" % (方, 仰)) if 方 == 方 else "     （还没出现）    "
            print("%5.2fs | %s | 左右 %+5.1f 上下 %+4.1f | %2d/%2d/%2d/%2d      | %-22s | %s%s"
                  % (k * 帧秒, 球说, 世界_用.眼球水平, 世界_用.眼球竖直,
                     记[-1][5], 记[-1][6], 记[-1][7], 记[-1][8],
                     亮成几成(段["粗"], 亮拍), 亮成几成(段["细"], 亮拍),
                     ("　｜刚动过：" + "、".join(变)) if 变 else ""))

    方, 仰 = 世界_用.眼里在哪(0)
    print("-" * 108)
    if 方 != 方:                      # nan = 这个场景里根本没有球
        print("末了：眼前自始至终没有球；眼睛朝 左右 %+.1f 度、上下 %+.1f 度"
              % (世界_用.眼球水平, 世界_用.眼球竖直))
    else:
        print("末了：球在视角里 左右 %+.1f 度、上下 %+.1f 度；眼睛朝 左右 %+.1f 度、上下 %+.1f 度"
              % (方, 仰, 世界_用.眼球水平, 世界_用.眼球竖直))
    偏 = [max(abs(r[1]), abs(r[2])) for r in 记 if abs(r[1]) <= 45 and abs(r[2]) <= 35]
    if 偏:
        print("球离视线中心：平均 %.1f 度，最远 %.1f 度（0 = 正好盯着；只算球还在视野里的时候）"
              % (sum(偏) / len(偏), max(偏)))
    return 记


def main():
    事 = sys.argv[1] if len(sys.argv) > 1 else "不动"
    学 = "学" in sys.argv
    if 事 == "不动":
        角 = float(sys.argv[2]) if len(sys.argv) > 2 and sys.argv[2][0] in "+-0123456789." else 25.0
        跑("大球不动", 球方位角=角, 秒数=4.0, 学=学)
    elif 事 == "横着飘":
        跑("大球从左边飘到右边", 球方位角=-25.0, 球横速=0.5, 秒数=5.0, 学=学)
    elif 事 == "竖着飘":
        跑("大球从下往上飘", 球方位角=0.0, 球高度=0.35, 球竖速=0.15, 秒数=8.0, 学=学)
    elif 事 == "小不动":
        角 = float(sys.argv[2]) if len(sys.argv) > 2 and sys.argv[2][0] in "+-0123456789." else 25.0
        跑("小球不动", 球方位角=角, 球半径=0.05, 秒数=4.0, 学=学)
    elif 事 == "小横着飘":
        跑("小球从左边飘到右边", 球方位角=-25.0, 球半径=0.05, 球横速=0.5, 秒数=5.0, 学=学)
    elif 事 == "小突然出现":
        跑("小球突然出现在右边 20 度", 球方位角=20.0, 球半径=0.05,
           出现时刻=2.0, 秒数=5.0, 学=学)
    elif 事 == "空场":
        跑("什么都没有", 球方位角=0.0, 球半径=0.05, 出现时刻=999.0, 秒数=3.0, 学=学)
    else:
        print(__doc__)


if __name__ == "__main__":
    main()
