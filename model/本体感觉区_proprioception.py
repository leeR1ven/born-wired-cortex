"""本体感觉区_proprioception.py —— 真·本体感觉：关节和肌肉那一路。

★ 这一片只管什么（2026-09-15 拆的）

  只放**身体真的能感觉到**的关节那一路：12 个关节角 + 12 个关节角速度。
  以前这里混着机身高度、前后速度、左右速度（身体其实没有传感器能感觉到它们，
  是算出来的），还有倾角、角速度（那是耳石/前庭那一路）—— 都拆到别的区去了：
    · 倾角 / 角速度        → 平衡感觉区_balance.py
    · 机身高度 / 前后速度 / 左右速度 → 机身状态区_bodystate.py

★ 12 个关节是哪 12 个

  腿1/2/3 = 左前 髋/大腿/小腿，腿4/5/6 = 右前，腿7/8/9 = 左后，腿10/11/12 = 右后
  （和 身体_go2.py 的 12 块肌肉一一对应；"角度"是相对站姿的偏差）
  速度写的是角速度，乘 8 倍再截到 -1~1，所以"走得快"就是大档。

自检：python 本体感觉区_proprioception.py
"""
from __future__ import annotations

import numpy as np

from 感觉区_共同 import 每档, 每特征细胞, 调谐感觉区

特征名 = (["腿%d角度" % (i + 1) for i in range(12)]
         + ["腿%d角速度" % (i + 1) for i in range(12)])

本区 = 调谐感觉区("本体感觉", 特征名)
特征数 = 本区.特征数
输出层数量 = 本区.输出层数量
总数 = 本区.总数
情况 = 本区.情况
块 = 本区.块
状态转激活 = 本区.状态转激活
解码特征 = 本区.解码特征
皮层 = 本区.皮层


# ================= 名字：身体摆成什么样 =================
# "蜷着"= 大腿往前折（正）+ 小腿收到最紧（负）。趴着的时候四条腿都是这样：
#   实测 趴姿：大腿 +0.75、小腿 -0.92；站姿：两个都接近 0（偏差 0.01~0.08，走负半）。
# 走路的时候大腿往负、小腿往正（正相反），所以不会误触发 —— 实测跑完 221 个动作、
# 3576 拍，只有「趴下去」和「站起来」会命中（这两个本来就该命中）。
本区.加情况("左前腿蜷着", 块("腿2角度", +1, 8, 8), 块("腿3角度", -1, 9, 9))
本区.加情况("右前腿蜷着", 块("腿5角度", +1, 8, 8), 块("腿6角度", -1, 9, 9))
本区.加情况("左后腿蜷着", 块("腿8角度", +1, 8, 8), 块("腿9角度", -1, 9, 9))
本区.加情况("右后腿蜷着", 块("腿11角度", +1, 8, 8), 块("腿12角度", -1, 9, 9))
# 「趴着」= 两条前腿都蜷着（后腿也一样，但前腿这两条就已经够分得开了）
本区.加情况("趴着", 情况["左前腿蜷着"], 情况["右前腿蜷着"])
# 四条腿全蜷着 = 更严格的"趴着"
本区.加情况("四条腿都蜷着", 情况["左前腿蜷着"], 情况["右前腿蜷着"],
            情况["左后腿蜷着"], 情况["右后腿蜷着"])


def 读身体(身):
    """从真身体上读出这 24 个特征（每个 -1~1）。"""
    return np.concatenate([
        np.clip(身.关节偏差() / 1.0, -1, 1),      # 12 个腿关节角偏差
        np.clip(身.关节角速度() / 8.0, -1, 1),     # 12 个腿关节角速度
    ])


if __name__ == "__main__":
    本区.自检()
    零 = np.zeros(特征数)
    a = 零.copy(); a[1] = 0.75; a[2] = -0.92       # 左前腿蜷着
    b = 零.copy(); b[1] = 0.80; b[2] = -0.90       # 再蜷一点点
    c = 零.copy(); c[1] = -0.20; c[2] = -0.60      # 左前腿另一种姿势
    重 = lambda x, y: len(set(皮层(x)) & set(皮层(y))) / max(len(set(皮层(x)) | set(皮层(y))), 1)
    print("\n  相近姿势（0.75 vs 0.80）重叠 %.0f%%  —— 要像" % (重(a, b) * 100))
    print("  别的姿势（-0.2/-0.6）重叠 %.0f%%  —— 要不像" % (重(a, c) * 100))
