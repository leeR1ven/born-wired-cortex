声道数 = 1          # 1 = 单声道；2 = 左右声道（以后做立体声时改成 2）
频带数 = 1500       # 频率分成多少根带（喂进来的频谱会压缩成这么多根）
每档对数 = 10       # 每根频带用几对神经元 = 几档响度（10 对 = 0~10 共 11 级）
层数 = 3
连接半径 = 10
权重范围 = 0.1      # 只影响出生时随机强度的分布（每个细胞的权重之后会被归一化）
