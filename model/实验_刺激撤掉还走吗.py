# -*- coding: utf-8 -*-
"""实验_刺激撤掉还走吗.py —— 把"看见红"这个刺激撤掉以后，行为还会不会自己走下去？

★ 要证的这件事（用户 2026-09-15 的说法）：
    "大脑的思考是靠大脑皮层的神经元相互激活来实现的。"
  如果行为只是"输入驱动的反射"，那么红一撤，走路当场就该停。
  如果行为进了皮层、靠皮层内部互相激活在转，那么红撤掉以后它应该还能接着走一段。

★ 三幕（都站着、每一幕都把皮层清干净、身体摆成站姿）：
    A 连续红    ：0~4 秒一直有红            → 基准
    B 先红后黑  ：0~2 秒有红，2 秒把红撤掉   → 看后 2 秒还走不走
    C 先黑后红  ：0~2 秒黑屏，2 秒才给红     → 看前 2 秒该不动、后 2 秒该走起来

★ 顺便盯三块名字，看"红"这件事在皮层里还亮不亮：
    视觉:中有红  /  前额叶:看着红  /  运动记忆:前进1.2（那一串时刻）

命令：python 实验_刺激撤掉还走吗.py [种子,种子,...]
"""
from __future__ import annotations

import sys

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 身体_go2 as 身体
import 运动记忆区_motor_memory as 运动记忆

帧秒 = 主循环.帧秒
种子们默认 = [20260914, 20260915, 20260916]
红图 = 主循环.红图("中")
黑图 = np.zeros_like(红图)
名字块 = ["视觉:中有红", "前额叶:看着红"]


def 取块(脑, 块名):
    名字 = 本能.读名字()
    区, 名 = 块名.split(":", 1)
    起 = 脑.网.区起点[区.strip()]
    return 起 + np.asarray(名字[区.strip()][名.strip()], dtype=np.int64)


def 一幕(脑, 身, 第二段给红, 秒=4.0, 换图时刻=2.0):
    """第一段（0~换图时刻）给红；第二段给不给红由 第二段给红 决定。"""
    身.摆成站姿()
    身.走(0.5, None)
    脑.亮[:] = False
    脑.上一拍[:] = False
    运记起 = 脑.网.区起点["运动记忆"]
    走 = 运记起 + np.asarray(运动记忆.时刻们("前进1.2"), dtype=np.int64)
    块 = {b: 取块(脑, b) for b in 名字块}
    前半 = {"走": 0, "总": 0}
    后半 = {"走": 0, "总": 0, "前额叶红": 0, "视觉红": 0}
    直到停 = None
    换 = int(round(换图时刻 / 帧秒))
    for k in range(int(round(秒 / 帧秒))):
        图 = 红图 if (k < 换 or 第二段给红) else 黑图
        脑.一拍(图=图, 身=身)
        身.步进(脑.肌肉发力())
        动 = bool(脑.上一拍[走].any())
        if k < 换:
            前半["总"] += 1
            前半["走"] += int(动)
        else:
            后半["总"] += 1
            后半["走"] += int(动)
            后半["前额叶红"] += int(bool(脑.上一拍[块["前额叶:看着红"]].any()))
            后半["视觉红"] += int(bool(脑.上一拍[块["视觉:中有红"]].any()))
            if 直到停 is None and not 动:
                直到停 = (k - 换) * 帧秒
    return dict(前半走=前半["走"], 前半总=前半["总"],
                后半走=后半["走"], 后半总=后半["总"],
                后半前额叶红=后半["前额叶红"], 后半视觉红=后半["视觉红"],
                撤掉后还走了几秒=(直到停 if 直到停 is not None else (秒 - 换图时刻)))


def main():
    种子们 = 种子们默认
    if len(sys.argv) > 1 and sys.argv[1].strip():
        种子们 = [int(a) for a in sys.argv[1].split(",")]
    幕 = [("A 连续红（对照）", True), ("B 先红后黑（2 秒撤掉）", False), ("C 先黑后红（2 秒才给）", False)]
    print("=" * 96)
    print("把刺激撤掉以后行为还走不走？（换图时刻 2.0 秒，总共跑 4.0 秒）")
    print("=" * 96)
    身 = 身体.身体()
    出 = []
    for s in 种子们:
        本能.建网种子 = s
        脑 = 主循环.脑(学=False, 说=False)
        for 名, 第二段给红 in 幕:
            # C 那一幕特殊：第一段本来就不给红
            if 名.startswith("C"):
                脑.亮[:] = False
                r = 一幕先黑(脑, 身)
            else:
                r = 一幕(脑, 身, 第二段给红)
            r["种子"], r["幕"] = s, 名
            出.append(r)
            print("种子 %d  %-22s 前半段走 %3d/%d 拍 | 后半段走 %3d/%d 拍 | 撤掉后还走 %4.1f 秒 | 后半段前额叶红亮 %d 拍、视觉红亮 %d 拍"
                  % (s, 名, r["前半走"], r["前半总"], r["后半走"], r["后半总"],
                     r["撤掉后还走了几秒"], r["后半前额叶红"], r["后半视觉红"]), flush=True)
    print("\n" + "=" * 96)
    print("【汇总】中位数")
    for 名, _ in 幕:
        行 = [r for r in 出 if r["幕"] == 名]
        print("  %-22s 前半段走 %4.0f/%d 拍 | 后半段走 %4.0f/%d 拍 | 撤掉后还走 %4.1f 秒"
              % (名, float(np.median([r["前半走"] for r in 行])), 行[0]["前半总"],
                 float(np.median([r["后半走"] for r in 行])), 行[0]["后半总"],
                 float(np.median([r["撤掉后还走了几秒"] for r in 行]))))
    return 出


def 一幕先黑(脑, 身, 秒=4.0, 换图时刻=2.0):
    """C 幕：前 2 秒黑屏，2 秒开始给红。"""
    身.摆成站姿()
    身.走(0.5, None)
    脑.亮[:] = False
    脑.上一拍[:] = False
    运记起 = 脑.网.区起点["运动记忆"]
    走 = 运记起 + np.asarray(运动记忆.时刻们("前进1.2"), dtype=np.int64)
    块 = {b: 取块(脑, b) for b in 名字块}
    换 = int(round(换图时刻 / 帧秒))
    前半走 = 0
    后半走 = 0
    后半前额叶红 = 0
    后半视觉红 = 0
    直到开 = None
    for k in range(int(round(秒 / 帧秒))):
        图 = 黑图 if k < 换 else 红图
        脑.一拍(图=图, 身=身)
        身.步进(脑.肌肉发力())
        动 = bool(脑.上一拍[走].any())
        if k < 换:
            前半走 += int(动)
        else:
            后半走 += int(动)
            后半前额叶红 += int(bool(脑.上一拍[块["前额叶:看着红"]].any()))
            后半视觉红 += int(bool(脑.上一拍[块["视觉:中有红"]].any()))
            if 直到开 is None and 动:
                直到开 = (k - 换) * 帧秒
    return dict(前半走=前半走, 前半总=换, 后半走=后半走, 后半总=int(round(秒 / 帧秒)) - 换,
                后半前额叶红=后半前额叶红, 后半视觉红=后半视觉红,
                撤掉后还走了几秒=(直到开 if 直到开 is not None else 0.0))


if __name__ == "__main__":
    出 = main()