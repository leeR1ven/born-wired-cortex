# -*- coding: utf-8 -*-
"""实验_切断回响.py —— 同一套本能接线，但每拍把皮层自己的状态抹掉，会怎么样？

★ 要证的这件事（用户 2026-09-15 的说法）：
    "大脑的思考是靠大脑皮层的神经元相互激活来实现的。"
  本能连接给出的是"电流往哪儿流"，可行为要成立，还得靠**上一拍的皮层活动留在原地**、
  下一拍接着往上叠。这个实验就是把"留"这一件事掐掉：

    正常脑   ：每一拍开始时，皮层带着**上一拍的输出**继续算（这就是互激）
    无回响脑 ：每一拍开始时，先把整片皮层清零，只灌外界信号（= 一个没有记忆的反射器）
               接线一个字不改、阈值一个字不改、身体一模一样。

  ★ 如果两种脑子表现差不多，那"思考是皮层互激"这句话就是空的。
    如果无回响脑做不出有序行为，那这条就立住了。

命令：python 实验_切断回响.py [种子,种子,...]
"""
from __future__ import annotations

import sys

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 运动输出区_motor_output as 运动
import 运动记忆区_motor_memory as 运动记忆
import 身体_go2 as 身体
import 实验_眼睛跟随 as 跟随

帧秒 = 主循环.帧秒
种子们默认 = [20260914, 20260915, 20260916]
红图 = 主循环.红图("中")
空图 = np.zeros_like(红图)


def 装上切断(脑):
    """把这一拍的皮层清零（只留下外界信号），再照常走一拍。"""
    原 = 脑.一拍

    def 一拍(图=None, 声=None, 身=None):
        脑.亮[:] = False
        return 原(图=图, 声=声, 身=身)

    脑.一拍 = 一拍


def 清脑(脑):
    脑.亮[:] = False
    脑.上一拍[:] = False


def 跑身体(脑, 身, 秒, 图=None, 盯=None):
    起 = 身.数据.qpos[:2].copy()
    最高 = 身.机身高度()
    点火 = 0
    时刻 = None
    if 盯:
        时刻 = 脑.网.区起点["运动记忆"] + np.asarray(运动记忆.时刻们(盯), dtype=np.int64)
    for _ in range(int(round(秒 / 帧秒))):
        脑.一拍(图=图, 身=身)
        身.步进(脑.肌肉发力())
        最高 = max(最高, 身.机身高度())
        if 时刻 is not None and bool(脑.上一拍[时刻].any()):
            点火 += 1
    return {"末高": 身.机身高度(), "最高": 最高, "歪": 身.机身歪了(),
            "前": float(身.数据.qpos[0] - 起[0]), "点火": 点火}


def 测_起身(脑, 身):
    清脑(脑)
    身.摆成趴姿()
    身.走(0.5, None)
    起高 = 身.机身高度()
    r = 跑身体(脑, 身, 3.0)
    r["起手高"] = 起高
    return r


def 测_见红走(脑, 身):
    清脑(脑)
    身.摆成站姿()
    身.走(0.5, None)
    return 跑身体(脑, 身, 4.0, 图=红图, 盯="前进1.2")


def 测_盯球(脑, 秒数=5.0):
    清脑(脑)
    w = 跟随.架好世界(球方位角=-25.0, 球高度=0.60, 球横向速度=0.5, 球半径=0.05)
    运起, 运宽 = 脑.运起, 脑.运宽
    偏 = []
    for _ in range(int(round(秒数 / 帧秒))):
        脑.一拍(图=w.看())
        力 = 运动.解码眼球发力(脑.亮[运起:运起 + 运宽])
        w.眼肌发力 = 力
        w.走眼睛(帧秒)
        w.走物体(帧秒)
        方, 仰 = w.眼里在哪(0)
        if 方 == 方 and abs(方) <= 45 and abs(仰) <= 35:
            偏.append(max(abs(方), abs(仰)))
    return {"平均偏离": (sum(偏) / len(偏) if 偏 else float("nan")), "末眼": w.眼球水平}


def 跑一个(种子, 切断):
    本能.建网种子 = 种子
    脑 = 主循环.脑(学=False, 说=False)
    if 切断:
        装上切断(脑)
    身 = 身体.身体()
    return dict(种子=种子, 切断=切断,
                起身=测_起身(脑, 身),
                见红走=测_见红走(脑, 身),
                盯球=测_盯球(脑))


def main():
    种子们 = 种子们默认
    if len(sys.argv) > 1 and sys.argv[1].strip():
        种子们 = [int(a) for a in sys.argv[1].split(",")]
    print("=" * 104)
    print("同一套本能接线：正常脑（皮层带着上一拍继续算） vs 无回响脑（每拍把皮层清零，只灌外界信号）")
    print("=" * 104)
    出 = []
    for 种子 in 种子们:
        for 切断 in (False, True):
            r = 跑一个(种子, 切断)
            出.append(r)
            print("种子 %d  %s：起身末高 %.3f（起手 %.3f）| 见红走 %+.2f 米、走路点火 %3d/200 拍 | 盯球平均偏离 %.1f 度"
                  % (种子, "无回响脑" if 切断 else "正常脑  ",
                     r["起身"]["末高"], r["起身"]["起手高"], r["见红走"]["前"],
                     r["见红走"]["点火"], r["盯球"]["平均偏离"]), flush=True)
    print("\n" + "=" * 104)
    print("【汇总】中位数（%d 个种子）" % len(种子们))
    for 切断 in (False, True):
        行 = [r for r in 出 if r["切断"] == 切断]
        print("  %-8s 起身末高 %.3f | 见红走 %+.2f 米（点火 %.0f/200）| 盯球偏离 %.1f 度"
              % ("无回响脑" if 切断 else "正常脑",
                 float(np.median([r["起身"]["末高"] for r in 行])),
                 float(np.median([r["见红走"]["前"] for r in 行])),
                 float(np.median([r["见红走"]["点火"] for r in 行])),
                 float(np.median([r["盯球"]["平均偏离"] for r in 行]))))
    return 出


if __name__ == "__main__":
    出 = main()