def 红图(哪里="中"):
    图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
    if 哪里 == "中":
        图[:, 图宽 // 3: 2 * 图宽 // 3, 0] = 255
    elif 哪里 == "全":
        图[:, :, 0] = 255
    return 图


class 脑:
    """整片皮层 + 时钟 + 前额叶网 + 返回线，一拍一拍地走。"""

    def __init__(self, 学=True, 说=False, 前额叶按灭=False, 前额叶不保留=None):
        self.网, self.本能条数 = 本能.装(说=说)
        # ★ 2026-09-16：「动态整体抑制」的旋钮（见 皮层连接_cortex_links.py 文件头
        #   前额叶自压 那段）。不传参数时看环境变量：
        #     前额叶自压=0.004   前额叶自压目标=0
        #   这不是架构的一部分，是"前额叶怎么才能只亮少数细胞"这个问题的旋钮。
        _自压 = os.environ.get("前额叶自压")
        if _自压 is not None and _自压.strip():
            self.网.前额叶自压 = float(_自压)
        _用不上 = os.environ.get("用不上衰减率")
        if _用不上 is not None and _用不上.strip():
            self.网.用不上衰减率 = float(_用不上)
        _压目标 = os.environ.get("前额叶自压目标")
        if _压目标 is not None and _压目标.strip():
            self.网.前额叶自压目标 = float(_压目标)
        网 = self.网
        self.学家 = []
        self.段 = {名: 网.区段(名) for 名 in ("视觉", "听觉", "运动", "运动记忆", "前额叶")}
        self.视起, self.视宽 = 网.区起点["视觉"], 网.区宽["视觉"]
        self.听起, self.听宽 = 网.区起点["听觉"], 网.区宽["听觉"]
        self.运起, self.运宽 = 网.区起点["运动"], 网.区宽["运动"]
        self.前起, self.前宽 = 网.区起点["前额叶"], 网.区宽["前额叶"]
        self.前额网 = 前额.前额网
        self.返回线 = 前额.返回线
        self.要学 = 学
        # 2026-09-15：用户要「验证前额叶有没有正常工作」，所以给一个**实验开关**：
        # 前额叶按灭 = 假装这个人的前额叶坏了（整片一个细胞都不亮），
        # 用来对照"同样看到红，前额叶参与 / 不参与，行为差在哪"。
        # 这不是架构的一部分，只是做对照实验用的（见 验证_前额叶.py）。
        self.前额叶按灭 = 前额叶按灭
        # ★ 2026-09-16：再给一个**对照实验用**的开关：前额叶"每拍重算、不留上一拍的"。
        #   前额叶现在装着环（见 本能工具_instincts.py 装() 里「自动首尾接成环」），
        #   亮起来的细胞会一直亮着 —— 这是用户要的"像文字网络那样能持续想"。
        #   但这样一来前额叶是个**累加器**：弱刺激看久了也能攒过阈值。
        #   要分清"哪些结果是环带来的、哪些本来就那样"，就得能把环这一层关掉做对照。
        #   （这不是架构的一部分，只是实验开关，和 前额叶按灭 一样。）
        # ★ 2026-09-16 再补一点：不传参数时看环境变量 前额叶不保留=1。
        #   这样任何脚本都能用同一套"没有环"的老行为跑一遍做对照（论文里 R1-R8 就是这一档），
        #   不用一个个去改脚本里的 主循环.脑(...)。
        if 前额叶不保留 is None:
            前额叶不保留 = os.environ.get("前额叶不保留") == "1"
        self.前额叶不保留 = bool(前额叶不保留)
        self.亮 = np.zeros(网.总数, dtype=bool)
        self.上一拍 = np.zeros(网.总数, dtype=bool)
        # 多巴胺（奖励）那一片：想吃奖励时直接把这一小撮点亮就行
        # （用户 2026-09-16："为了简化实验，当我们想激活多巴胺时可以直接激活多巴胺"）。
        # 它亮着的那一拍，皮层的学习走"当场连起来"那条快路，见
        # 皮层连接_cortex_links.py 的 _多巴胺强化。
        _d起 = 网.区起点.get("多巴胺")
        self._多巴胺段 = (slice(_d起, _d起 + 网.区宽["多巴胺"])
                       if _d起 is not None else None)
        self.多巴胺亮 = False
        # ★ 2026-09-16：触觉区（AGI触觉宽度>0 才有）。它的细胞**不在这里**由代码
        #   点亮 —— "被摸一下"是**外界信号**，和眼前那张图、耳边那个声音一样，
        #   由体外那一方送进来（见 一拍 的 摸 参数、触觉区_touch.py 的 摸()）。
        #   送进来以后，天生那条本能连接（触觉:<部位> -> 多巴胺:全部）会把它
        #   引到多巴胺上；多巴胺一亮，这一拍亮着的那些神经元之间的连接当场连起来。
        #   所以：想给奖励，就得伸手摸它，代码里没有"发奖励"这个开关了。
        self._触觉段 = 网.区段("触觉") if "触觉" in 网.区起点 else None

    # ---------- 一拍 ----------
    def 一拍(self, 图=None, 声=None, 身=None, 摸=None):
        网 = self.网
        时钟.走一步()                                   # ① 时间往前走一格
        亮 = self.亮.copy()
        if 图 is not None:                              # ② 外界信号进感觉皮层
            # ★ 2026-09-15：视觉区是 [第4层 | 第1层] 两段拼起来的（见 本能工具_instincts.py
            #   里 视觉区宽度 那一段）。第4层是压缩完的"整体感觉"，第1层是还没压缩的细节
            #   （小东西只有第1层看得见）。一次 前向传播 两层都算出来了，各填各的。
            本能.灌视觉(亮, 网, 图)
        if 声 is not None:
            亮[self.听起:self.听起 + self.听宽] = 听觉.网.前向传播(听觉.频谱转信号(声))
        if 身 is not None:
            感觉.灌感觉(亮, 网, 身)
        if self._触觉段 is not None:                      # 手碰到身上那一下
            # ★ 和 图/声 不一样：触觉是这一拍**有没有被碰到**，不是一直被碰着。
            #   手拿开了（摸=None）就得灭掉 —— 否则亮过一次就赖在皮层上不走
            #   （触觉区是只进不出的，没有谁能把它压灭），那就成了"碰一下奖励发一辈子"。
            _宽 = self._触觉段.stop - self._触觉段.start
            亮[self._触觉段] = (np.zeros(_宽, dtype=bool) if 摸 is None
                               else np.asarray(摸, dtype=bool)[:_宽])
        # 前额叶只吃**压缩完的那一段**（第4层）；没压缩的细节不进前额叶
        视出 = 亮[self.视起:self.视起 + 本能.视觉前段]
        听出 = 亮[self.听起:self.听起 + self.听宽]
        运入 = 亮[self.运起:self.运起 + self.运宽]
        前 = np.asarray(self.前额网.前向传播(视出, 听出, 运入), dtype=bool)   # ③ 前额叶再压一次
        if self.前额叶按灭:                                                    # 实验：前额叶"坏了"
            # ★ 2026-09-16：前额叶改成"靠自己接的环往下转"（下面 |= 那一段）以后，
            #   这里必须**把整片抹掉**，不能只把新送进来的那股市 0。
            #   只送 0 的话，亮名单里还留着上一拍前额叶亮着的那些细胞，
            #   它们靠自己的环接着转 —— 那就不是"前额叶坏了"，是"前额叶还活着"。
            #   对照实验要的是"整片一个细胞都不亮"（见文件头 前额叶按灭 那段）。
            前 = np.zeros_like(前)
            亮[self.前起:self.前起 + self.前宽] = False
        # ★ 2026-09-16 改：原来是 `= 前`（每一拍把前额叶整片**覆盖**掉），
        #   所以前额叶亮完就没了，和文字网络那种"一直转着"完全不一样。
        #   用户："前额叶激活状态就要像之前的文字网络那样。"
        #   现在改成 `|= 前`：前额叶网只负责**送一股输入进来**，
        #   前额叶自己靠它出生时接好的那些环（见 本能工具_instincts.py 装() 里
        #   「一段神经元自动首尾接成环」）一拍一拍往下走，信号撤了也还在。
        if self.前额叶不保留:
            # 对照：把前额叶当"每拍重算"的一块（加环之前的老行为）
            亮[self.前起:self.前起 + self.前宽] = 前
        else:
            亮[self.前起:self.前起 + self.前宽] |= 前   # 按灭时上面已经抹成空，|= 等于没加
        回 = np.asarray(self.返回线.返回(前), dtype=bool)                     # ④ 返回线送回感觉区
        if 回.any():
            # 返回线送回的是**第4层那一段**（前额叶只跟压缩完的信号打交道）
            亮[self.视起:self.视起 + 本能.视觉前段] |= 回[:本能.视觉前段]
            亮[self.听起:self.听起 + self.听宽] |= 回[本能.视觉前段:本能.视觉前段 + self.听宽]
            亮[self.运起:self.运起 + self.运宽] |= 回[本能.视觉前段 + self.听宽:]
        if self.多巴胺亮 and self._多巴胺段 is not None:                        # ⑤ 多巴胺（奖励）
            # 这不是架构的一部分，是**对照实验用**的开关：想跳过触觉、直接从外面
            # 点一下奖励时用它。仿生那条路是 摸 -> 触觉区 -> 天生本能 -> 多巴胺，
            # 见本文件 脑.__init__ 里 _触觉段 那段说明。
            亮[self._多巴胺段] = True
        出 = 网.步进(亮)                                                      # ⑥ 整片皮层走一拍
        if self.要学:
            网.学习(亮, 出)                                                   # ⑦ 赫布学习
        self.上一拍 = 亮
        self.亮 = 出
        return 出

    def 肌肉发力(self):
        return 运动.解码发力(self.亮[self.运起:self.运起 + self.运宽])



# ================= 跑起来 =================
def 跑(脑, 身, 秒数, 图=None, 声=None, 说=True, 每多少拍报一次=25):
    起 = 身.数据.qpos[:2].copy()
    最高 = 身.机身高度()
    上一点 = 起.copy()
    路程 = 0.0                      # 一步一步加起来走了多远（哪怕是绕圈）
    翻倒于 = None                   # 什么时候歪过 75 度（那就是摔了）
    # ★ 2026-09-15："动没动"不等于"走没走"。黑屏下身子会塌、平衡反射拼命在救，
    #   路程照样累加。所以这里额外盯"走路的动作有没有点火"。
    看点 = ["前进1.2", "左转1.5", "右转0.75", "站起来", "原地踏步", "站姿"]
    运记起 = 脑.网.区起点["运动记忆"]
    时刻 = {a: 运记起 + np.asarray(运动记忆.时刻们(a), dtype=np.int64) for a in 看点}
    点火 = {a: 0 for a in 看点}
    for k in range(int(round(秒数 / 帧秒))):
        脑.一拍(图=图, 声=声, 身=身)
        身.步进(脑.肌肉发力())
        for a in 看点:
            if 脑.上一拍[时刻[a]].any():
                点火[a] += 1
        最高 = max(最高, 身.机身高度())
        点 = 身.数据.qpos[:2]
        路程 += float(np.hypot(点[0] - 上一点[0], 点[1] - 上一点[1]))
        上一点 = 点.copy()
        if 翻倒于 is None and 身.机身歪了() > 75:
            翻倒于 = k * 帧秒
        if 说 and k % 每多少拍报一次 == 0:
            各 = "、".join("%s%d" % (名, int(脑.亮[段].sum()))
                          for 名, 段 in (("视", 脑.段["视觉"]), ("听", 脑.段["听觉"]),
                                       ("前", 脑.段["前额叶"]), ("运动记忆", 脑.段["运动记忆"]),
                                       ("运动", 脑.段["运动"])))
            发力 = 脑.肌肉发力()
            print("   %4.2f 秒  机身 %.3f 米  歪 %3.0f 度  %s"
                  % (k * 帧秒, 身.机身高度(), 身.机身歪了(), 各))
    p = 身.数据.qpos
    return dict(最高=最高, 末高=身.机身高度(),
                走了=float(np.hypot(p[0] - 起[0], p[1] - 起[1])),
                路程=float(路程), 翻倒于=翻倒于, 歪=身.机身歪了(),
                点火=点火, 总拍=int(round(秒数 / 帧秒)))


def main():
    要说 = "--静" not in sys.argv
    要学 = "不要学" not in sys.argv
    事 = [a for a in sys.argv[1:] if not a.startswith("-")]
    print("=" * 78)
