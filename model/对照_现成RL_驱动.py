def 读策略():
    """把别人的模型读进来，返回（前向函数, 第一层形状）。"""
    import torch
    sd = torch.load(策略文件, map_location="cpu", weights_only=False)["model_state_dict"]
    形状 = tuple(int(v) for v in sd["actor.0.weight"].shape)
    权 = [sd["actor.%d.weight" % i].numpy() for i in (0, 2, 4, 6)]
    偏 = [sd["actor.%d.bias" % i].numpy() for i in (0, 2, 4, 6)]
    均 = sd["actor_obs_normalizer._mean"].numpy().ravel()
    方 = sd["actor_obs_normalizer._var"].numpy().ravel()

    def 前向(观察):
        x = (观察 - 均) / np.sqrt(方 + 1e-8)
        for k in range(3):
            x = 权[k] @ x + 偏[k]
            x = np.where(x > 0, x, np.expm1(np.minimum(x, 50.0)))   # ELU
        return 权[3] @ x + 偏[3]

    return 前向, 形状


def 机身歪(数据):
    w, x, y, z = 数据.qpos[3:7]
    上z = 1 - 2 * (x * x + y * y)
    return float(np.degrees(np.arccos(np.clip(上z, -1.0, 1.0))))


def _建(姿势):
    import mujoco
    模型 = mujoco.MjModel.from_xml_path(str(身体.保证模型存在() / "scene.xml"))
    数据 = mujoco.MjData(模型)
    mujoco.mj_resetDataKeyframe(模型, 数据, 0)
    if 姿势 == "趴":
        数据.qpos[:] = 0.0
        数据.qpos[2] = 0.12
        数据.qpos[3] = 1.0
        数据.qpos[7:] = np.radians(身体.趴姿角)
    else:
        数据.qpos[7:] = np.radians(身体.站姿角)
    数据.qvel[:] = 0.0
    mujoco.mj_forward(模型, 数据)
    return mujoco, 模型, 数据


def 跑(指令, 刚度, 阻尼, 拍数=200, 姿势="站", 前向=None):
    """让别人的模型带着身体走这么多拍，返回记录。"""
    mujoco, 模型, 数据 = _建(姿势)
    起x, 起y = float(数据.qpos[0]), float(数据.qpos[1])
    上次 = np.zeros(12)
    发力序列 = []
    高 = [float(数据.qpos[2])]
    歪 = [机身歪(数据)]
    for _ in range(拍数):
        R = 数据.xmat[1].reshape(3, 3)
        观察 = np.concatenate([数据.qvel[3:6], R.T @ np.array([0.0, 0.0, -1.0]), 指令,
                              数据.qpos[7:] - 默认角, 数据.qvel[6:], 上次])
        上次 = 前向(观察)
        目标 = 默认角 + 动作缩放 * 上次
        发力序列.append(上次.copy())
        for _ in range(控制间隔):
            数据.ctrl[:] = np.clip(刚度 * (目标 - 数据.qpos[7:]) - 阻尼 * 数据.qvel[6:],
                                   -身体.最大力矩, 身体.最大力矩)
            mujoco.mj_step(模型, 数据)
        高.append(float(数据.qpos[2]))
        歪.append(机身歪(数据))
    末x, 末y = float(数据.qpos[0]), float(数据.qpos[1])
    return dict(前进=末x - 起x, 横移=末y - 起y,
                直线=float(np.hypot(末x - 起x, 末y - 起y)),
                末高度=高[-1], 最低=float(np.min(高)), 末歪=歪[-1],
                站在地上=bool(高[-1] >= 0.25 and 歪[-1] < 30.0),
                发力序列=np.array(发力序列), 高度序列=np.array(高))


def 跑恒定(发力, 刚度, 阻尼, 拍数, 姿势="趴"):
    """不用模型，12 块肌肉恒定发同一个数 —— 量站起来在这具身体上到底难不难。"""
    mujoco, 模型, 数据 = _建(姿势)
    目标 = np.radians(身体.发力转角度(np.full(12, float(发力))))
    高 = [float(数据.qpos[2])]
    到 = None
    for k in range(拍数):
        for _ in range(控制间隔):
            数据.ctrl[:] = np.clip(刚度 * (目标 - 数据.qpos[7:]) - 阻尼 * 数据.qvel[6:],
                                   -身体.最大力矩, 身体.最大力矩)
            mujoco.mj_step(模型, 数据)
        高.append(float(数据.qpos[2]))
        if 到 is None and 高[-1] >= 0.25:
            到 = k + 1
    return dict(第几拍到0_25米=到, 末高度=高[-1], 末歪=机身歪(数据),
                最低=float(np.min(高)))


