# -*- coding: utf-8 -*-
"""实验_白脑对照.py —— "出生就没有本能连接"的大脑能做出有序行为吗？

★ 为什么要有这个：
  论文主张 P5：「一个网络不能从沉默开始」，并且说身体能做出有序动作靠的是
  **本能连接**。之前只有"不给感觉"的对照（身体瘫掉）—— 那证明的是"没有感觉不行"，
  不是"没有本能连接不行"。审稿人一定会追问：会不会随机背景连接本身就够用？
  这个脚本把本能表整个清空、只留随机背景连接（下称"白脑"），跑跟论文 R1 一样的三件事。

★ 两种脑子的唯一差别：白脑不调用 本能.装()，所以一条本能连接都没展开；
  建网种子、区宽度、背景连接、感觉输入全部一样。

★ 预期：白脑三件事全部做不到；完整脑全部做得到。

命令：python 实验_白脑对照.py [种子,种子,...]
"""
from __future__ import annotations

import sys

import numpy as np

import 本能工具_instincts as 本能
import 闭环_前提 as 前提
import 身体_go2 as 身体

默认种子们 = [20260914, 20260915, 20260916, 20260917, 20260918]


def 跑一趟(种子, 白脑):
    本能.建网种子 = 种子
    if 白脑:
        网 = 本能.建网()
        条 = 0
    else:
        网, 条 = 本能.装(说=False)
    身 = 身体.身体()
    # [1] 趴着，什么都不给 —— 靠本能"感觉到自己趴着"自己站起来
    身.摆成趴姿()
    身.走(0.5, None)
    起手高 = 身.机身高度()
    r1 = 前提.一张段(网, 身, 3.0, 说=False)
    # [2] 站着，眼前正中间一片红 —— 靠本能朝红走
    身.摆成站姿()
    身.走(0.5, None)
    红激活 = np.asarray(前提.视觉.网.前向传播(前提.视觉.图像转信号(前提.红图("中"))), dtype=bool)
    起 = 身.数据.qpos[:2].copy()
    r2 = 前提.一张段(网, 身, 4.0, 视觉激活=红激活, 说=False)
    前 = float(身.数据.qpos[0] - 起[0])
    # [3] 什么都不给（连感觉都不给）—— 对照：应该瘫掉
    身.摆成站姿()
    r3 = 前提.一张段(网, 身, 1.5, 用感觉=False, 说=False)
    return {"种子": 种子, "白脑": 白脑, "本能条数": 条, "起手高": 起手高,
            "站起来末高": r1["末高"], "朝红走了": 前,
            "瘫掉末高": r3["末高"], "瘫掉歪了": r3["歪"]}


def main():
    种子们 = 默认种子们
    if len(sys.argv) > 1 and sys.argv[1].strip():
        种子们 = [int(a) for a in sys.argv[1].split(",")]
    print("=" * 96)
    print("白脑对照：本能表清空（只有随机背景连接）vs 完整脑，同样的三件事，%d 个种子" % len(种子们))
    print("=" * 96)
    出 = []
    for 白 in (True, False):
        for s in 种子们:
            r = 跑一趟(s, 白)
            出.append(r)
            print("%s 种子 %d（本能连接 %d 根）：起手 %.3f 米 → 站起来末高 %.3f；朝红走了 %+.2f 米；"
                  "什么都不给 → 末高 %.3f、歪 %.0f 度"
                  % ("白脑  " if 白 else "完整脑", r["种子"], r["本能条数"], r["起手高"],
                     r["站起来末高"], r["朝红走了"], r["瘫掉末高"], r["瘫掉歪了"]), flush=True)
    print("\n" + "=" * 96)
    print("【汇总】")
    for 白, 名 in ((True, "白脑（本能表清空）"), (False, "完整脑（585 条本能）")):
        组 = [r for r in 出 if r["白脑"] == 白]
        a = np.array([r["站起来末高"] for r in 组])
        b = np.array([r["朝红走了"] for r in 组])
        c = np.array([r["瘫掉末高"] for r in 组])
        print("  %s：" % 名)
        print("    自己站起来（末高 > 0.20 算成功）： %d/%d，末高 中位 %.3f、最高 %.3f"
              % (int((a > 0.20).sum()), len(a), float(np.median(a)), float(a.max())))
        print("    朝红走（> 0.30 米算成功）：        %d/%d，走了 中位 %+.2f 米、最多 %+.2f"
              % (int((b > 0.30).sum()), len(b), float(np.median(b)), float(b.max())))
        print("    什么都不给（末高 < 0.20 算瘫掉）：  %d/%d，末高 中位 %.3f"
              % (int((c < 0.20).sum()), len(c), float(np.median(c))))
    return 出


if __name__ == "__main__":
    出 = main()