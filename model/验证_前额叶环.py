# -*- coding: utf-8 -*-
"""验证_前额叶环.py —— 前额叶那几段神经元，亮起来之后会不会"赖着不走"

★ 用户 2026-09-16 要的东西：
    "任何一段神经元被激活后……自动能让它在大脑里被持续激活……
     这些循环持续激活只存在前额叶，所以不影响记忆区的按顺序激活。"

★ 这个脚本只回答三个问题：
   ① 红在眼前时，前额叶那一段"看着红"亮多少？
   ② 把红撤掉（换黑屏）之后，"看着红"那一段还亮不亮？亮多久？
   ③ 会不会越积越多、最后整片前额叶全亮（那就是塌缩）？

命令： python 验证_前额叶环.py
"""
from __future__ import annotations

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 身体_go2 as 身体

图高, 图宽 = 主循环.图高, 主循环.图宽


def 红图():
    图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
    图[:, 图宽 // 3: 2 * 图宽 // 3, 0] = 255
    return 图


黑图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)


def main():
    名字 = 本能.读名字()
    脑 = 主循环.脑(学=True, 说=False)
    身 = 身体.身体()
    身.摆成站姿()
    身.走(0.5, None)
    网 = 脑.网
    前起 = 网.区起点["前额叶"]
    前宽 = 网.区宽["前额叶"]
    看着红 = np.asarray(名字["前额叶"]["看着红"], dtype=np.int64) + 前起
    声 = np.asarray(本能.听觉例子["低频响"](), dtype=np.float64)
    听到声 = np.asarray(名字["前额叶"]["听到低频响"], dtype=np.int64) + 前起

    print("=" * 96)
    print("前额叶环：整片 %d 个细胞；「看着红」这一段 %d 个；「听到低频响」那一段 %d 个"
          % (前宽, 看着红.size, 听到声.size))
    print("=" * 96)

    print("\n[1] 红在眼前，走 40 拍")
    for k in range(40):
        脑.一拍(图=红图(), 声=None, 身=身)
        身.步进(脑.肌肉发力())
    print("    这一拍：整片前额叶亮 %d；其中「看着红」那一段亮 %d/%d；视觉亮 %d"
          % (int(脑.亮[前起:前起 + 前宽].sum()),
             int(脑.亮[看着红].sum()), 看着红.size,
             int(脑.亮[脑.段["视觉"]].sum())))

    print("\n[2] 把红撤掉，只给黑屏，继续走 80 拍（看它还在不在）")
    print("     拍   整片前额叶   「看着红」还在亮   视觉亮   运动记忆亮")
    for k in range(1, 81):
        脑.一拍(图=黑图, 声=None, 身=身)
        身.步进(脑.肌肉发力())
        if k % 10 == 0:
            print("    %4d %10d %13d/%d %9d %11d"
                  % (k, int(脑.亮[前起:前起 + 前宽].sum()),
                     int(脑.亮[看着红].sum()), 看着红.size,
                     int(脑.亮[脑.段["视觉"]].sum()),
                     int(脑.亮[脑.段["运动记忆"]].sum())), flush=True)

    print("\n[3] 换成「只听声音、黑屏」，走 60 拍（看声音那一段会不会自己赖着）")
    print("     拍   整片前额叶   「听到声音」亮   听觉亮")
    for k in range(1, 61):
        脑.一拍(图=黑图, 声=声, 身=身)
        身.步进(脑.肌肉发力())
        if k % 10 == 0:
            print("    %4d %10d %13d/%d %8d"
                  % (k, int(脑.亮[前起:前起 + 前宽].sum()),
                     int(脑.亮[听到声].sum()), 听到声.size,
                     int(脑.亮[脑.段["听觉"]].sum())), flush=True)

    print("\n[4] 声音也撤掉，黑屏 + 静音，再走 60 拍")
    for k in range(1, 61):
        脑.一拍(图=黑图, 声=None, 身=身)
        身.步进(脑.肌肉发力())
        if k % 10 == 0:
            print("    %4d 整片前额叶 %10d   「听到声音」%5d/%d"
                  % (k, int(脑.亮[前起:前起 + 前宽].sum()),
                     int(脑.亮[听到声].sum()), 听到声.size), flush=True)
    print("\n（整片前额叶一共 %d 个细胞。要是这个数一路涨到接近 %d，就是塌缩了）" % (前宽, 前宽))


if __name__ == "__main__":
    main()