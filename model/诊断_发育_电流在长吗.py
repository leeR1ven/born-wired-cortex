# -*- coding: utf-8 -*-
"""诊断_发育_电流在长吗.py —— 一边生活，一边量"声音到走路"那条路上冒出来多少电流

★ 为什么要有这个：
  实验_发育_学会走路.py 只给一个"点着没点着"的二值答案，太粗，也来得太慢。
  真正的机制是：赫布学习在 听觉皮层 -> 运动记忆区 之间**新长出一批连接**，
  这些连接慢慢变粗，于是"只放这个声音"时，走路那串时刻收到的电流慢慢涨。
  这个脚本把那条**电流曲线**直接画出来。涨到 1.0（兴奋阈值）以上，行为才会翻转。

★ 两个数：
  ① 新长出来的 听觉->运动记忆 连接有几千条、权重和是多少（结构）
  ② 只放这个声音时，走路"第一拍"那个细胞收到多少电流（功能）
     对照：本能连接给的是 0.80（视觉:中有红那一半），阈值 1.0

命令： python 诊断_发育_电流在长吗.py [种子] [生活秒数] [每多少拍量一次]
"""
from __future__ import annotations

import sys
import time

import numpy as np

import 本能工具_instincts as 本能
import 听觉前处理_auditory_preprocess as 听觉
import 主循环_完整的一拍 as 主循环
import 身体_go2 as 身体
import 运动记忆区_motor_memory as 运动记忆

图高, 图宽 = 主循环.图高, 主循环.图宽
帧秒 = 主循环.帧秒
黑图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)


def 红图():
    图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
    图[:, 图宽 // 3: 2 * 图宽 // 3, 0] = 255
    return 图


def 量一次(脑, 声):
    网 = 脑.网
    信号 = 听觉.频谱转信号(声)
    听出 = np.asarray(听觉.网.前向传播(信号), dtype=bool)
    亮 = np.zeros(网.总数, dtype=bool)
    亮[脑.听起: 脑.听起 + 脑.听宽] = 听出
    电流 = 网._兴奋电流(亮) - 网._抑制电流(亮)
    头 = 脑.网.区起点["运动记忆"] + int(运动记忆.时刻们("前进1.2")[0])
    段 = slice(脑.网.区起点["运动记忆"], 脑.网.区起点["运动记忆"] + 脑.网.区宽["运动记忆"])
    听号 = 网.区名.index("听觉")
    运记号 = 网.区名.index("运动记忆")
    源区 = 网.区号[网._兴奋源]
    目区 = 网.区号[网._兴奋目]
    掩 = (源区 == 听号) & (目区 == 运记号)
    return {"听亮": int(听出.sum()), "头电流": float(电流[头]),
            "运动记忆最大电流": float(电流[段].max()),
            "听运连接": int(掩.sum()),
            "听运权和": float(网._兴奋权[掩].astype(np.float64).sum()),
            "全边数": int(网._兴奋源.size)}


def main():
    种子 = int(sys.argv[1]) if len(sys.argv) > 1 else 20260914
    生活秒 = float(sys.argv[2]) if len(sys.argv) > 2 else 60.0
    每多少拍 = int(sys.argv[3]) if len(sys.argv) > 3 else 250
    本能.建网种子 = 种子
    print("=" * 100)
    print("诊断：一边生活（眼前红 + 耳朵里低频响），一边量「声音 -> 走路」这条路")
    print("  种子 %d；生活 %.0f 秒（%d 拍）；每 %d 拍量一次" % (种子, 生活秒, int(生活秒 / 帧秒), 每多少拍))
    print("=" * 100)
    脑 = 主循环.脑(学=True, 说=False)
    身 = 身体.身体()
    身.摆成站姿()
    身.走(0.5, None)
    声 = np.asarray(本能.听觉例子["低频响"](), dtype=np.float64)
    红 = 红图()
    拍数 = int(round(生活秒 / 帧秒))
    print("  拍    听亮   头电流  运动记忆最大  听->运 连接数  权和  全边数")
    print("-" * 100)
    记 = []
    for k in range(拍数 + 1):
        if k % 每多少拍 == 0:
            r = 量一次(脑, 声)
            r["拍"] = k
            记.append(r)
            print("  %5d %6d %8.3f %12.3f %13d %8.2f %9d"
                  % (k, r["听亮"], r["头电流"], r["运动记忆最大电流"],
                     r["听运连接"], r["听运权和"], r["全边数"]), flush=True)
        if k >= 拍数:
            break
        脑.一拍(图=红, 声=声, 身=身)
        身.步进(脑.肌肉发力())
    print()
    print("【说明】头电流 = 只放这个声音时，走路「第一拍」那个细胞收到的兴奋减抑制。")
    print("        本能连接给的是 0.80（视觉:中有红那一半），阈值是 1.0。")
    print("        这个数从 0 往 1.0 爬 = 学习正在长出「声音 -> 走路」这条路。")
    return 记


if __name__ == "__main__":
    记 = main()