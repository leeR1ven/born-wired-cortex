# -*- coding: utf-8 -*-
"""实验_前几层看得见小东西吗.py —— 拿最小的东西（一个格子那么大）去戳，看每一层"新亮起来"几个细胞。

用户 2026-09-15："假如眼前有一个非常小的物体经过，画面变动非常小，大脑皮层激活的
神经元可能完全没有改变。这时我们就不能只关注皮层神经元，我们可以观察视觉区的
神经网络的前几层，前几层对于画面信息还没有压缩太多，可以观察到变化。"

这一支就是去量这句话：
  · 每一层"新亮起来"（空画面下没亮、有小东西时亮了）的细胞有几个
  · 这些新亮的细胞是不是**集中在小东西那个方向上**（不然就是白亮）
  · 顺便量一下**输入层（温度计码，比第1层还早）**
"""
from __future__ import annotations

import numpy as np

import 本能工具_instincts as 本能
import 视觉前处理_visual_preprocess as 视觉

方向们 = [("左3", -32), ("左2", -20), ("左1", -8), ("正中", 0),
        ("右1", 8), ("右2", 20), ("右3", 32)]
大像素列数 = 视觉.大像素列数


def 各层(图):
    视觉.网.前向传播(视觉.图像转信号(图))
    return ([np.asarray(a, dtype=bool).copy() for a in 视觉.网.普通层激活],
            np.asarray(视觉.网.输入层.激活, dtype=bool).copy(),
            np.asarray(视觉.网.前向传播(视觉.图像转信号(图)), dtype=bool))


空 = 各层(本能._空画面())


def 新亮(图):
    普, 入, 末 = 各层(本能._球在(np.radians(图), 半径=0.05))
    普0, 入0, 末0 = 空
    出 = [普[k] & ~普0[k] for k in range(3)]
    出.append(入 & ~入0)
    出.append(末 & ~末0)
    return 出, [普[k] & ~普0[k] | (普0[k] & ~普[k]) for k in range(3)] + [入 ^ 入0]


# 每一层：一个"输入神经元/细胞"属于画面第几列（拿环上的编号反推）
def 列们(编号):
    """一串细胞编号 -> 它们各在画面第几列。第1~3层和输入层同编号（一一对应）。"""
    编号 = np.asarray(编号, dtype=np.int64)
    if 编号.size == 0:
        return 编号
    对 = 编号 // 2
    像 = 对 // (视觉.通道数 * 视觉.每档对数)
    r, c = np.divmod(像, 大像素列数)
    return np.where(r % 2 == 0, c, 大像素列数 - 1 - c)


print("每种情况下「空画面下没亮、有小球时亮了」的细胞数（小球半径 0.05 = 一个格子那么大）")
print("%6s | %10s | %8s %8s %8s | %8s | %s"
      % ("方向", "球占第几列", "第1层", "第2层", "第3层", "第4层", "输入层(最前面那层)"))
print("-" * 84)
新亮表 = {}
for 名, 角 in 方向们:
    出, 变 = 新亮(角)
    新亮表[名] = 出
    列 = 列们(np.nonzero(出[3])[0])
    列说 = ("%d~%d" % (列.min(), 列.max())) if 列.size else "—"
    print("%6s | %10s | %8d %8d %8d | %8d | %8d"
          % (名, 列说, 出[0].sum(), 出[1].sum(), 出[2].sum(), 出[4].sum(), 出[3].sum()))
print()
print("这些新亮的细胞**落在哪一列**上（只在第1~3层能算，因为第1~3层和输入层同编号）")
print("%6s | %s" % ("方向", "  ".join("%6s" % n for n, _ in 方向们)))
print("-" * 84)
for k, 层名 in ((0, "第1层"), (1, "第2层"), (2, "第3层")):
    格 = []
    for 名, _ in 方向们:
        列 = 列们(np.nonzero(新亮表[名][k])[0])
        格.append("%6s" % (("%d~%d" % (列.min(), 列.max())) if 列.size else "—"))
    print("%6s | %s" % (层名, "  ".join(格)))
