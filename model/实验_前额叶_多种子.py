# -*- coding: utf-8 -*-
"""实验_前额叶_多种子.py —— 把 R2 那四幕在多个建网种子上重复一遍。

★ 为什么要有这个：论文里不能只有一个种子。这四幕的结论（前额叶一按灭，
  「看见红就走」当场没了）必须在换一批随机背景连接以后仍然成立。

四幕（都站着、面前一张固定不变的图、跑 4 秒）：
  ① 红，前额叶好     → 该走
  ② 红，前额叶按灭   → 该走不起来
  ③ 黑屏，前额叶好   → 该走不起来
  ④ 蓝屏，前额叶好   → 该走不起来

判据一律是「走路那串时刻有没有点火」：黑屏下身子会塌、平衡反射在救，
路程照样累加，所以不能拿「动了没」当判据。

命令：python 实验_前额叶_多种子.py [种子,种子,...]
"""
from __future__ import annotations

import sys

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 身体_go2 as 身体
import 运动记忆区_motor_memory as 运动记忆

帧秒 = 主循环.帧秒
图高, 图宽 = 主循环.图高, 主循环.图宽
种子们默认 = [20260914, 20260915, 20260916, 20260917, 20260918]
看点 = ["前进1.2", "左转1.5", "右转0.75", "站起来", "原地踏步", "站姿"]


def 纯色带(通道):
    图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
    图[:, 图宽 // 3: 2 * 图宽 // 3, 通道] = 255
    return 图


黑图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)


def 一幕(脑, 身, 图, 按灭, 秒=4.0):
    身.摆成站姿()
    身.走(0.5, None)
    脑.前额叶按灭 = 按灭
    脑.亮[:] = False
    脑.上一拍[:] = False
    运记起 = 脑.网.区起点["运动记忆"]
    时刻 = {a: 运记起 + np.asarray(运动记忆.时刻们(a), dtype=np.int64) for a in 看点}
    起 = 身.数据.qpos[:2].copy()
    上一点 = 起.copy()
    路程 = 0.0
    前额叶亮 = []
    点火 = {a: 0 for a in 看点}
    首点火 = None
    for k in range(int(round(秒 / 帧秒))):
        脑.一拍(图=图, 身=身)
        身.步进(脑.肌肉发力())
        if 首点火 is None and 脑.上一拍[时刻["前进1.2"]].any():
            首点火 = k + 1                      # 第几拍第一次走起来（看"累加多久才过阈值"）
        点 = 身.数据.qpos[:2]
        路程 += float(np.hypot(点[0] - 上一点[0], 点[1] - 上一点[1]))
        上一点 = 点.copy()
        前额叶亮.append(int(脑.上一拍[脑.段["前额叶"]].sum()))
        for a in 看点:
            if 脑.上一拍[时刻[a]].any():
                点火[a] += 1
    return dict(路程=路程, 总拍=len(前额叶亮), 点火=点火["前进1.2"],
                前额叶=float(np.mean(前额叶亮)), 首点火=首点火)


def main():
    种子们 = 种子们默认
    if len(sys.argv) > 1 and sys.argv[1].strip():
        种子们 = [int(a) for a in sys.argv[1].split(",")]
    #   最后一项 = "前额叶是不是每拍重算"（True = 把环那一层关掉的对照，见主循环里 前额叶不保留）
    幕 = [("① 红，前额叶好", 纯色带(0), False, True, False),
          ("② 红，前额叶按灭", 纯色带(0), True, False, False),
          ("③ 黑屏，前额叶好", 黑图, False, False, False),
          ("④ 蓝屏，前额叶好", 纯色带(2), False, False, False),
          ("⑤ 蓝屏，前额叶每拍重算", 纯色带(2), False, False, True)]
    print("=" * 96)
    print("前额叶干预：四幕 × %d 个建网种子（走路判据 = 前进1.2 那串时刻点火 > 0 拍）" % len(种子们))
    print("=" * 96)
    身 = 身体.身体()
    出 = []
    for s in 种子们:
        本能.建网种子 = s
        脑 = 主循环.脑(学=False, 说=False)
        for 名, 图, 按灭, 该走, 不保留 in 幕:
            脑.前额叶不保留 = 不保留
            r = 一幕(脑, 身, 图, 按灭)
            r["种子"], r["幕"], r["该走"] = s, 名, 该走
            出.append(r)
            print("种子 %d  %-20s 走路点火 %3d/%d 拍 | 首次点火 %s | 路程 %.2f 米 | 前额叶平均亮 %5.0f 个"
                  % (s, 名, r["点火"], r["总拍"],
                     ("第 %d 拍" % r["首点火"]) if r["首点火"] else "没有",
                     r["路程"], r["前额叶"]), flush=True)
        脑.前额叶不保留 = False
    print("\n" + "=" * 96)
    print("【汇总】")
    print("%-18s | %-14s | %-30s | %s" % ("那一幕", "该不该走", "有几种子走起来了", "点火拍数 / 总拍"))
    print("-" * 96)
    for 名, 图, 按灭, 该走, _r in 幕:
        行 = [r for r in 出 if r["幕"] == 名]
        走 = sum(1 for r in 行 if r["点火"] > 0)
        print("%-22s | %-14s | %-30s | %s"
              % (名, "该走" if 该走 else "不该走",
                 "%d/%d 个种子走起来了（期望 %d）" % (走, len(行), len(行) if 该走 else 0),
                 "、".join("%d/%d" % (r["点火"], r["总拍"]) for r in 行)))
    print("\n【前额叶平均亮多少个细胞】")
    for 名, 图, 按灭, 该走, _r in 幕:
        行 = [r for r in 出 if r["幕"] == 名]
        print("  %-22s %s" % (名, "、".join("%.0f" % r["前额叶"] for r in 行)))
    return 出


if __name__ == "__main__":
    出 = main()