# -*- coding: utf-8 -*-
"""运动输出区_motor_output.py —— 运动皮层 = 肌群神经元（肌肉的力就是从这儿来的）。

★ 一句话

  运动皮层里，每块肌肉占一组神经元（一组「每块肌肉神经元」个，默认 10）。
  这组亮几个，这块肌肉就出多大力：

      亮 0 个 = 完全放松     亮 5 个 = 一半力     亮 10 个 = 最大力

  生物学上这就是「运动单位募集」：想要更大力，就多招几个运动单位。

★ 为什么不做「发力 → 温度计码 → 网络 → 稀疏命令码 → 再解码」那一套

  那等于在皮层和肌肉之间插一层翻译器，再插一个解码器翻回来。
  实测（2026-09-14，12 块肌肉）：读回来的发力最大误差 1.0（=100%），
  也就是皮层上根本读不出"想用多大力"。
  用户的要求是「一切皆神经元」：皮层亮多少就是多大力，中间不翻译，
  也不该有"命令码"这个词。

★ 运动皮层是**输入层**（用户反复强调）

  别的区把信号连到它身上，它再连给肌肉。所以这里不产生动作 ——
  动作是"别的地方把它点亮"的结果。本能连接（比如"前额叶:起立 → 运动:站姿"）
  就是直接写到这里这 120 个神经元上的。
"""
from __future__ import annotations

import numpy as np

from 身体_go2 import 肌肉名, 肌肉数      # 肌肉有几块、都叫什么：只由身体说了算

每块肌肉神经元 = 10                      # 一块肌肉用几个神经元表示发力档位
腿区宽度 = 肌肉数 * 每块肌肉神经元        # 12 条腿上的肌肉，占运动皮层最前面这一截

# ---------------- 眼球的四条眼外肌（2026-09-15 加）----------------
# 眼睛（就是「视角中心」那个东西）自己不会转，是四条眼外肌拉的：
#   往右 / 往左 一对，往上 / 往下一对。
# 编码和腿上一样：这组神经光亮几个，这块肌肉就出多大力。
#   ★ 四块全灭 = 都不拉 = 眼睛停在原地（这跟腿不一样：腿上"0.5 档"才是站姿，
#     眼睛的"歇着"就是一根都不亮）。
#   ★ 一对拮抗肌同时使劲时互相抵消，眼睛往力气大的那边偏（往右力 - 往左力）。
眼球肌肉名 = ["眼往右", "眼往左", "眼往上", "眼往下"]
每块眼球肌肉神经元 = 10
眼球区宽度 = len(眼球肌肉名) * 每块眼球肌肉神经元

运动区宽度 = 腿区宽度 + 眼球区宽度        # = 运动皮层一共多少个神经元（腿 120 + 眼 40）


def 肌肉段(m: int) -> slice:
    """第 m 块肌肉在运动皮层里占的那一段神经元。"""
    return slice(m * 每块肌肉神经元, (m + 1) * 每块肌肉神经元)


def 发力转激活(发力) -> np.ndarray:
    """0~1 的发力 -> 运动皮层的神经元（真/假）。亮的个数就是档位。"""
    发力 = np.clip(np.asarray(发力, dtype=float).ravel(), 0.0, 1.0)
    档 = np.rint(发力 * 每块肌肉神经元).astype(int)
    激活 = np.zeros(运动区宽度, dtype=bool)
    for m in range(肌肉数):
        段 = 肌肉段(m)
        激活[段.start:段.start + 档[m]] = True
    return 激活


def 解码发力(激活) -> np.ndarray:
    """运动皮层的神经元 -> 每块肌肉 0~1 的发力。亮几个就是几档。"""
    激活 = np.asarray(激活, dtype=bool).ravel()[:腿区宽度]
    return 激活.reshape(肌肉数, 每块肌肉神经元).sum(axis=1) / 每块肌肉神经元


def 每块肌肉档位(激活) -> np.ndarray:
    """调试用：每块肌肉亮了几个神经元（0~每块肌肉神经元）。"""
    return np.asarray(激活, dtype=bool).ravel()[:腿区宽度].reshape(
        肌肉数, 每块肌肉神经元).sum(axis=1)


def 眼球段(i: int) -> slice:
    """第 i 块眼球肌肉（0=往右 1=往左 2=往上 3=往下）在运动皮层里占的那一段。"""
    return slice(腿区宽度 + i * 每块眼球肌肉神经元,
                 腿区宽度 + (i + 1) * 每块眼球肌肉神经元)


def 眼球发力转激活(发力) -> np.ndarray:
    """四块眼外肌的发力（0~1，按 眼球肌肉名 的顺序）-> 眼肌那一段的神经元。"""
    发力 = np.clip(np.asarray(发力, dtype=float).ravel(), 0.0, 1.0)
    激活 = np.zeros(眼球区宽度, dtype=bool)
    for i in range(len(眼球肌肉名)):
        档 = int(np.rint(float(发力[i]) * 每块眼球肌肉神经元)) if i < 发力.size else 0
        激活[i * 每块眼球肌肉神经元: i * 每块眼球肌肉神经元 + 档] = True
    return 激活


def 解码眼球发力(激活) -> np.ndarray:
    """眼肌那一段 -> 四块眼外肌 0~1 的发力。"""
    激活 = np.asarray(激活, dtype=bool).ravel()
    眼 = 激活[腿区宽度:腿区宽度 + 眼球区宽度]
    if 眼.size < 眼球区宽度:
        眼 = np.concatenate([眼, np.zeros(眼球区宽度 - 眼.size, dtype=bool)])
    return 眼.reshape(len(眼球肌肉名), 每块眼球肌肉神经元).sum(axis=1) / 每块眼球肌肉神经元


def 眼动(激活):
    """眼肌那一段 -> (水平, 竖直)。正 = 往右偏 / 往上偏，负 = 往左偏 / 往下偏。"""
    力 = 解码眼球发力(激活)
    return float(力[0] - 力[1]), float(力[2] - 力[3])


if __name__ == "__main__":
    rng = np.random.default_rng(0)
    print("运动皮层宽度：%d 个神经元（腿 %d 块肌肉 × %d = %d，眼球 %d 块 × %d = %d）"
          % (运动区宽度, 肌肉数, 每块肌肉神经元, 腿区宽度,
             len(眼球肌肉名), 每块眼球肌肉神经元, 眼球区宽度))
    最差 = 0.0
    for _ in range(200):
        发力 = rng.uniform(0, 1, 肌肉数)
        读回 = 解码发力(发力转激活(发力))
        最差 = max(最差, float(np.abs(读回 - 发力).max()))
    print("往返自检（200 次随机发力）：最大误差 %.3f（应 ≤ 0.05，即半档以内）" % 最差)
    for 名, 发力 in [("站姿", [0.5] * 肌肉数), ("放松", [0.0] * 肌肉数), ("最大", [1.0] * 肌肉数)]:
        激 = 发力转激活(发力)
        print("  %s：亮 %d 个 -> 读回 %s" % (名, int(激.sum()), np.round(解码发力(激), 2)))
    print("  腿上的肌肉读回来不受眼肌影响：%s"
          % ("是对的" if abs(解码发力(发力转激活([1.0] * 肌肉数)) - 1.0).max() < 0.05 else "不对！"))
    for 名, 发力 in [("眼往右", [1, 0, 0, 0]), ("眼往下", [0, 0, 0, 1]),
                    ("一对抵消", [1, 1, 0, 0]), ("都不动", [0, 0, 0, 0])]:
        激 = 眼球发力转激活(发力)
        水平, 竖直 = 眼动(np.concatenate([np.zeros(腿区宽度, dtype=bool), 激]))
        print("  %s：眼肌亮 %d 个 -> 水平 %+.1f 竖直 %+.1f" % (名, int(激.sum()), 水平, 竖直))
