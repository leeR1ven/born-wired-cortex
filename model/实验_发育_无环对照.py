# -*- coding: utf-8 -*-
"""实验_发育_无环对照.py —— 同一套"教它听声音站起来走"，但把前额叶的环关掉

为什么要这一组：用户 2026-09-16 说"模型还没形成复杂网络，一段神经元被激活后亮一下就
没了，没法循环持续激活，所以「声音」和「走路」永远碰不到一起"，所以要给前额叶接环。
但也可能不接环照样教得会（多巴胺那条路的"源"本来就是"上一拍亮着的"，
声音一直响，听觉那片一直亮着，本来就有资格当源）。
这一组就是直接把环关掉，别的全不动，看还能不能教会。

命令：python 实验_发育_无环对照.py 20260914 20260915
"""
from __future__ import annotations

import sys

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 运动记忆区_motor_memory as 运动记忆
import 身体_go2 as 身体

图高, 图宽 = 主循环.图高, 主循环.图宽
黑图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
红图 = 主循环.红图("中")
动作名 = "前进1.2"

出生拍数 = 30
天生拍数 = 30
教学拍数 = 200
考试拍数 = 200


def 跑一个种子(种子):
    本能.建网种子 = 种子
    脑 = 主循环.脑(学=True, 说=False, 前额叶不保留=True)     # ★ 关掉前额叶的环
    身 = 身体.身体()
    网 = 脑.网
    运记起 = 网.区起点["运动记忆"]
    走 = 运记起 + 运动记忆.时刻们(动作名)
    声 = np.asarray(本能.听觉例子["低频响"](), dtype=np.float64)
    前起, 前宽 = 网.区起点["前额叶"], 网.区宽["前额叶"]

    def 走一段(拍数, 图, 声, 多巴胺=False):
        脑.多巴胺亮 = 多巴胺
        上一点 = 身.数据.qpos[:2].copy()
        路程 = 0.0
        走路拍 = 0
        翻在 = None
        前峰 = 0
        for k in range(1, 拍数 + 1):
            脑.一拍(图=图, 声=声, 身=身)
            身.步进(脑.肌肉发力())
            if 脑.亮[走].sum():
                走路拍 += 1
            前峰 = max(前峰, int(脑.亮[前起:前起 + 前宽].sum()))
            p = 身.数据.qpos[:2]
            路程 += float(np.hypot(p[0] - 上一点[0], p[1] - 上一点[1]))
            上一点 = p.copy()
            if 翻在 is None and 身.机身歪了() > 75:
                翻在 = k
        return 路程, 走路拍, 翻在, 前峰

    身.摆成趴姿(); 身.走(0.3, None)
    脑.亮[:] = False; 脑.上一拍[:] = False
    出生路程, 出生走, _, 出生前 = 走一段(出生拍数, 黑图, 声)

    身.摆成站姿(); 身.走(0.5, None)
    脑.亮[:] = False; 脑.上一拍[:] = False
    天生路程, 天生走, _, 天生前 = 走一段(天生拍数, 红图, None)

    身.摆成站姿(); 身.走(0.5, None)
    脑.亮[:] = False; 脑.上一拍[:] = False
    出生条 = int(网.摘要()["当前兴奋连接"])
    教学路程, 教学走, _, 教学前 = 走一段(教学拍数, 红图, 声, 多巴胺=True)
    长出 = int(网.摘要()["当前兴奋连接"]) - 出生条

    脑.多巴胺亮 = False
    脑.亮[:] = False; 脑.上一拍[:] = False
    身.摆成趴姿(); 身.走(0.3, None)
    考试路程, 考试走, 考试翻, 考试前 = 走一段(考试拍数, 黑图, 声)

    print("### 种子 %d（前额叶**不接环**，每拍重算）" % 种子, flush=True)
    print("  出生：只放声音   挪 %.3f 米  走路 %d/%d 拍  前额叶峰值 %d" % (出生路程, 出生走, 出生拍数, 出生前), flush=True)
    print("  天生：看红       挪 %.3f 米  走路 %d/%d 拍  前额叶峰值 %d" % (天生路程, 天生走, 天生拍数, 天生前), flush=True)
    print("  教学：红+声音+多巴胺  挪 %.3f 米  长出 %d 根新连接  前额叶峰值 %d" % (教学路程, 长出, 教学前), flush=True)
    print("  考试：只放声音   挪 %.3f 米  最高站到 %.3f 米  走路 %d/%d 拍  %s  前额叶峰值 %d"
          % (考试路程, 身.机身高度(), 考试走, 考试拍数,
             ("第 %d 拍翻倒" % 考试翻) if 考试翻 else "没翻", 考试前), flush=True)
    print("", flush=True)


if __name__ == "__main__":
    种子们 = [int(a) for a in sys.argv[1:]] or [20260914, 20260915]
    for s in 种子们:
        跑一个种子(s)