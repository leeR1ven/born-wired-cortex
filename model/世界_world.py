def _约束表(对表):
    """对表 = [(点名A, 点名B), ...]，返回两边序号和每个约束对每个点的分摊矩阵。"""
    A = np.array([序号[a] for a, _ in 对表], dtype=int)
    B = np.array([序号[b] for _, b in 对表], dtype=int)
    W = 质量倒数[A] + 质量倒数[B]
    M = np.zeros((点数, len(对表)))
    for k in range(len(对表)):
        M[A[k], k] = 质量倒数[A[k]] / W[k]
        M[B[k], k] = -质量倒数[B[k]] / W[k]
    return A, B, M


def _夹角(A, B, C):
    u = A - B; v = C - B
    c = np.dot(u, v) / (np.linalg.norm(u) * np.linalg.norm(v) + 1e-12)
    return float(np.degrees(np.arccos(np.clip(c, -1.0, 1.0))))


def 夹角到距离(角, LA, LC):
    """A-B-C 夹角 -> A、C 两点的距离（骨头长度 LA、LC 已知）。"""
    return np.sqrt(np.maximum(LA * LA + LC * LC - 2.0 * LA * LC * np.cos(np.radians(角)), 0.0))


