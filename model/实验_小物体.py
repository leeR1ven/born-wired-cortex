# -*- coding: utf-8 -*-
"""实验_小物体.py —— 小到一定程度，视觉皮层是不是真的"什么都没变"？

用户 2026-09-15 的假设："假如眼前有一个非常小的物体经过，画面变动非常小，
大脑皮层激活的神经元可能完全没有改变。这时我们就不能只关注皮层神经元，
我们可以观察视觉区神经网络的前几层。"

这个脚本就是把这句话量出来：
  · 第 1 层（还没压缩的）变化的细胞数
  · 第 4 层（视觉皮层的输出层）变化的细胞数
  · 标定好的"看球在某方向"那片名字亮了几成（那是位置反射的输入）
"""
from __future__ import annotations

import numpy as np

import 本能工具_instincts as 本能
import 视觉前处理_visual_preprocess as 视觉
import 世界_world as 世界

方向们 = [-32, -20, -8, 0, 8, 20, 32]
半径们 = [0.30, 0.10, 0.05, 0.03, 0.02]
名字 = 本能.读名字()


def 某层(图):
    视觉.网.前向传播(视觉.图像转信号(图))
    return [np.asarray(a, dtype=bool).copy() for a in 视觉.网.普通层激活], \
           np.asarray(视觉.网.前向传播(视觉.图像转信号(图)), dtype=bool)


def 一层图(图):
    视觉.网.前向传播(视觉.图像转信号(图))
    return [np.asarray(a, dtype=bool).copy() for a in 视觉.网.普通层激活]


空层 = 一层图(本能._空画面())
空末 = 本能._看出去的(本能._空画面())

print("眼前什么都没有时：第1层亮 %d 个，第4层亮 %d 个"
      % (空层[0].sum(), 空末.sum()))
print()
print("%6s | %5s | %8s | %10s | %10s | %s"
      % ("球半径", "方向", "第1层变化", "第4层变化", "第4层剩几成", "「看球在该方向」名字亮几成"))
print("-" * 100)
for 半 in 半径们:
    for 角 in 方向们:
        图 = 本能._球在(np.radians(角), 半径=半)
        层 = 一层图(图)
        末 = 本能._看出去的(图)
        变1 = int((层[0] != 空层[0]).sum())
        变4 = int((末 != 空末).sum())
        剩 = int((末 & 空末).sum()) / max(int(空末.sum()), 1)
        名 = "看球在正中" if 角 == 0 else ("看球在右%d" % (1 + (abs(角) > 12) + (abs(角) > 25))
                                    if 角 > 0 else "看球在左%d" % (1 + (abs(角) > 12) + (abs(角) > 25)))
        块 = 名字["视觉"].get(名)
        if 块 is None:
            亮 = float("nan")
        else:
            亮 = float(末[np.asarray(块, dtype=np.int64)].mean())
        print("%6.2f | %+5d | %8d | %10d | %9.0f%% | %s %.0f%%"
              % (半, 角, 变1, 变4, 100 * 剩, 名, 100 * 亮))
    print("-" * 100)
