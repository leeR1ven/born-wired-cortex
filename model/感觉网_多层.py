# -*- coding: utf-8 -*-
"""感觉网_多层.py —— "把大量外界信号压成少量信号"的那层网（视觉、听觉共用这一份）。

★ 为什么要单独抽出来（2026-09-15，用户："出了问题应该直接改，而不是打补丁"）

  原来 视觉前处理_visual_preprocess.py 和 听觉前处理_auditory_preprocess.py 里
  **各抄了一份一模一样的 神经网络 类**。同一个毛病要改两遍，改漏一处就悄悄不一致。
  现在只有这一份，两边 import 过去用。

★ 这份网原来有三个根子上的毛病（用户："外界画面线性改变，而皮层激活的神经元没有
  线性改变，这有问题，按理说输出应该和输入一样是线性改变的"）

  毛病一：**"对"的两个神经元各自随机取权重。**
    输入层是"对"编码：正神经元亮 = "这一档亮度过了"，反神经元亮 = "这一档亮度还没过"。
    它们本来是一件事的两面（一个 + 一个 −）。可是原来的代码给每个神经元**各自**
    随机抽一个正权重，于是"过没过这一档"在下一层的求和里退化成两个无关的随机数 ——
    亮度信息在那一层就被抵消掉，输出当然不跟着输入走。
    **改法**：让"对"里正反两个神经元共用一个强度、方向相反 —— 正的那根是兴奋性连接，
    反的那根是**抑制性连接**（就相当于挂一个抑制神经元，功能和负权重一样，见用户
    2026-09-15 那句"抑制神经元本质上的功能就和负权重一样"）。
    这样一来，一颗细胞对"局部亮度"的响应就是**单调**的：越亮，驱动越大。

  毛病二：**权重按"总和"归一 —— 等于让细胞去取平均。**
    总和归一（幅 / 幅.sum()，Σ幅 = 1）之后，权重越大视野越"糊"：
    一个细胞把 ±600 个输入加起来再除以 600，得到的是一片**平均**，
    细胞之间的差别趋近于 0 —— 于是任何门槛都是"要么几乎全亮、要么几乎全灭"。
    当初加"取前几名放电"就是为了硬撑这个假象。
    **改法**：按**平方和**归一（幅 / sqrt((幅**2).sum())，Σ幅² = 1）。
    这时这个和 = "输入和我认的这个模式像不像"（相关/投影），
    视野多大都照样敏感，门槛才有统一的意思。

  毛病三：**整层共用同一个门槛。**
    温度码的 ± 结构是对称的，所以同一层所有细胞"偏好的亮度"全卡在同一个档位上，
    一起翻、不一个个翻 —— 亮度降一点，整片一起灭。
    **改法**：每个细胞的门槛**出生时各不相同**（真实的神经元兴奋性本来就参差），
    这样偏好的亮度散布在整个范围里，亮度一路降下来，细胞就一个一个灭，
    整个"认得出红到什么程度"才是一条连续的线。见 门槛中心 / 门槛散布。

  最后一层放电一律是**固定阈值**（不再"取前几名"）。
  "平均每帧亮几个"由 门槛中心 调 —— 这就是用户说的"通过调整多层网络的各种参数，
  来保证输出神经元激活数量稳定在一个数值"，不靠自动校准去钉死它。
"""
from __future__ import annotations

import numpy as np
from numpy.lib.stride_tricks import sliding_window_view

出生种子 = 20260914          # 固定住：每次跑出来的网必须一模一样，否则写死的本能连接下次就对不上了
归一 = "平方和"              # ★ 见上面"毛病二"。改成 "总和" 就退回老毛病（取平均）
出生门槛下限 = 0.02          # 门槛再怎么随机也不会低过这个（低过 0 的细胞会永远亮着）


class 特征神经元池:
    """numpy 版：所有神经元共用两个数组，速度比对象版快几十到几百倍"""

    def __init__(self, 对数):
        self.对数 = 对数
        self.总数 = 对数 * 2
        self.信号 = np.zeros(self.总数)              # 每个神经元的信号
        self.激活 = np.zeros(self.总数, dtype=bool)  # 每个神经元是否激活

    def 接收信号(self, 编号, 值):
        self.信号[编号] += 值

    def 更新所有对(self):
        正信号 = self.信号[0::2]   # 偶数下标 = 正神经元
        反信号 = self.信号[1::2]   # 奇数下标 = 反神经元
        正赢 = 正信号 >= 反信号    # 平局时正神经元赢
        self.激活[0::2] = 正赢
        self.激活[1::2] = ~正赢
        self.信号[:] = 0.0         # 清空本轮信号


class 神经网络:
    """沿环的局部连接网：每个细胞只看上一层环上左右 半径 个邻居（首尾相接成环）。

    用哪些参数调什么：
      · 层数          —— 叠几层。每叠一层，一层层叠出来的感受野翻一倍，分层能力是指数级涨的。
      · 连接半径      —— 中间层每层看多远。
      · 输出感受野    —— 最后一层看多远（一般是前几层的很多倍，让它"看整体"）。
      · 采样数        —— 每个细胞从自己那片视野里**随机抽几根**来连（视野比这个大得多时）。
                         不抽（0）= 连满整片视野，那片视野一大就变成"取平均"。
      · 门槛中心 / 门槛散布 —— 放电门槛。每个细胞的门槛 = 中心 ± 散布（随机）；
                         中心调"平均每帧亮几个"，散布调"一个个灭还是一起灭"。
      · 权重范围      —— 只影响出生时随机强度的分布（反正每颗细胞的权重会被归一化）。
    """

    def __init__(self, 输入层, 层数, 连接半径=10,
                 权重范围=0.1, 门槛中心=0.4, 门槛散布=0.6,
                 输出感受野=None, 采样数=64):
        self.输入层 = 输入层
        self.对数 = 输入层.对数
        self.层数 = 层数
        self.半径 = 连接半径
        self.每层数 = 输入层.总数
        self.输出层数量 = self.每层数  # 最后一层神经元数量（记忆区靠它同步）
        self.输出感受野 = 连接半径 if 输出感受野 is None else 输出感受野
        self.采样数 = 采样数
        self.权重范围 = 权重范围

        出生随机 = np.random.default_rng(出生种子)

        self.来源 = []
        self.权重 = []
        self.半径们 = []                      # 每层各自用了多宽的半径
        self.抽着连 = []                      # 这一层是不是"抽着连"的
        self.普通层激活 = [np.zeros(self.每层数, dtype=bool) for _ in range(层数 - 1)]
        self.阈值 = [np.clip(门槛中心 + 门槛散布 * 出生随机.uniform(-1.0, 1.0, self.每层数),
                            出生门槛下限, None)
                   for _ in range(层数 - 1)]

        for k in range(层数 - 1):
            # 最后一层用加宽的 输出感受野；其它层用 连接半径
            用半径 = self.输出感受野 if k == 层数 - 2 else 连接半径
            连接数 = 2 * 用半径 + 1
            目标 = np.arange(self.每层数)
            抽着 = 采样数 and 采样数 < 连接数
            if 抽着:
                # 视野太大（最后一层 1201 个输入）：只随机抽 采样数 根来连
                抽 = 出生随机.integers(0, 连接数, size=(self.每层数, 采样数))
                来源 = (目标[:, None] - 用半径 + 抽) % self.每层数
                幅 = 出生随机.uniform(0.0, 1.0, size=(self.每层数, 采样数))
            else:
                偏移 = np.arange(-用半径, 用半径 + 1)
                来源 = (目标[:, None] + 偏移[None, :]) % self.每层数
                # ★ 关键：权重按"对"给，不按神经元给。
                #   同一个"对"的偏移（对偏移）共用一份强度；正神经元取 +，反神经元取 −。
                #   这样"亮度过没过这一档"才是一件事的两面，而不是两个随机数。
                对偏移 = 来源 // 2 - (目标 // 2)[:, None]
                列 = 对偏移 - 对偏移.min()
                # ★ 2026-09-16 改（用户问"尺度放大我的电脑带的动吗"时量出来的）：
                #   来源 是**绕环回绕**的（(目标+偏移) % 每层数），所以一头一尾的目标
                #   会把 对偏移 拉到 ±每层数/2 那么远 —— 列.max() 直接等于 每层数-1。
                #   于是这行原来是 **每层数 × 每层数** 的一张密集随机表：
                #   听觉网 每层数 30000 → 30000×29999×8 字节 = **7.2 GB**，
                #   实测进程峰值 7.0 GB 全是这一句吃的（建网只要 10~23 秒、稳态不到 1 GB）。
                #   它是放大规模的唯一堵点。
                #   改法：**按行分块**地抽。每一块里抽的是同一段行、同样多的数，
                #   而 rng.uniform(size=(n,m)) 是按行优先顺序一个接一个填的，
                #   所以分块抽出来的值与原表**一个一个都相同**（见 验证_感觉网分块.py）。
                #   每行只把自己用得上的 21 个数留下，表本身不再落地。
                _宽 = int(列.max()) + 1
                _块行 = max(1, min(self.每层数, 4_000_000 // max(_宽, 1)))
                _幅 = np.empty(列.shape, dtype=np.float64)
                for _起 in range(0, self.每层数, _块行):
                    _止 = min(self.每层数, _起 + _块行)
                    _强 = 出生随机.uniform(0.0, 1.0, size=(_止 - _起, _宽))
                    _行 = np.arange(_止 - _起)[:, None]
                    _幅[_起:_止] = _强[_行, 列[_起:_止]]
                幅 = _幅
            幅 = 幅 / np.sqrt((幅 ** 2).sum(axis=1, keepdims=True))   # ★ 平方和归一（见文件头毛病二）
            符号 = np.where(来源 % 2 == 0, 1.0, -1.0)                 # 正=兴奋，反=抑制
            self.来源.append(来源.astype(np.int32))
            self.权重.append((幅 * 符号).astype(np.float32))
            self.半径们.append(int(用半径))
            self.抽着连.append(bool(抽着))

    def _局部加权和(self, k, 当前激活):
        """第 k 层每个细胞的加权和。

        直觉写法 `(权重 * 激活[来源]).sum(1)` 会先铺一张 每层数×(2*半径+1) 的大表
        （视野 600 时是 23040×1201 ≈ 两千七百万个格子），时间全花在搬这张表上。
        改成「沿环滑一个窗口 + einsum」只读不铺表，实测快 20 多倍，数一样。
        """
        R = self.半径们[k]
        x = 当前激活
        if self.抽着连[k]:
            return np.einsum("ij,ij->i", self.权重[k], x[self.来源[k]])
        if 2 * R >= self.每层数:              # 半径大到绕一圈了，退回直觉写法
            return (self.权重[k] * x[self.来源[k]]).sum(axis=1)
        xt = np.concatenate([x[self.每层数 - R:], x, x[:R]])
        X = sliding_window_view(xt, 2 * R + 1)
        return np.einsum("ij,ij->i", self.权重[k], X)

    def 前向传播(self, 输入信号):
        self.输入层.信号[:] = 输入信号
        self.输入层.更新所有对()
        当前激活 = self.输入层.激活.astype(np.float32)

        for k in range(self.层数 - 1):
            加权和 = self._局部加权和(k, 当前激活)
            当前激活 = 加权和 >= self.阈值[k]      # 固定阈值：亮几个随输入连续变
            self.普通层激活[k] = 当前激活
            当前激活 = 当前激活.astype(np.float32)

        return 当前激活