# -*- coding: utf-8 -*-
"""诊断_互斥到底压没压.py —— 起身站住的整个过程里，互斥那两个抑制神经元亮不亮。

为什么要这么量：拿"从外面注入一个命令"去试是不干净的（赫布学习会把那根临时边
变成"一个卡住的时刻"）。直接看**抑制神经元和电流**才是干净的。
"""
from __future__ import annotations
import numpy as np

import 主循环_完整的一拍 as 主循环
import 本能工具_instincts as 本能
import 身体_go2 as 身体
import 运动记忆区_motor_memory as 记

大脑 = 主循环.脑(学=True, 说=False)
网 = 大脑.网
名字 = 本能.读名字()
记起 = 网.区起点["运动记忆"]
抑起 = 网.区起点["抑制"]
坐下入口 = 记起 + int(记.起手("坐下"))
趴下入口 = 记起 + int(记.起手("趴下去"))
站姿段 = 记起 + np.asarray(记.时刻们("站姿"), dtype=np.int64)
站得高 = np.asarray(名字["机身状态"]["站得高"], dtype=np.int64) + 网.区起点["机身状态"]


def 谁在压(目标):
    """列出往这个目标发抑制的、出自抑制区的那些神经元（全局号、本区号、力度）。"""
    出 = []
    边 = np.nonzero(网._抑制目 == 目标)[0]
    for e in 边:
        s = int(np.searchsorted(网._抑制起, e, side="right") - 1)
        if s >= 抑起:
            出.append((s, s - 抑起, float(网._抑制权[e]) * 网.抑制强度))
    return 出


print("往「坐下入口」发抑制的抑制区神经元：", 谁在压(坐下入口))
print("往「趴下去入口」发抑制的抑制区神经元：", 谁在压(趴下入口))

身 = 身体.身体(); 身.摆成趴姿(); 身.走(0.5, None)
大脑.亮[:] = False
互斥坐 = [s for s, _, _ in 谁在压(坐下入口)]
print()
for k in range(250):
    出 = 大脑.一拍(身=身)
    身.步进(大脑.肌肉发力())
    if 100 <= k < 110 or k % 25 == 0:
        亮 = 大脑.亮
        兴 = 网._兴奋电流(亮); 抑 = 网._抑制电流(亮)
        print("  %4.2f秒 高%.3f 歪%3.0f | 站姿时刻亮%d 站得高亮%d | 互斥抑制神经元亮 %s | 坐下入口 抑制%.2f"
              % (k * 0.02, 身.机身高度(), 身.机身歪了(),
                 int(亮[站姿段].sum()), int(亮[站得高].sum()),
                 [s - 抑起 for s in 互斥坐 if 亮[s]] or "无", 抑[坐下入口]))
