# -*- coding: utf-8 -*-
"""实验_渐变_边界.py —— 同一个脑，漂移前 vs 漂移后，哪些色相能点着走路？

★ 为什么要有这个：
  原来 R4 的收尾对照只在**漂移之后**测了 6 项，结果里「跳到 180°」居然是 7/8。
  单独看它说明不了任何事：不知道 180° 本来就能点着，还是漂移把它变成能点着的。
  这个脚本把一组色相在**漂移前**和**漂移后**各测一遍（同一个脑、同一套权重），
  于是能直接看出局部赫布规则把边界搬到了哪里、有没有搬歪。

★ 两个判据：
  「点着」= 清空皮层后，给这个颜色 8 拍，走路那串时刻里亮了几拍（>=6 算认得出）。

命令：python 实验_渐变_边界.py [种子,种子,...]
"""
from __future__ import annotations

import sys
import time

import numpy as np

import 本能工具_instincts as 本能
import 实验_颜色渐变 as 渐变
import 身体_go2 as 身体
import 主循环_完整的一拍 as 主循环

默认种子们 = [20260914, 20260915, 20260916, 20260917, 20260918]
色相们 = [0, 24, 48, 72, 96, 120, 144, 168, 180, 204, 240]
探头 = 8
学习段 = 25
每步预算 = 200
终点 = 180


def 测一遍(脑, 身, 时刻):
    出 = {}
    for h in 色相们:
        脑.亮[:] = False
        脑.上一拍[:] = False
        统 = 渐变.跑几拍(脑, 身, 渐变.彩色块(h), 探头, 时刻, 渐变.空统计())
        出[h] = 统["前进1.2"]
    脑.亮[:] = False
    脑.上一拍[:] = False
    黑 = np.zeros((渐变.图高, 渐变.图宽, 3), dtype=np.uint8)
    统 = 渐变.跑几拍(脑, 身, 黑, 探头, 时刻, 渐变.空统计())
    出["黑"] = 统["前进1.2"]
    return 出


def 跑一趟(步长, 种子, 说=True):
    本能.建网种子 = 种子
    脑 = 主循环.脑(学=True, 说=False)
    身 = 身体.身体()
    身.摆成站姿()
    身.走(0.5, None)
    时刻 = 渐变.拿时刻(脑)
    渐变.跑几拍(脑, 身, 渐变.彩色块(0), 40, 时刻, 渐变.空统计())
    前 = 测一遍(脑, 身, 时刻)
    # ---- 漂移：色相 0 起，能重新点着就往下挪一格，点不着就停 ----
    h = 0
    总拍 = 40
    while h < 终点 and 总拍 < 6000:
        格拍 = 0
        点着 = 0
        while 格拍 < 每步预算 and 总拍 < 6000:
            渐变.跑几拍(脑, 身, 渐变.彩色块(h), 学习段, 时刻, 渐变.空统计())
            格拍 += 学习段
            总拍 += 学习段
            脑.亮[:] = False
            脑.上一拍[:] = False
            统 = 渐变.跑几拍(脑, 身, 渐变.彩色块(min(h + 步长, 终点)), 探头, 时刻,
                          渐变.空统计())
            点着 = 统["前进1.2"]
            if 点着 >= 6:
                break
        if 点着 < 6:
            break
        h = min(h + 步长, 终点)
    后 = 测一遍(脑, 身, 时刻)
    if 说:
        print("  种子 %d：漂移走到 %d°，共 %d 拍" % (种子, h, 总拍), flush=True)
    return {"种子": 种子, "停在哪": h, "总拍": 总拍, "前": 前, "后": 后}


def main():
    种子们 = 默认种子们
    if len(sys.argv) > 1 and sys.argv[1].strip():
        种子们 = [int(a) for a in sys.argv[1].split(",")]
    print("=" * 100)
    print("渐变边界：同一个脑，3° 一档漂移前 vs 漂移后，哪些色相还能点着走路（%d 个种子）" % len(种子们))
    print("=" * 100)
    出 = []
    for s in 种子们:
        起 = time.time()
        r = 跑一趟(3, s)
        出.append(r)
        print("      （这一趟用了 %.0f 秒）" % (time.time() - 起), flush=True)
    print()
    print("=" * 100)
    print("【总表】点着几拍 / %d 拍" % 探头)
    头 = "  色相 |" + "".join("%10s" % ("种子%d" % r["种子"]) for r in 出) + " | 漂移前合计 | 漂移后合计"
    print(头)
    print("-" * len(头))
    键们 = 色相们 + ["黑"]
    for k in 键们:
        前 = [r["前"][k] for r in 出]
        后 = [r["后"][k] for r in 出]
        名 = "%6s" % ("黑屏" if k == "黑" else "%d°" % k)
        print("%s |" % 名 + "".join("%7d/%-3d" % (a, 探头) for a in 前) + " |"
              + " %4d/%-4d |" % (sum(a >= 6 for a in 前), len(前))
              + " %4d/%-4d |" % (sum(a >= 6 for a in 后), len(后)))
    print()
    print("【合并（前后各一次，同一个脑）】")
    for k in 键们:
        前 = [r["前"][k] for r in 出]
        后 = [r["后"][k] for r in 出]
        名 = "黑屏" if k == "黑" else "%3d°" % k
        print("   %s：漂移前 %s；漂移后 %s"
              % (名, "、".join(str(a) for a in 前), "、".join(str(a) for a in 后)))
    return 出


if __name__ == "__main__":
    出 = main()