# -*- coding: utf-8 -*-
import numpy as np
import 身体_go2 as 身体
import 运动输出区_motor_output as 运动
import 本能工具_instincts as 本能
import 感觉区_共同 as 感觉
import 前额叶区_prefrontal as 前额
import 运动记忆区_motor_memory as 记
import 视觉前处理_visual_preprocess as 视觉

网, 条 = 本能.装(说=False)
段名 = {}
for n, seg in 记.时刻段.items():
    for t in seg:
        段名[t] = n
运起 = 网.区起点["运动"]; 运宽 = 网.区宽["运动"]
记起 = 网.区起点["运动记忆"]; 记宽 = 网.区宽["运动记忆"]
前起 = 网.区起点["前额叶"]; 前宽 = 网.区宽["前额叶"]
真路 = list(前额.前额网.输入路)


def 设路(可回集合):
    前额.返回线.输入路 = [(n, w, h, n in 可回集合) for n, w, h, k in 真路]


def 跑(身, 秒, 视觉激活=None):
    亮 = np.zeros(网.总数, dtype=bool)
    起 = 身.数据.qpos[:2].copy()
    记亮名 = set()
    for k in range(int(秒 / 0.02)):
        for 区名, 区 in 感觉.三个感觉区():
            c = 网.区起点[区名]
            亮[c:c + 区.输出层数量] = 区.状态转激活(区.读身体(身))
        本能.灌视觉(亮, 网, 第4层=视觉激活)
        各路 = {nm: 亮[网.区段(nm)] for nm, _, _, _ in 真路}
        前 = np.asarray(前额.前额网.前向传播(各路), dtype=bool)
        亮[前起:前起 + 前宽] = 前
        回 = 前额.返回线.返回(前)
        for nm, _, _, _ in 真路:
            s = 回[nm]
            if s.any():
                亮[网.区段(nm)] |= s
        出 = 网.步进(亮)
        发力 = 运动.解码发力(出[运起:运起 + 运动.运动区宽度])
        身.步进(发力)
        亮 = 出
        if k > 40:
            for i in np.nonzero(出[记起:记起 + 记宽])[0]:
                记亮名.add(段名.get(int(i), "?" + str(int(i))))
    return dict(末高=身.机身高度(), 歪=身.机身歪了(),
                前进=float(身.数据.qpos[0] - 起[0]), 记忆=sorted(记亮名))


图 = np.zeros((1080, 1920, 3), dtype=np.uint8); 图[:, 640:1280, 0] = 255
红 = np.asarray(视觉.网.前向传播(视觉.图像转信号(图)), dtype=bool)

for 名, 集合 in [("原样(全部可回)", {"视觉", "听觉", "运动记忆", "运动"}),
                 ("去掉运动记忆", {"视觉", "听觉", "运动"}),
                 ("只留视觉/听觉", {"视觉", "听觉"})]:
    设路(集合)
    身 = 身体.身体(); 身.摆成趴姿(); 身.走(0.5, None)
    r1 = 跑(身, 3.0)
    print("%-16s 起身 末高%.3f 歪%3.0f 记忆[%s]" % (名, r1["末高"], r1["歪"], ",".join(r1["记忆"])))
    身 = 身体.身体(); 身.摆成站姿(); 身.走(0.5, None)
    r2 = 跑(身, 5.0, 视觉激活=红)
    print("%-16s 见红 前进%.2f米 末高%.3f 歪%3.0f 记忆[%s]" % ("", r2["前进"], r2["末高"], r2["歪"], ",".join(r2["记忆"])))
    身 = 身体.身体(); 身.摆成站姿(); 身.走(0.5, None)
    r3 = 跑(身, 5.0)
    print("%-16s 黑屏 末高%.3f 记忆[%s]" % ("", r3["末高"], ",".join(r3["记忆"])))
