# -*- coding: utf-8 -*-
'''验证_前额叶.py —— 用户问："看到红色后往前走这些流程有没有用到前额叶？"

★ 先说结论（2026-09-15 改之前）

  没用上。改之前那条本能是  视觉:中有红 → 运动记忆:前进1.2（力度 1.5），
  是**视觉皮层直接点运动记忆**，前额叶一次都没参与。前额叶网虽然被主循环
  调用了，但它算出来的东西没有任何一根连接往下走。

★ 改成了什么

  每一条本能只给一半力度，两条加起来才过阈值 1.0（阈值见 皮层连接_cortex_links.py）：
      视觉:中有红    → 运动记忆:前进1.2   0.9   ← 眼睛看见红
      前额叶:看着红  → 运动记忆:前进1.2   0.4   ← 前额叶也在想红
  0.9 和 0.4 各自都不到 1.0，所以**谁单独都点不着**；两个一起 1.3 才点着。
  这不是代码里的 if，是两个来源的电流在**同一个神经元上相加**。
  于是"看见红 → 往前走"这条路**必须经过前额叶**。

  ★ 但这不是「与」门（用户 2026-09-15 纠正）：神经元只是把各个区送来的电流
    加在一起，谁多谁少并不固定 —— 别处完全可能"光前额叶就够"、"光视觉就够"，
    也可能还要加上听觉/本体感觉/平衡感觉…… 数量不一定的。

★ 怎么验证（本脚本干的事）

  同样一个身体、同样一个画面，只改一件事，看行为差在哪：

    ① 站着看红，前额叶好   → 该往前走
    ② 站着看红，前额叶按灭 → 该走不起来   ← 这一条证明"路真的要经过前额叶"
    ③ 站着看黑屏，前额叶好 → 不该走       ← 顺带证明不会乱走
       （注意"走"的判据是"走路动作有没有点火"：黑屏下身体会塌、平衡反射在救，
         路程照样会累加，所以不能拿"动了没"当判据。）
    ④ 站着看蓝屏，前额叶好 → 不该动

  命令：python 验证_前额叶.py            （4 幕 × 4 秒，不学习，很快）
        python 验证_前额叶.py --学        （把赫布学习打开，慢一些）
'''
from __future__ import annotations

import sys
import time

import numpy as np

import 主循环_完整的一拍 as 主循环
import 身体_go2 as 身体
import 运动记忆区_motor_memory as 运动记忆

帧秒 = 主循环.帧秒
图高, 图宽 = 主循环.图高, 主循环.图宽
看点 = ["前进1.2", "左转1.5", "右转0.75", "站起来", "原地踏步", "站姿"]


def 红带(通道=0):
    图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
    图[:, 图宽 // 3: 2 * 图宽 // 3, 通道] = 255
    return 图


def 黑图():
    return np.zeros((图高, 图宽, 3), dtype=np.uint8)


def 一幕(脑, 图, 按灭, 秒=4.0, 要学=False, 说=False):
    # 摆成站姿，面前给一张图，走 N 秒。
    身 = 身体.身体()
    身.摆成站姿()
    身.走(0.5, None)                      # 让它站稳
    脑.要学 = 要学
    脑.前额叶按灭 = 按灭
    脑.亮[:] = False
    脑.上一拍[:] = False
    运记起 = 脑.网.区起点["运动记忆"]
    时刻 = {a: 运记起 + np.asarray(运动记忆.时刻们(a), dtype=np.int64) for a in 看点}
    # 一个动作不止头一拍：点亮头一拍之后，这一串时刻会自己一拍一拍走下去。
    # 所以要看的是「这个动作的**整串时刻**里有没有亮着」，不是只看头一拍。
    起 = 身.数据.qpos[:2].copy()
    上一点 = 起.copy()
    路程 = 0.0
    前额叶亮 = []
    点火 = {a: 0 for a in 看点}
    总拍 = int(round(秒 / 帧秒))
    for k in range(总拍):
        脑.一拍(图=图, 身=身)
        身.步进(脑.肌肉发力())
        点 = 身.数据.qpos[:2]
        路程 += float(np.hypot(点[0] - 上一点[0], 点[1] - 上一点[1]))
        上一点 = 点.copy()
        # 注意：脑.亮 是"这一步算完的下一拍"；这一拍真正参与运算的是 脑.上一拍
        前额叶亮.append(int(脑.上一拍[脑.段["前额叶"]].sum()))
        for a in 看点:
            if 脑.上一拍[时刻[a]].any():
                点火[a] += 1
        if 说 and k % 50 == 0:
            火 = "、".join("%s" % a for a in 看点 if 脑.上一拍[时刻[a]].any()) or "（没有动作在走）"
            print("      %4.2f 秒  前额叶亮 %4d  运动记忆点火：%s"
                  % (k * 帧秒, 前额叶亮[-1], 火))
    净 = float(np.hypot(身.数据.qpos[0] - 起[0], 身.数据.qpos[1] - 起[1]))
    return dict(路程=路程, 净=净, 总拍=总拍, 点火=点火,
                前额叶=float(np.mean(前额叶亮)) if 前额叶亮 else 0.0,
                歪=身.机身歪了())


def main():
    要学 = "--学" in sys.argv
    秒 = 4.0
    print("=" * 78)
    print("验证：看到红 → 往前走，这条路有没有经过前额叶")
    print("=" * 78)
    print("\n① 建模型（本能表 + 皮层连接网，这一步十几秒）...")
    脑 = 主循环.脑(学=要学, 说=False)
    print("   本能 %s 根，皮层 %s 个神经元" % (format(脑.本能条数, ","), format(脑.网.总数, ",")))
    if 要学:
        print("   （这次开着赫布学习）")

    幕 = [
        ("① 站着看红，前额叶好",   红带(0), False, "走了"),
        ("② 站着看红，前额叶按灭", 红带(0), True,  "没走起来"),
        ("③ 站着看黑屏，前额叶好", 黑图(),  False, "没走起来"),
        ("④ 站着看蓝屏，前额叶好", 红带(2), False, "没走起来"),
    ]
    果 = []
    for 名, 图, 按灭, 期望 in 幕:
        print("\n%s —— 面前这张图固定不变，走 %.0f 秒" % (名, 秒))
        t0 = time.perf_counter()
        r = 一幕(脑, 图, 按灭, 秒=秒, 要学=要学, 说=True)
        # ★ 2026-09-15 改判据：原来用"动了没"（路程 > 1 米），但"动"不等于"走"。
        #   黑屏时身体站不住会往下塌、平衡反射拼命在救，身子在地上扭，
        #   路程也能累到 1.67 米 —— 可"前进1.2"那个走路动作**一次都没点火**。
        #   所以判据改成"**走路的动作有没有点火**"，这才问的是"它想不想走"。
        走没走 = "走了" if r["点火"]["前进1.2"] > r["总拍"] * 0.5 else "没走起来"
        print("   运动记忆里在走的动作（几拍 / 共 %d 拍）：%s"
              % (r["总拍"], "、".join("%s×%d" % (a, n) for a, n in r["点火"].items() if n) or "（一个都没有）"))
        print("   结果：走路的动作点了 %d/%d 拍；身子挪了 %.2f 米（直线 %.2f 米）；前额叶平均亮 %.0f 个细胞"
              % (r["点火"]["前进1.2"], r["总拍"], r["路程"], r["净"], r["前额叶"]))
        print("         期望【%s】 实际【%s】 %s   （用了 %.0f 秒）"
              % (期望, 走没走, "✓" if 期望 == 走没走 else "✗", time.perf_counter() - t0))
        果.append((名, 期望, 走没走, r))

    print("\n" + "=" * 78)
    for 名, 期望, 实际, r in 果:
        print("   %-22s 期望 %-8s 实际 %-8s   路程 %.2f 米，前进1.2 走了 %3d/%d 拍，前额叶平均亮 %.0f"
              % (名, 期望, 实际, r["路程"], r["点火"]["前进1.2"], r["总拍"], r["前额叶"]))
    print("=" * 78)
    print("★ ① 和 ② 唯一的差别就是前额叶亮不亮：")
    print("  · ① 前额叶在算 → 视觉 0.95 + 前额叶 0.80 → 前进1.2 点着 → 一直往前走")
    print("  · ② 前额叶灭了 → 只剩视觉那 0.95（还要扣掉抑制），过不了阈值 1.0 → 点不着")
    print("  所以「看到红 → 往前走」这条路是真的经过前额叶的。")


if __name__ == "__main__":
    main()
