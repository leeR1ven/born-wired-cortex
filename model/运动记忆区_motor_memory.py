"""运动记忆区_motor_memory.py —— 一条时间线，时间神经元一个一个往下走。

★ 一句话

  这个区里**一个神经元 = 一个时刻**。时刻到了，这个神经元就亮，
  它连着"这一刻该动的那几块肌肉、各出多大力的那些运动皮层细胞"。
  时间往前走一格，就是下一个时刻，换下一个神经元亮。

  所以这里没有"第几拍"这种东西 —— 只有**时间神经元**。
  一个动作 = 时间线上的一段（从头到尾连续的若干个时刻）。
  谁点火？感觉（机身很低 → 站起来）或者前额叶以后学会的"想"。

★ 为什么不是"一拍一组细胞"

  2026-09-15 用户说：「为什么要用一组细胞表示第几拍？我没看懂，你不要把事情搞复杂。
  原架构不是很清楚吗，完全可以按时间神经元激活该激活的肌肉啊，为什么要有第几拍这种东西？」

  他说得对。原来我给每一拍分了 12 个细胞（每块肌肉一个），那是把"第几拍"当成
  一个额外发明出来的维度。其实**第几拍就是时间本身** —— 直接用时间神经元就行：
  一个时刻一个神经元，它管这一刻的**全部**肌肉。

★ 时刻表

  动作库里有 221 个动作、一共 3576 拍（一拍 = 20 毫秒 = 主循环一跳）。
  每个动作占时间线上连续的一段：第 1 个动作用时刻 0~n1-1，第 2 个用 n1~n1+n2-1 …
  一个动作的第 k 拍 = 它那一段里的第 k 个时刻。
  循环的动作，最后一拍接回第一拍（时刻自己接回去）。

自检：python 运动记忆区_motor_memory.py
"""
from __future__ import annotations

import json
import pathlib

import numpy as np

根 = pathlib.Path(__file__).resolve().parent


def 读动作库():
    return json.loads((根 / "动作库.json").read_text(encoding="utf-8"))


动作库 = 读动作库()

# 每个动作占时间线上连续的一段时刻
时刻段 = {}
_游标 = 0
for _名, _v in 动作库.items():
    时刻段[_名] = list(range(_游标, _游标 + len(_v["拍"])))
    _游标 += len(_v["拍"])
总时刻数 = _游标
输出层数量 = 总时刻数          # 一个时刻 = 一个时间神经元
总数 = 输出层数量
每拍时刻数 = 1                 # 时间每走一格 = 一拍


def 起手(动作名: str) -> int:
    """这个动作的**第一个时刻**在本区里的下标（点亮它 = 开始做这个动作）。"""
    return int(时刻段[动作名][0])


def 那一刻(动作名: str, 第几拍: int) -> int:
    """这个动作第 几拍 对应的时刻下标。"""
    return int(时刻段[动作名][第几拍])


def 时刻们(动作名: str) -> np.ndarray:
    return np.array(时刻段[动作名], dtype=np.int64)


if __name__ == "__main__":
    print("运动记忆区 = 一条时间线：%d 个时刻，一个时刻一个神经元" % 输出层数量)
    拍数 = np.array([len(v["拍"]) for v in 动作库.values()])
    print("  动作 %d 个，拍数 %d~%d，共 %d 个时刻"
          % (len(动作库), 拍数.min(), 拍数.max(), 总时刻数))
    名 = "前进0.8" if "前进0.8" in 时刻段 else list(时刻段)[0]
    print("  拿「%s」试：占时刻 %s …（共 %d 个）"
          % (名, 时刻段[名][:4], len(时刻段[名])))
    print("  它的起手（第一个时刻）在区里的下标：%d" % 起手(名))
    print("  时间走一格 = 一跳 = 20 毫秒")
    好 = (时刻段[list(时刻段)[0]][0] == 0
          and 时刻段[list(时刻段)[-1]][-1] == 总时刻数 - 1
          and all(时刻段[a][-1] + 1 == 时刻段[b][0]
                  for a, b in zip(list(时刻段), list(时刻段)[1:])))
    print("  每个动作占连续一段、首尾相接：%s" % ("对" if 好 else "不对！"))
