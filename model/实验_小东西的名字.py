# -*- coding: utf-8 -*-
"""实验_小东西的名字.py —— 名字（那片"这个方向有东西"的细胞）能不能一套管住大小的东西？

上一支脚本量出来的事：
  · 画面是 24x16 的马赛克，一个格子 = 6.25 度 x 3.1 度。比一个格子还小的球，
    渲染出来和"一个格子那么大的球"**一模一样**（实测半径 0.10 / 0.05 / 0.03 / 0.02
    的画面完全相同）—— 所以在这个世界里，"很小的东西"就是"一个格子"。
  · 现在那几片名字是拿 0.30 米的球标定的：小球在某个方向，那片名字只亮 0~38%，
    过不了 50% 的线，所以本能拉不动。这就是"看不见小东西"的根子。

这一支量的是：拿小球（0.05）标定出来的名字，
  · 别的方向的小球会不会把它点亮（串味）
  · 大球（0.30）会不会把它点亮（一套名字管不管大小两种）
"""
from __future__ import annotations

import numpy as np

import 本能工具_instincts as 本能
import 世界_world as 世界

方向们 = [("左3", -32), ("左2", -20), ("左1", -8), ("正中", 0),
        ("右1", 8), ("右2", 20), ("右3", 32)]
参考 = [本能._空画面(), 本能._纯色(0), 本能._纯色(1), 本能._纯色(2), 本能._纯色()]
空 = 本能._看出去的(本能._空画面())


def 亮(图):
    return 本能._看出去的(图)


def 名_小(角):
    出 = 亮(本能._球在(np.radians(角), 半径=0.05))
    for 参 in 参考:
        出 = 出 & ~亮(参)
    return np.nonzero(出)[0]


def 名_大(角):
    出 = 亮(本能._球在(np.radians(角), 半径=0.30))
    for 参 in 参考:
        出 = 出 & ~亮(参)
    return np.nonzero(出)[0]


小名 = {名: 名_小(角) for 名, 角 in 方向们}
大名 = {名: 名_大(角) for 名, 角 in 方向们}
print("小球标定的名字一共几个细胞：", {k: len(v) for k, v in 小名.items()})
print("大球标定的名字一共几个细胞：", {k: len(v) for k, v in 大名.items()})
print()

for 谁, 库 in (("小球的名字", 小名), ("大球的名字", 大名)):
    print("【%s】被谁点亮（行=名字，列=眼前是什么）" % 谁)
    print("%6s | %s" % ("", " | ".join("%6s" % n for n, _ in 方向们) + " |  小球别处 | 大球同向"))
    print("-" * 96)
    for 名, 角 in 方向们:
        格 = []
        for 名2, 角2 in 方向们:
            f = 亮(本能._球在(np.radians(角2), 半径=0.05))[库[名]].mean()
            格.append("%5.0f%%" % (100 * f))
        大 = 亮(本能._球在(np.radians(角), 半径=0.30))[库[名]].mean()
        print("%6s | %s |     %5.0f%% |  %5.0f%%" % (名, " | ".join(格), 100 * (0 if 名 == "正中" else 0), 100 * 大))
    print()
