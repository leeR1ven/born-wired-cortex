# -*- coding: utf-8 -*-
"""诊断_摔是谁干的.py —— 一个脑教一次，然后换不同开关考试，看摔倒是谁造成的

背景：只靠本能"看红→走"能稳稳走 3 秒（机身歪 2 度）；
      学出来的"听声音→走"在 3/5 个种子上走到 1 米左右就翻倒（歪 178~180 度）。
不猜，用同一个教过的脑，把考试分别放在几个开关下跑：

  E1  原样（只放声音）
  E2  把**天生互惠返回线**关掉（前额叶不再往视觉/听觉/运动回送信号）
  E3  把**前额叶按灭**（连返回线一起没了，只剩听觉那一路的学出来的连接）

命令：python 诊断_摔是谁干的.py
"""
from __future__ import annotations

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 运动记忆区_motor_memory as 运动记忆
import 身体_go2 as 身体

图高, 图宽 = 主循环.图高, 主循环.图宽
黑图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
红图 = 主循环.红图("中")
动作名 = "前进1.2"
教学拍数 = 200
考试拍数 = 200


def main():
    本能.建网种子 = 20260914
    脑 = 主循环.脑(学=True, 说=False)
    身 = 身体.身体()
    网 = 脑.网
    运记起 = 网.区起点["运动记忆"]
    走 = 运记起 + 运动记忆.时刻们(动作名)
    声 = np.asarray(本能.听觉例子["低频响"](), dtype=np.float64)
    运起, 运宽 = 网.区起点["运动"], 网.区宽["运动"]

    # 教学
    身.摆成站姿(); 身.走(0.5, None)
    脑.亮[:] = False; 脑.上一拍[:] = False
    脑.多巴胺亮 = True
    for _ in range(教学拍数):
        脑.一拍(图=红图, 声=声, 身=身)
        身.步进(脑.肌肉发力())
    脑.多巴胺亮 = False
    print("教完了：兴奋连接 %d 根（出生 %d 根）"
          % (网._兴奋键.size, 网.统计.get("出生兴奋连接", 0)), flush=True)

    零回 = np.zeros(脑.前额网.输入数量, dtype=bool)

    def 考一次(名, 关返回=False, 灭前额叶=False):
        脑.亮[:] = False; 脑.上一拍[:] = False
        脑.前额叶按灭 = 灭前额叶
        if 关返回:
            脑.返回线.返回 = lambda 输出激活, 抑制量=0.0: 零回
        身.摆成趴姿(); 身.走(0.3, None)
        上一点 = 身.数据.qpos[:2].copy()
        路程 = 0.0
        翻在 = None
        print("\n[%s] 清空皮层、重新趴下、只放声音，%d 拍" % (名, 考试拍数))
        for k in range(1, 考试拍数 + 1):
            脑.一拍(图=黑图, 声=声, 身=身)
            身.步进(脑.肌肉发力())
            p = 身.数据.qpos[:2]
            路程 += float(np.hypot(p[0] - 上一点[0], p[1] - 上一点[1]))
            上一点 = p.copy()
            if 翻在 is None and 身.机身歪了() > 75:
                翻在 = k
            if k % 20 == 0:
                print("    %4d 机身高 %.3f 歪 %5.1f 度 路程 %.3f 米 走路链 %d"
                      % (k, 身.机身高度(), 身.机身歪了(), 路程, int(脑.亮[走].sum())),
                      flush=True)
        print("    → %s：路程 %.3f 米，最后机身高 %.3f、歪 %.1f 度，%s"
              % (名, 路程, 身.机身高度(), 身.机身歪了(),
                 ("第 %d 拍翻倒" % 翻在) if 翻在 else "一次没翻"))

    考一次("E1 原样", 关返回=False, 灭前额叶=False)
    考一次("E2 关掉返回线", 关返回=True, 灭前额叶=False)


if __name__ == "__main__":
    main()