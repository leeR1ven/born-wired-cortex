# -*- coding: utf-8 -*-
"""实验_发育_声音叫走路_多种子.py —— 上面那个发育实验，换成好几个随机脑各跑一遍

命令：python 实验_发育_声音叫走路_多种子.py 20260914 20260915 20260916
（不给参数就默认跑 20260914~20260918）

四段（同一个脑，中间不重建）：
  ① 出生     趴着 + 黑屏 + 只放声音        → 预期：一动不动（本能表里没有一条"声音→走路"）
  ② 天生会的 站着 + 眼前有红 + 不放声音     → 预期：自己往前走（出生就会）
  ③ 教学     站着 + 红 + 同时响声音 + 点亮多巴胺 200 拍
  ④ 考试     把皮层全清空、重新趴下、黑屏、只放声音 200 拍 → 预期：自己站起来走

还会写一份每拍的轨迹 CSV：日志_发育轨迹_<种子>.csv（画图用）
"""
from __future__ import annotations

import io
import sys

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 运动记忆区_motor_memory as 运动记忆
import 身体_go2 as 身体

图高, 图宽 = 主循环.图高, 主循环.图宽
黑图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
红图 = 主循环.红图("中")
动作名 = "前进1.2"

出生拍数 = 30
天生拍数 = 30
教学拍数 = 200
考试拍数 = 200


def 跑一个种子(种子):
    本能.建网种子 = 种子
    名字 = 本能.读名字()
    脑 = 主循环.脑(学=True, 说=False)
    身 = 身体.身体()
    网 = 脑.网

    运记起 = 网.区起点["运动记忆"]
    走 = 运记起 + 运动记忆.时刻们(动作名)
    声 = np.asarray(本能.听觉例子["低频响"](), dtype=np.float64)
    前起, 前宽 = 网.区起点["前额叶"], 网.区宽["前额叶"]
    听起, 听宽 = 网.区起点["听觉"], 网.区宽["听觉"]
    声段 = 听起 + np.asarray(名字["听觉"]["低频响"], dtype=np.int64)

    轨迹 = []

    def 走链():
        return int(脑.亮[走].sum())

    def 走一段(拍数, 图, 声, 多巴胺=False, 阶段="?"):
        脑.多巴胺亮 = 多巴胺
        上一点 = 身.数据.qpos[:2].copy()
        路程 = 0.0
        最高 = 身.机身高度()
        走路拍 = 0
        翻在 = None
        for k in range(1, 拍数 + 1):
            脑.一拍(图=图, 声=声, 身=身)
            身.步进(脑.肌肉发力())
            if 走链():
                走路拍 += 1
            p = 身.数据.qpos[:2]
            路程 += float(np.hypot(p[0] - 上一点[0], p[1] - 上一点[1]))
            上一点 = p.copy()
            最高 = max(最高, 身.机身高度())
            if 翻在 is None and 身.机身歪了() > 75:
                翻在 = k
            轨迹.append((种子, 阶段, k, 身.机身高度(), 路程, 走链(),
                         int(脑.亮[前起:前起 + 前宽].sum()),
                         int(脑.亮[声段].sum()), 身.机身歪了()))
        return 路程, 最高, 走路拍, 翻在

    # ① 出生：趴着 + 只放声音
    身.摆成趴姿(); 身.走(0.3, None)
    脑.亮[:] = False; 脑.上一拍[:] = False
    出生路程, 出生最高, 出生走, _ = 走一段(出生拍数, 黑图, 声, 阶段="出生")

    # ② 天生就会的：站着 + 红
    身.摆成站姿(); 身.走(0.5, None)
    脑.亮[:] = False; 脑.上一拍[:] = False
    天生路程, _, 天生走, _ = 走一段(天生拍数, 红图, None, 阶段="天生")

    # ③ 教学：站着 + 红 + 声音 + 多巴胺
    身.摆成站姿(); 身.走(0.5, None)
    脑.亮[:] = False; 脑.上一拍[:] = False
    出生键 = 网._兴奋键.copy()                      # 教学前有哪些连接
    教学路程, _, _, _ = 走一段(教学拍数, 红图, 声, 多巴胺=True, 阶段="教学")
    长出 = int(网.摘要()["当前兴奋连接"] - 出生键.size)

    # 学出来的连接，按"落在哪个区"数一数（只数**新长出来的**那些）
    目新 = 网._兴奋目
    位 = np.searchsorted(出生键, 网._兴奋键)
    在 = 位 < 出生键.size
    有 = np.zeros(网._兴奋键.shape, dtype=bool)
    有[在] = 出生键[位[在]] == 网._兴奋键[在]
    目新 = 目新[~有]
    分区 = {}
    for 区 in 网.区名:
        起 = 网.区起点[区]; 宽 = 网.区宽[区]
        n = int(((目新 >= 起) & (目新 < 起 + 宽)).sum())
        if n:
            分区[区] = n

    # ④ 考试：清空 + 趴下 + 黑屏 + 只放声音
    脑.多巴胺亮 = False
    脑.亮[:] = False; 脑.上一拍[:] = False
    身.摆成趴姿(); 身.走(0.3, None)
    考试路程, 考试最高, 考试走, 考试翻 = 走一段(考试拍数, 黑图, 声, 阶段="考试")

    写轨迹(轨迹)

    print("### 种子 %d" % 种子, flush=True)
    print("  出生：只放声音     挪 %.3f 米  最高 %.3f 米  走路拍了 %d/%d"
          % (出生路程, 出生最高, 出生走, 出生拍数), flush=True)
    print("  天生：看红         挪 %.3f 米  走路拍了 %d/%d"
          % (天生路程, 天生走, 天生拍数), flush=True)
    print("  教学：红+声音+多巴胺  挪 %.3f 米  长出 %d 根新连接  （一共 %d 根）"
          % (教学路程, 长出, 网._兴奋键.size), flush=True)
    print("       新连接落在：%s" % "、".join("%s %d" % kv for kv in
          sorted(分区.items(), key=lambda kv: -kv[1])[:8]), flush=True)
    print("  考试：只放声音     挪 %.3f 米  最高站到 %.3f 米  走路拍了 %d/%d  %s"
          % (考试路程, 考试最高, 考试走, 考试拍数,
             ("第 %d 拍翻倒" % 考试翻) if 考试翻 else "一次没翻（歪 %.0f 度）" % 身.机身歪了()),
          flush=True)
    print("", flush=True)


缓冲 = []


def 写轨迹(行):
    缓冲.extend(行)


if __name__ == "__main__":
    参数 = sys.argv[1:]
    种子们 = [int(a) for a in 参数 if not a.startswith("-")] or [20260914, 20260915, 20260916, 20260917, 20260918]
    for s in 种子们:
        跑一个种子(s)
    if 缓冲:
        名 = "日志_发育轨迹_%d.csv" % 种子们[0]
        with io.open(名, "w", encoding="utf-8", newline="\n") as f:
            f.write("种子,阶段,拍,机身高,累计路程,走路链亮,前额叶亮,听觉亮,歪角\n")
            for r in 缓冲:
                f.write("%d,%s,%d,%.4f,%.4f,%d,%d,%d,%.1f\n" % r)
        print("每拍轨迹写到 %s（%d 行）" % (名, len(缓冲)), flush=True)