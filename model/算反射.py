# -*- coding: utf-8 -*-
"""算反射.py —— 用训练好的模型当裁判，把「偏了以后该怎么修正」算出来，写成反射本能。

★ 思路（一句话）

  照抄的动作是开环的：身体偏了它照旧往下演，就摔。
  真正的老师是**每 20 毫秒看一眼身体状态再下令**的。
  所以我们这样问它：
      「现在身体是这副样子（偏成这样了），你会怎么下力？」
  再拿它的答案和「计划本来要下的力」比。多看几次，就得到一张表：

      在「往前倾得厉害」这种情况里，左前大腿它一直给到 8 档以上
      在「快趴下了」这种情况里，右后小腿它一直是松的（3 档以下）

  把这些写成**反射**：
      平衡感觉:往前倾得厉害  ->  运动:左前大腿至少8档     1.5   是
      机身状态:快趴下了      ->  运动:右后小腿不超过3档   -1.5  是

  第一条是「点亮」那几个档位细胞；第二条的力度写**负数**，意思是"这条是压住的"——
  它会自动借一个**抑制神经元**，让那个神经元去把那几个档位细胞压住。
  合起来就是把这块肌肉的力钉在一个范围里。

★ 为什么只挑"它一直极端"的那些写

  如果老师在某种情况里对某块肌肉的令忽高忽低（跟步子节奏有关），
  那就不是"情况决定的"，写死了反而会跟计划打架。所以只写**一直很用力**或
  **一直很松**的，其余留给计划自己演 —— 这也就是本能的"粗略偏置"。

命令：
    python 算反射.py 看     # 只统计，不写表
    python 算反射.py        # 统计 + 写 反射表.txt
"""
from __future__ import annotations

import json
import pathlib
import sys
from collections import defaultdict

import numpy as np

import 身体_go2 as 身体
import 感觉区_共同 as 感觉
from 取动作_从训练好的模型 import _读策略, 默认角

根 = pathlib.Path(__file__).resolve().parent
帧秒 = 1.0 / 50.0
策略 = _读策略()
库 = json.loads((根 / "动作库.json").read_text(encoding="utf-8"))
训练 = json.loads((根 / "动作库_训练好的.json").read_text(encoding="utf-8"))

危险情况 = ["往前倾得厉害", "往后仰得厉害", "往左歪得厉害", "往右歪得厉害",
          "正在往前扑", "正在往后倒", "正在往左翻", "正在往右翻",
          "歪得很厉害", "快趴下了", "正在打转"]
三个区 = dict(感觉.三个感觉区())


def 这个情况在哪个区(名):
    for 区名, 区 in 感觉.三个感觉区():
        if 名 in 区.情况:
            return 区名
    raise SystemExit("没有哪个感觉区里有叫「%s」的情况" % 名)


# 每个危险情况 → (它在哪个区, 那块细胞的区内下标)
块表 = {名: (这个情况在哪个区(名),
            np.array(三个区[这个情况在哪个区(名)].情况[名], dtype=np.int64))
        for 名 in 危险情况}

最少样本 = 40
触发比例 = 2.0 / 3.0        # 整块亮到这个比例，力度 1.5 的本能才会真的压过阈值 1.0
地板门槛 = 0.65             # 「至少N档」：25% 分位都要 ≥ 这个数，才算"一直很用力"
天花板门槛 = 0.40           # 「不超过N档」：75% 分位都要 ≤ 这个数，才算"一直很松"
力度 = 1.5


def 触发(各区激活):
    """这次的身体状态，点亮了哪些「危险情况」。各区激活 = {区名: 0/1 数组}"""
    出 = []
    for 名, (区名, 块) in 块表.items():
        if 块.size and np.count_nonzero(各区激活[区名][块]) / 块.size >= 触发比例:
            出.append(名)
    return 出


def 收数据(动作, 最多=200):
    """开环回放这个动作；偏了的时候问老师一句。"""
    名 = 动作["名字"]
    拍 = np.array(动作["拍"], dtype=float)
    指令 = 动作["指令"]
    身 = 身体.身体()
    if 动作.get("起手趴"):
        身.摆成趴姿(); 身.走(0.6, None)
    else:
        身.摆成站姿(); 身.走(0.5, None)
    样本 = defaultdict(list)
    上次 = np.zeros(12)
    n = len(拍)
    for t in range(最多):
        计划 = 拍[t % n]
        激活 = {区名: 区.状态转激活(区.读身体(身))
                for 区名, 区 in 感觉.三个感觉区()}
        命中的 = 触发(激活)
        if 命中的:
            R = 身.数据.xmat[1].reshape(3, 3)
            观察 = np.concatenate([身.数据.qvel[3:6], R.T @ np.array([0.0, 0.0, -1.0]),
                                  np.asarray(指令, dtype=float),
                                  身.数据.qpos[7:] - 默认角, 身.数据.qvel[6:], 上次])
            上次 = 策略(观察)
            老师 = 身体.角度转发力(np.degrees(默认角 + 0.5 * 上次))
            for 名况 in 命中的:
                样本[名况].append((计划.copy(), 老师.copy()))
        身.步进(计划)
        if 身.机身歪了() > 80:
            break
    return 样本


def 主(写表=True):
    import time
    候选 = [k for k, v in 库.items() if v["来源"] != "手编" and k in 训练]
    # 挑一批有代表性的指令，别把 207 个全跑一遍
    取样 = 候选[::max(1, len(候选) // 60)][:60]
    汇总 = defaultdict(list)
    print("拿 %d 个走路动作，一路跑到偏，看老师会怎么下令 ..." % len(取样))
    t0 = time.time()
    for i, 名 in enumerate(取样, 1):
        条 = dict(库[名]); 条["名字"] = 名; 条["指令"] = 训练[名]["指令"]
        条["起手趴"] = 名 in ("站起来",)
        for k, v in 收数据(条).items():
            汇总[k].extend(v)
        if i % 8 == 0:
            print("   %d/%d ... 用了 %.0f 秒" % (i, len(取样), time.time() - t0))
    print("\n各情况收到多少条样本：")
    for 名 in 危险情况:
        print("   %-14s %5d 条" % (名, len(汇总.get(名, []))))

    print("\n老师在这些情况里对每块肌肉的令（挑出「一直很用力/一直很松」的写成反射）：")
    print("   %-14s" % "情况", " ".join("%15s" % n[:4] for n in 身体.肌肉名))
    规则行 = []
    for 名 in 危险情况:
        样本 = 汇总.get(名, [])
        if len(样本) < 最少样本:
            print("   %-14s  （样本只有 %d 条，不写）" % (名, len(样本)))
            continue
        老师 = np.array([s[1] for s in 样本])
        下四分 = np.percentile(老师, 25, axis=0)
        上四分 = np.percentile(老师, 75, axis=0)
        说明 = []
        for m in range(身体.肌肉数):
            区名 = 块表[名][0]
            if 下四分[m] >= 地板门槛:
                档 = int(min(10, max(2, round(下四分[m] * 10))))
                规则行.append((名, 区名, "运动:%s至少%d档" % (身体.肌肉名[m], 档), 力度))
                说明.append("%s≥%d档" % (身体.肌肉名[m], 档))
            elif 上四分[m] <= 天花板门槛:
                档 = int(min(9, max(1, round(上四分[m] * 10))))
                规则行.append((名, 区名, "运动:%s不超过%d档" % (身体.肌肉名[m], 档), -力度))
                说明.append("%s≤%d档" % (身体.肌肉名[m], 档))
        print("   %-14s  %s" % (名, "、".join(说明) or "（没有一直偏的，不写）"))
    print("\n一共得到 %d 条反射。" % len(规则行))
    if not 写表:
        return 规则行
    头 = ["# 反射表 —— 这一份是 算反射.py 算出来的，别手改（重跑会覆盖）",
         "#",
         "# 每一行的意思：在左边这种情况里，把右边那块肌肉的力钉在一个范围里。",
         "#   「至少N档」配正力度 = 源直接连到那几个档位细胞，把它们点亮；",
         "#   「不超过N档」配负力度 = 源先点亮一个**抑制神经元**，由它把那几个档位细胞压住。",
         "#                            （皮层里没有负权重，压人一律靠抑制神经元）",
         "# 力度 ±1.5：整块情况细胞亮到 2/3 就把阈值 1.0 顶过去 / 压下去。",
         "#",
         "# 来源：让训练好的模型在「我们身体偏了」的状态下重新下了一遍令，",
         "#       再挑出它**一直**很用力（≥70% 的样本都 ≥0.7）或**一直**很松",
         "#       （≤0.3）的那些，写成规则。忽高忽低的（跟步子节奏有关的）不写。",
         ""]
    文本 = "\n".join(头)
    for 名 in 危险情况:
        本组 = [r for r in 规则行 if r[0] == 名]
        if not 本组:
            continue
        文本 += "\n# ---- %s（%d 条）----\n" % (名, len(本组))
        for _, 区名, 目标, w in 本组:
            文本 += "%s:%-12s ->  %-28s  %+.1f   是\n" % (区名, 名, 目标, w)
    (根 / "反射表.txt").write_text(文本, encoding="utf-8", newline="\n")
    print("写好了：反射表.txt")
    return 规则行


if __name__ == "__main__":
    主(写表=not (len(sys.argv) > 1 and sys.argv[1] == "看"))