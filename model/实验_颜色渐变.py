图高, 图宽 = 主循环.图高, 主循环.图宽
帧秒 = 主循环.帧秒
看点 = ["前进1.2", "左转1.5", "右转0.75", "站起来", "原地踏步", "站姿"]


def 彩色块(h, s=1.0, v=1.0):
    """正前方那一片涂成 HSV(h,s,v) 的颜色"""
    r, g, b = colorsys.hsv_to_rgb((h % 360) / 360.0, s, v)
    图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
    图[:, 图宽 // 3: 2 * 图宽 // 3, 0] = int(round(r * 255))
    图[:, 图宽 // 3: 2 * 图宽 // 3, 1] = int(round(g * 255))
    图[:, 图宽 // 3: 2 * 图宽 // 3, 2] = int(round(b * 255))
    return 图


def 拿时刻(脑):
    运记起 = 脑.网.区起点["运动记忆"]
    return {a: 运记起 + np.asarray(运动记忆.时刻们(a), dtype=np.int64) for a in 看点}


def 跑几拍(脑, 身, 图, 拍数, 时刻, 统计):
    """走 拍数 拍，把"这一拍点了什么"记进 统计"""
    for k in range(拍数):
        脑.一拍(图=图, 身=身)
        身.步进(脑.肌肉发力())
        for a in 看点:
            if 脑.上一拍[时刻[a]].any():
                统计[a] += 1
        统计["拍"] += 1
        统计["视亮"].append(int(脑.上一拍[脑.段["视觉"]].sum()))
        统计["前亮"].append(int(脑.上一拍[脑.段["前额叶"]].sum()))
    return 统计


def 空统计():
    d = {a: 0 for a in 看点}
    d.update(拍=0, 视亮=[], 前亮=[])
    return d


