# -*- coding: utf-8 -*-
"""机身状态区_bodystate.py —— 身体其实感觉不到的三个量（先单独放这儿）。

★ 为什么单独放一个区

  2026-09-15 拆本体感觉的时候发现的：原来那一片里混着三样东西，
  其中「机身高度 / 前后速度 / 左右速度」**根本不是身体能感觉到的**——
  人身上没有哪个传感器直接报告"我现在离地多高""我每秒平移多少米"。
  这些是**算出来的**（靠关节角 + 重力方向做正运动学就能推出来，机器人也一样）。

  但它们确实有用（"趴着还是站着""在往前走还是在后退"写本能要用），
  所以没有删，单独放一个区，写清楚它不是感觉。
  以后前额叶真会做"再压缩"的时候，这三个量应该由别的区算出来喂给它，
  而不是天生就摆在这儿 —— 留还是删，等你定。

★ 三个特征

  机身高度    0.28 米 = 站姿 = 0；越低越负（趴着约 -1）
  前后速度 / 左右速度   机身平移速度，乘 2 倍再截到 -1~1

自检：python 机身状态区_bodystate.py
"""
from __future__ import annotations

import numpy as np

from 感觉区_共同 import 每档, 每特征细胞, 调谐感觉区

特征名 = ["机身高度", "前后速度", "左右速度"]

本区 = 调谐感觉区("机身状态", 特征名)
特征数 = 本区.特征数
输出层数量 = 本区.输出层数量
总数 = 本区.总数
情况 = 本区.情况
块 = 本区.块
状态转激活 = 本区.状态转激活
解码特征 = 本区.解码特征
皮层 = 本区.皮层


本区.加情况("趴在地上", 块("机身高度", -1, 每档, 每档))
本区.加情况("趴下去了", 块("机身高度", -1, 6, 6))
本区.加情况("身体压低", 块("机身高度", -1, 3, 3))
本区.加情况("站得高",   块("机身高度", +1, 3, 3))
本区.加情况("快趴下了", 块("机身高度", -1, 8, 8))
本区.加情况("在往前走", 块("前后速度", +1, 6, 6))
本区.加情况("在往后走", 块("前后速度", -1, 6, 6))
本区.加情况("在往左走", 块("左右速度", +1, 4, 4))
本区.加情况("在往右走", 块("左右速度", -1, 4, 4))


def 读身体(身):
    """从真身体上读出这 3 个特征（每个 -1~1）。"""
    p = 身.数据.qpos
    v = 身.数据.qvel
    return np.array([
        np.clip((p[2] - 0.28) / 0.16, -1, 1),   # 机身高度（0.28 米 = 站姿 = 0）
        np.clip(v[0] / 2.0, -1, 1),             # 前后速度
        np.clip(v[1] / 2.0, -1, 1),             # 左右速度
    ])


if __name__ == "__main__":
    本区.自检()
    print("\n  提醒：这三个量身体感觉不到，是算出来的 —— 见本文件开头。")
