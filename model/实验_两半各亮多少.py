# -*- coding: utf-8 -*-
"""实验_两半各亮多少.py —— 把「看到红→往前走」这条本能的两半拆开，逐拍量。

★ 为什么要这个（2026-09-15 晚）
  R2 那张表只报了「走路点了几拍」和「前额叶平均亮几个细胞」。可是那条本能是**两半相加**：
      视觉:中有红 给 0.80  ＋  前额叶:看着红 给 0.85  ＞ 阈值 1.0
  于是立刻要问：这两半各自**分不分得清颜色**？如果前额叶那一半在黑屏下也亮着，
  那它就是个常数偏置，真正分辨颜色的只有视觉那一半 —— 这个必须实测、必须写进论文，
  不能靠猜。

★ 每一拍记四样：
    · 视觉:中有红 亮了几个（占这一块的比例）
    · 前额叶:看着红 亮了几个（比例）
    · 「前进1.2」那个头细胞这一拍收到的电流，**按来源区拆开**（视觉区给多少、前额叶给多少、
      抑制扣了多少、总共多少）
    · 走路动作点没点着

命令：python 实验_两半各亮多少.py [种子,种子,...]
"""
from __future__ import annotations

import sys

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 身体_go2 as 身体
import 运动记忆区_motor_memory as 运动记忆

帧秒 = 主循环.帧秒
图高, 图宽 = 主循环.图高, 主循环.图宽
种子们默认 = [20260914, 20260915, 20260916, 20260917, 20260918]


def 图带(通道):
    图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
    图[:, 图宽 // 3: 2 * 图宽 // 3, 通道] = 255
    return 图


幕们 = [("红", 图带(0)), ("黑", np.zeros((图高, 图宽, 3), dtype=np.uint8)),
        ("蓝", 图带(2)), ("绿", 图带(1))]


缓存 = {}


def 取脑(种子):
    if 种子 not in 缓存:
        本能.建网种子 = 种子
        缓存[种子] = 主循环.脑(学=False, 说=False)
    return 缓存[种子]


def 跑一个(种子, 名, 图):
    脑 = 取脑(种子)
    网 = 脑.网
    名字 = 本能.读名字()
    运记起 = 网.区起点["运动记忆"]
    目标 = 运记起 + int(名字["运动记忆"]["前进1.2"][0])
    掩 = 网._兴奋目 == 目标
    源 = 网._兴奋源[掩]
    权 = 网._兴奋权[掩].astype(np.float64)
    区名 = np.empty(网.总数, dtype=object)
    for 名区, 起 in 网.区起点.items():
        区名[起:起 + 网.区宽[名区]] = 名区
    块 = {}
    for 区, 表 in 名字.items():
        for 名2, idx in 表.items():
            块["%s:%s" % (区, 名2)] = 网.区起点[区] + np.asarray(idx, dtype=np.int64)
    视块 = 块["视觉:中有红"]
    前块 = 块["前额叶:看着红"]
    走 = 运记起 + np.asarray(运动记忆.时刻们("前进1.2"), dtype=np.int64)

    身 = 身体.身体()
    身.摆成站姿()
    身.走(0.5, None)
    脑.亮[:] = False
    脑.上一拍[:] = False
    视比 = []
    前比 = []
    给视 = []
    给前 = []
    给抑 = []
    给总 = []
    点火 = 0
    for _ in range(200):
        脑.一拍(图=图, 身=身)
        身.步进(脑.肌肉发力())
        亮拍 = 脑.上一拍
        视比.append(float(亮拍[视块].mean()))
        前比.append(float(亮拍[前块].mean()))
        贡献 = 权 * 亮拍[源]
        出 = {}
        for i in np.nonzero(贡献 > 0)[0]:
            k = 区名[源[i]]
            出[k] = 出.get(k, 0.0) + float(贡献[i])
        抑 = float(网._抑制电流(亮拍)[目标])
        给视.append(出.get("视觉", 0.0))
        给前.append(出.get("前额叶", 0.0))
        给抑.append(抑)
        给总.append(sum(出.values()) - 抑)
        if bool(亮拍[走].any()):
            点火 += 1
    return dict(视块数=len(视块), 前块数=len(前块),
                视比=float(np.mean(视比)), 前比=float(np.mean(前比)),
                给视=float(np.mean(给视)), 给前=float(np.mean(给前)),
                给抑=float(np.mean(给抑)), 给总=float(np.mean(给总)),
                点火=点火)


def main():
    种子们 = 种子们默认
    if len(sys.argv) > 1 and sys.argv[1].strip():
        种子们 = [int(a) for a in sys.argv[1].split(",")]
    print("=" * 104)
    print("「看到红→往前走」两半拆开：每一拍量两块名字亮了多少、那个头细胞收到多少电流")
    print("=" * 104, flush=True)
    出 = []
    for 种子 in 种子们:
        for 名, 图 in 幕们:
            r = 跑一个(种子, 名, 图)
            r["种子"], r["幕"] = 种子, 名
            出.append(r)
            print("种子 %d  %s：视觉:中有红 亮 %.2f（块 %d 个）| 前额叶:看着红 亮 %.2f（块 %d 个）"
                  "| 给这半 视 %.2f + 前 %.2f − 抑 %.2f = 净 %.2f | 走路 %d/200"
                  % (种子, 名, r["视比"], r["视块数"], r["前比"], r["前块数"],
                     r["给视"], r["给前"], r["给抑"], r["给总"], r["点火"]), flush=True)
    print("\n" + "=" * 104)
    print("【汇总：每个幕取中位数】")
    print("%-6s | %-16s | %-16s | %-10s | %-10s | %-10s | %-10s | %-10s"
          % ("幕", "视觉:中有红 亮", "前额叶:看着红 亮", "视觉给的", "前额叶给的", "抑制扣的", "净电流", "走路点燃"))
    print("-" * 104)
    for 名, _ in 幕们:
        行 = [r for r in 出 if r["幕"] == 名]
        m = lambda k: float(np.median([r[k] for r in 行]))
        print("%-6s | %-16s | %-16s | %-10.2f | %-10.2f | %-10.2f | %-10.2f | %-10s"
              % (名, "%.2f（%d 个）" % (m("视比"), 行[0]["视块数"]),
                 "%.2f（%d 个）" % (m("前比"), 行[0]["前块数"]),
                 m("给视"), m("给前"), m("给抑"), m("给总"),
                 "%.0f/200" % m("点火")))
    return 出


if __name__ == "__main__":
    出 = main()