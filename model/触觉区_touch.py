"""触觉区_touch.py —— "被摸一下"这件事，怎么变成大脑里亮起来的一小片神经元。

用户 2026-09-16：
  "如果追求完全仿生，可以给模型加上触觉区，我们轻轻触摸模型时激活的某些
   触觉区神经元会激活多巴胺区。"

它在这套架构里的位置（和视觉区、听觉区是同一个身份）：
  · 皮肤是**外界**，所以"被碰到"是一路外界信号 —— 它按规矩也是**从外面往里送**
    （和运动区相反：运动区是往里送信号给肌肉，方向朝外）。
  · 但它是简单信号（没有图、没有谱），不需要一层多层网去压缩：
    一个细胞 = 身上一个地方、被摸到的一档力度。它自己就是"压缩完的那一层"。
  · 它只做一件事：被点亮以后，靠一条**天生就有的本能连接**把「多巴胺」点亮
    （见 本能规则()）。多巴胺亮 = 这一拍亮着的那些神经元之间的连接当场连起来
    （见 皮层连接_cortex_links.py 的 _多巴胺强化）。
  · 于是"奖励"不再是人从外面按的一个开关，而是**身体真被碰到了**：
    想让模型得奖励，就得伸手摸它。

★★ 默认是关的（AGI触觉宽度 不设 = 0，这个区不存在）。
   为什么：加一个区，全脑的随机连接就会换成另一套（随机数消耗的位置全变了），
   论文里 R1~R8 那一批数字是在"没有触觉区"的那一版上跑出来的。要看仿生奖励：
       PowerShell:  $env:AGI触觉宽度='210'
   这一条和 规模试验 的 AGI行数/AGI列数 是一回事：旋钮不动，老结果一个不变。
"""
from __future__ import annotations

import os

import numpy as np

# 身上能被摸到的地方（不给"尾巴"之类还没有的部位）。
部位们 = ("头顶", "背", "腹", "左前腿", "右前腿", "左后腿", "右后腿")

# ★ 总宽度：不设 = 0 = 没有这个区（论文那一版就是这个）。
宽度 = int(os.environ.get("AGI触觉宽度", 0))

# 每个部位分到几个细胞。宽度除不尽时前面几个部位多分一个（多一个细胞 = 分辨力多一档）。
_基, _余 = divmod(宽度, len(部位们)) if 宽度 > 0 else (0, 0)
每处细胞 = _基 + (1 if _余 else 0)

部位段: dict[str, np.ndarray] = {}
_游标 = 0
for _i, _名 in enumerate(部位们):
    _n = _基 + (1 if _i < _余 else 0)
    部位段[_名] = np.arange(_游标, _游标 + _n, dtype=np.int64)
    _游标 += _n
全部 = np.arange(宽度, dtype=np.int64)


def 名字块() -> dict[str, list]:
    """给「标定/读名字」用：触觉区里每个部位各占哪几个细胞（编号是本区内的编号）。"""
    if 宽度 <= 0:
        return {}
    块 = {名: [int(i) for i in 段] for 名, 段 in 部位段.items()}
    块["全部"] = [int(i) for i in 全部]
    return 块


def 本能规则() -> list[tuple]:
    """触觉区天生就有的那条本能连接：摸到哪个部位 -> 多巴胺亮。

    为什么是「每个部位各写一条」而不是「整片触觉 -> 多巴胺 一条」：
      本能表的力度是按**源块大小摊平**的（见 本能工具_instincts.py 的 交叉）。
      写成一整片的话，只摸到"背"这一处 = 只亮了源块的 1/7 → 递到多巴胺那儿
      只有 2.0×1/7 = 0.29，过不了阈值 1.0，摸了等于没摸。
      拆成一条一条，摸满任意**一处**就能把多巴胺点着；
      摸得轻（只亮该部位的一部分细胞）则点不着 —— 轻轻蹭一下不算奖励，
      这也是合理的：奖励是"真被碰到了"。
    """
    if 宽度 <= 0:
        return []
    return [(f"触觉:{名}", "多巴胺:全部", 2.0, True, "仿生奖励（天生）") for 名 in 部位们]


def 摸(部位="背", 力度=1.0) -> np.ndarray:
    """伸手摸一下 -> 触觉区这一拍亮哪几个细胞（长度 = 宽度 的 bool 向量）。

    力度 0~1：摸满 = 该部位全部细胞亮；轻轻蹭 = 只亮前面几个。
    """
    if 宽度 <= 0:
        raise SystemExit("没有触觉区（AGI触觉宽度 没设）。要看仿生奖励，先设它。")
    if 部位 not in 部位段:
        raise SystemExit(f"没有「{部位}」这个部位。能摸的：{'、'.join(部位们)}")
    段 = 部位段[部位]
    亮 = np.zeros(宽度, dtype=bool)
    if 力度 <= 0:
        return 亮
    n = int(np.clip(round(float(力度) * 段.size), 1, 段.size))
    亮[段[:n]] = True
    return 亮


if __name__ == "__main__":
    print(f"触觉区宽度 {宽度}（{'没有这个区' if 宽度 <= 0 else '每个部位 %d 个细胞' % 每处细胞}）")
    for 名 in 部位们:
        if 部位段[名].size:
            print(f"  触觉:{名:<5} 细胞 {部位段[名].size} 个（编号 {部位段[名][0]}~{部位段[名][-1]}）")
    print("天生本能连接：")
    for r in 本能规则():
        print("  %s -> %s  力度 %s  %s  （%s）" % r)