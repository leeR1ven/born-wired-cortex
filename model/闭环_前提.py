"""闭环_前提.py —— 验"动作前提"：不给任何指令，看它靠感觉到的情况自己决定做什么。

这一段和 闭环_身体go2.py 的区别：
  那边是**人**点亮"前额叶:中走"（相当于下命令："走"）；
  这边**什么都不点**，只把
     · 本体感觉（自己感觉趴着 / 站着 / 要往前倒）
     · 视觉（眼睛看到什么）
  灌进皮层，剩下的全靠一出生写好的本能连接。
  它站起来，是因为它**感觉到自己趴着**，而"趴着 → 站起来"这条本能是出生就有的。

★ 要看到的事
  1. 把它摆成趴姿，不给任何东西 → 自己站起来（机身 0.10 → 0.25 米左右）
  2. 让它站着，眼前给一大片红 → 自己朝红的地方走过去
     （2026-09-15：这条路现在是**经过前额叶**的。本能表里"看到红→往前走"拆成两半：
      视觉:中有红 给 0.9、前额叶:看着红 给 0.4，两半加起来 1.3 才过阈值 1.0。
      所以这一段也必须跟前额叶一起算，不然只剩 0.9 那一半，点不着。）
  3. 什么都不给 → 肌肉放松，瘫掉
"""
from __future__ import annotations

import numpy as np

import 身体_go2 as 身体
import 运动输出区_motor_output as 运动
import 本能工具_instincts as 本能
import 感觉区_共同 as 感觉
import 视觉前处理_visual_preprocess as 视觉
import 前额叶区_prefrontal as 前额

帧秒 = 1.0 / 50.0
图高, 图宽 = 1080, 1920


def 红图(通道="中"):
    图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
    if 通道 == "中":
        图[:, 图宽 // 3: 2 * 图宽 // 3, 0] = 255
    elif 通道 == "全":
        图[:, :, 0] = 255
    return 图


def 一张段(网, 身, 秒, 视觉激活=None, 用感觉=True, 说=True):
    """跑一段。只灌本体感觉（+可选视觉），不给任何指令。"""
    运起 = 网.区起点["运动"]
    运宽 = 网.区宽["运动"]
    视起 = 网.区起点["视觉"]
    视宽 = 网.区宽["视觉"]
    听起 = 网.区起点["听觉"]
    听宽 = 网.区宽["听觉"]
    前起 = 网.区起点["前额叶"]
    前宽 = 网.区宽["前额叶"]
    亮 = np.zeros(网.总数, dtype=bool)
    起 = 身.数据.qpos[:2].copy()
    最高 = 身.机身高度()
    for k in range(int(秒 / 帧秒)):
        # 只覆盖「感觉」那两段输入；剩下的皮层活动就是**上一拍的输出**——
        # 这样动作链才能一拍接一拍自己在皮层里走下去（这一步以前写错过：
        # 每拍把皮层清空重来，等于把上一拍的结果丢了）
        for 区名, 区 in 感觉.三个感觉区():          # 三个身体感觉区一起灌
            起k = 网.区起点[区名]
            亮[起k:起k + 区.输出层数量] = (
                区.状态转激活(区.读身体(身)) if 用感觉 else False)
        本能.灌视觉(亮, 网, 第4层=视觉激活)      # 视觉区是 [第4层 | 第1层] 两段，走统一入口
        # 前额叶：把视觉/听觉/运动三路再压一次（和 主循环_完整的一拍.py 里一模一样）。
        # "看到红→往前走"这条本能现在有一半压在前额叶身上，所以这一段必须算。
        前 = np.asarray(前额.前额网.前向传播(
            亮[视起:视起 + 本能.视觉前段], 亮[听起:听起 + 听宽], 亮[运起:运起 + 运宽]), dtype=bool)
        亮[前起:前起 + 前宽] = 前
        出 = 网.步进(亮)
        发力 = 运动.解码发力(出[运起:运起 + 运动.运动区宽度])
        身.步进(发力)
        亮 = 出
        最高 = max(最高, 身.机身高度())
        if 说 and k % 25 == 0:
            看到 = "有红" if 视觉激活 is not None else "—"
            print("   %4.1f 秒  机身 %.3f 米  歪 %3.0f 度  前额叶亮 %4d 个  眼睛 %s"
                  % (k * 帧秒, 身.机身高度(), 身.机身歪了(), int(前.sum()), 看到))
    return dict(最高=最高, 末高=身.机身高度(),
                走了=float(np.hypot(身.数据.qpos[0] - 起[0], 身.数据.qpos[1] - 起[1])),
                歪=身.机身歪了())


def main():
    print("=" * 74)
    名字 = 本能.读名字()
    网, 条 = 本能.装(说=False)
    print("网建好：%s；本能 %s 根" % ("、".join("%s%d" % kv for kv in 网.区宽.items()),
                                     format(条, ",")))
    身 = 身体.身体()

    print("\n[1] 摆成趴姿，什么都不给（没有指令，只有它自己的感觉）")
    身.摆成趴姿(); 身.走(0.5, None)
    print("   起手：机身 %.3f 米" % 身.机身高度())
    r = 一张段(网, 身, 3.0)
    print("   -> 最高 %.3f 米，末了 %.3f 米  %s"
          % (r["最高"], r["末高"], "自己站起来了 ✓" if r["末高"] > 0.20 else "没站起来 ✗"))

    print("\n[2] 摆成站姿，眼前放一大片红")
    身.摆成站姿(); 身.走(0.5, None)
    红 = 视觉.网.前向传播(视觉.图像转信号(红图("中")))
    红激活 = np.asarray(红, dtype=bool)
    print("   眼睛：正前方一片红（视觉皮层亮 %d 个）" % int(红激活.sum()))
    起 = 身.数据.qpos[:2].copy()
    r = 一张段(网, 身, 4.0, 视觉激活=红激活)
    前 = 身.数据.qpos[0] - 起[0]
    print("   -> 朝前走了 %.2f 米  %s" % (前, "自己朝红的地方走过去 ✓" if 前 > 0.3 else "没动 ✗"))

    print("\n[3] 什么都不给（连感觉都不给）")
    身.摆成站姿()
    r = 一张段(网, 身, 1.5, 用感觉=False, 说=False)
    print("   -> 机身 %.3f 米，歪 %.0f 度  %s"
          % (r["末高"], r["歪"], "瘫掉了（说明动作确实是皮层下的令）✓" if r["末高"] < 0.20 else "✗"))


if __name__ == "__main__":
    main()