# -*- coding: utf-8 -*-
"""诊断_触觉版_天生站起来.py —— 摆成趴姿、黑屏、什么都不给：它自己站得起来吗？

为什么要这一条：仿生奖励那一版（开了 210 个细胞的触觉区）里，学过之后考试时
走路链点着了（200/200），但身子一直没起来（最高 0.058~0.155 米），而论文 R9 那一版
同样的种子里是 0.388/0.391 米。要分清是谁干的：
  · "站起来"是**天生**的（R1），考试时压根没有触摸，奖励那条路是静的
    —— 所以它不可能是触摸通路造成的；
  · 那到底是这一版的脑子天生就站不利索，还是"走路学好了、把站起来压住了"？
把"没学过的同一个脑子"摆成趴姿、什么都不给跑一遍，就有答案：
  站得起来 = 天生的没问题，是学过之后走路把它压住了；
  站不起来 = 这一版的脑子天生就站不利索，跟奖励没关系。

用法：
    python 诊断_触觉版_天生站起来.py 20260914 20260915 20260916
    （要看哪一版，就在外面设 AGI触觉宽度；不设 = 论文那一版）
"""
from __future__ import annotations

import os
import sys

import numpy as np

import 本能工具_instincts as 本能
import 主循环_完整的一拍 as 主循环
import 运动记忆区_motor_memory as 运动记忆
import 身体_go2 as 身体

图高, 图宽 = 主循环.图高, 主循环.图宽
黑图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
拍数 = 150


def 跑(种子):
    本能.建网种子 = 种子
    脑 = 主循环.脑(学=False, 说=False)
    身 = 身体.身体()
    身.摆成趴姿(); 身.走(0.3, None)
    起高 = 身.机身高度()
    最高 = 起高
    站拍 = 0
    运记起 = 脑.网.区起点["运动记忆"]
    站起来 = 运记起 + np.asarray(运动记忆.时刻们("站起来"), dtype=np.int64)
    站姿 = 运记起 + np.asarray(运动记忆.时刻们("站姿"), dtype=np.int64)
    for k in range(拍数):
        脑.一拍(图=黑图, 声=None, 身=身)
        身.步进(脑.肌肉发力())
        h = 身.机身高度()
        最高 = max(最高, h)
        if 脑.上一拍[站起来].any() or 脑.上一拍[站姿].any():
            站拍 += 1
    print("  种子 %d：起手 %.3f 米 -> 最高 %.3f 米、末了 %.3f 米；"
          "『站起来/站姿』这串时刻亮了 %d/%d 拍  %s"
          % (种子, 起高, 最高, 身.机身高度(), 站拍, 拍数,
             "自己站起来了 ✓" if 最高 > 0.25 else "没站起来 ✗"), flush=True)
    return 最高, 身.机身高度(), 站拍


if __name__ == "__main__":
    种子们 = [int(a) for a in sys.argv[1:] if a.strip().isdigit()] or [20260914, 20260915, 20260916]
    触觉宽 = os.environ.get("AGI触觉宽度", "0")
    print("=" * 90)
    print("天生就站得起来吗？（摆成趴姿 + 黑屏 + 什么都不给，%d 拍；学=关）" % 拍数)
    print("  这一版的触觉区宽度 = %s%s" % (触觉宽, "（没有触觉区 = 论文那一版）" if 触觉宽 in ("0", "") else ""))
    print("=" * 90)
    出 = [跑(s) for s in 种子们]
    print()
    print("  站起来的 %d/%d 个脑子；最高机身高 %s 米"
          % (sum(1 for a, _, _ in 出 if a > 0.25), len(出),
             "、".join("%.3f" % a for a, _, _ in 出)))