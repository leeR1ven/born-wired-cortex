# -*- coding: utf-8 -*-
"""实验_发育_仿生奖励_声音叫走路.py —— 奖励不再由代码点亮，而是**伸手摸它**。

★ 和 实验_发育_声音叫走路_多种子.py 是同一件事，只换掉奖励那一路：
    原来：教学时 脑.多巴胺亮 = True         （人在代码里按了一下奖励开关）
    现在：教学时 摸 = 触觉.摸("背", 1.0)     （手真碰到身上）
          触觉区亮 -> 天生本能 触觉:背 -> 多巴胺:全部 -> 多巴胺亮 -> 当场强化连接
  这个脚本里**没有**"发奖励"这个开关：想给奖励，就得伸手摸它。

★ 摸的时机照用户说的做（"模型没有走路，我们就不摸他；如果走路了，我们摸他"）：
  只在**上一拍走路链亮着**的时候摸。

★ 两个条件：
    摸    —— 教学段：站着 + 红 + 声音，它一走就摸
    不摸  —— 教学段一模一样，但一次都不摸（对照：没有奖励就学不会）

★ 注意：开了触觉区，全脑的随机连接会换成另一套（随机数消耗的位置全变了），
  所以这里每个种子的脑子和论文 R9 那一版**不是同一个脑子**；
  数字不能跟 R9 的数直接比，只能跟同一次跑里的"不摸"比。

命令：python 实验_发育_仿生奖励_声音叫走路.py [种子,种子,...]
"""
from __future__ import annotations

import os
import sys

import numpy as np

if not os.environ.get("AGI触觉宽度"):
    os.environ["AGI触觉宽度"] = "210"      # 没设就默认开一个 210 个细胞的触觉区

import 本能工具_instincts as 本能
import 触觉区_touch as 触觉
import 主循环_完整的一拍 as 主循环
import 运动记忆区_motor_memory as 运动记忆
import 身体_go2 as 身体

图高, 图宽 = 主循环.图高, 主循环.图宽
黑图 = np.zeros((图高, 图宽, 3), dtype=np.uint8)
红图 = 主循环.红图("中")
动作名 = "前进1.2"
摸哪 = "背"

出生拍数 = 30
天生拍数 = 30
教学拍数 = 200
考试拍数 = 200


def 跑一个种子(种子, 条件):
    本能.建网种子 = 种子
    脑 = 主循环.脑(学=True, 说=False)
    身 = 身体.身体()
    网 = 脑.网
    运记起 = 网.区起点["运动记忆"]
    走 = 运记起 + 运动记忆.时刻们(动作名)
    声 = np.asarray(本能.听觉例子["低频响"](), dtype=np.float64)

    def 走链():
        return int(脑.亮[走].sum())

    def 走一段(拍数, 图, 声, 摸吗=False):
        上一点 = 身.数据.qpos[:2].copy()
        路程 = 0.0
        走路拍 = 0
        摸了几拍 = 0
        翻在 = None
        for k in range(1, 拍数 + 1):
            手 = None
            if 摸吗 and 走链() > 0:                 # 它这一拍在走 -> 伸手摸它
                手 = 触觉.摸(摸哪, 1.0)
                摸了几拍 += 1
            脑.一拍(图=图, 声=声, 身=身, 摸=手)
            身.步进(脑.肌肉发力())
            if 走链():
                走路拍 += 1
            p = 身.数据.qpos[:2]
            路程 += float(np.hypot(p[0] - 上一点[0], p[1] - 上一点[1]))
            上一点 = p.copy()
            if 翻在 is None and 身.机身歪了() > 75:
                翻在 = k
        return 路程, 走路拍, 翻在, 摸了几拍

    身.摆成趴姿(); 身.走(0.3, None)
    脑.亮[:] = False; 脑.上一拍[:] = False
    出生路程, 出生走, _, _ = 走一段(出生拍数, 黑图, 声)

    身.摆成站姿(); 身.走(0.5, None)
    脑.亮[:] = False; 脑.上一拍[:] = False
    天生路程, 天生走, _, _ = 走一段(天生拍数, 红图, None)

    身.摆成站姿(); 身.走(0.5, None)
    脑.亮[:] = False; 脑.上一拍[:] = False
    出生条 = int(网.摘要()["当前兴奋连接"])
    # ★ 教学段之前先把多巴胺那个老开关**关掉**，证明奖励只可能从手上来。
    脑.多巴胺亮 = False
    教学路程, 教学走, _, 摸了几拍 = 走一段(教学拍数, 红图, 声, 摸吗=(条件 == "摸"))
    长出 = int(网.摘要()["当前兴奋连接"]) - 出生条

    脑.多巴胺亮 = False
    脑.亮[:] = False; 脑.上一拍[:] = False
    身.摆成趴姿(); 身.走(0.3, None)
    考试路程, 考试走, 考试翻, _ = 走一段(考试拍数, 黑图, 声)

    print("### 种子 %d ［%s］" % (种子, 条件), flush=True)
    print("  出生：只放声音     挪 %.3f 米  走路拍了 %d/%d" % (出生路程, 出生走, 出生拍数), flush=True)
    print("  天生：看红         挪 %.3f 米  走路拍了 %d/%d" % (天生路程, 天生走, 天生拍数), flush=True)
    print("  教学：红+声音      挪 %.3f 米  摸过 %d 拍  长出 %d 根新连接"
          % (教学路程, 摸了几拍, 长出), flush=True)
    print("  考试：只放声音     挪 %.3f 米  最高站到 %.3f 米  走路拍了 %d/%d  %s"
          % (考试路程, 身.机身高度(), 考试走, 考试拍数,
             ("第 %d 拍翻倒" % 考试翻) if 考试翻 else "没翻"), flush=True)
    print("", flush=True)
    return dict(种子=种子, 条件=条件, 出生走=出生走, 天生走=天生走, 长出=长出,
                摸了几拍=摸了几拍, 考试走=考试走, 考试路程=考试路程, 考试拍数=考试拍数)


if __name__ == "__main__":
    种子们 = [int(a) for a in sys.argv[1:] if not a.startswith("-")] or [20260914, 20260915, 20260916]
    出 = []
    for 条件 in ("摸", "不摸"):
        for s in 种子们:
            出.append(跑一个种子(s, 条件))
    print("=" * 96)
    print("【总表】考试段：清空皮层 + 趴下 + 黑屏 + 只放声音，它会不会自己站起来往前走")
    print("  %-6s %-30s %-30s %s" % ("条件", "出生时（不该走）", "考试时（学会了没有）", "教学段摸了几拍 / 长出几根"))
    print("-" * 96)
    for 条件 in ("摸", "不摸"):
        组 = [r for r in 出 if r["条件"] == 条件]
        生 = sum(r["出生走"] for r in 组)
        考 = sum(r["考试走"] for r in 组)
        拍 = sum(r["考试拍数"] for r in 组)
        摸 = sum(r["摸了几拍"] for r in 组)
        长 = [r["长出"] for r in 组]
        print("  %-6s %-30s %-30s 摸了 %d 拍 / 长 %s 根"
              % (条件, "%d/%d 拍（%d 个脑子）" % (生, 30 * len(组), len(组)),
                 "%d/%d 拍（%d 个脑子）" % (考, 拍, len(组)), 摸, 长))