# -*- coding: utf-8 -*-
"""实验_眼睛底噪对照.py —— 眼前放各种"没东西"的画面，看眼睛会不会自己乱动。

用户的架构里，本能连接必须只在"真有个东西"时才拉眼球。加了「视觉细节:细_某列」
这一路之后要重新查一遍（它的名字是拿**一个格子那么大**的东西标的，
而"满屏红"在那一格上跟一个红球长得一模一样 —— 所以这一路会不会被满屏颜色带跑，
必须量，不能猜）。

命令：python 实验_眼睛底噪对照.py
"""
from __future__ import annotations

import numpy as np

import 本能工具_instincts as 本能
import 运动输出区_motor_output as 运动
import 世界_world as 世界
import 主循环_完整的一拍 as 主循环
import 视觉前处理_visual_preprocess as 视觉

帧秒 = 1.0 / 50.0


def 空世界(物体=None):
    w = 世界.世界()
    w.摆成站着()
    w.清空物体()
    if 物体:
        w.加物体(*物体)
    return w


def 满屏(色):
    图 = np.zeros((1080, 1920, 3), dtype=np.uint8)
    图[:, :] = 色
    return 图


情形 = [
    ("眼前什么都没有", 空世界(), None),
    ("满屏红", 空世界(), 满屏((255, 0, 0))),
    ("满屏绿", 空世界(), 满屏((0, 255, 0))),
    ("满屏蓝", 空世界(), 满屏((0, 0, 255))),
    ("满屏白", 空世界(), 满屏((255, 255, 255))),
    ("正前方一条红带", 空世界(), None),
    ("一个小球在右边 20 度", 空世界((3 * np.cos(np.radians(20)), 3 * np.sin(np.radians(20)),
                                0.60, 0.05, (230, 30, 30))), None),
    ("一个大球在右边 20 度", 空世界((3 * np.cos(np.radians(20)), 3 * np.sin(np.radians(20)),
                                0.60, 0.30, (230, 30, 30))), None),
]

大脑 = 主循环.脑(学=False, 说=False)
名字 = 本能.读名字()
运起 = 大脑.网.区起点["运动"]
运宽 = 大脑.网.区宽["运动"]
细块 = {n: 大脑.网.区起点["视觉细节"] + np.asarray(名字["视觉细节"][n], dtype=np.int64)
       for n in 本能.细节名字们 if n in 名字["视觉细节"]}
红带 = np.zeros((1080, 1920, 3), dtype=np.uint8)
红带[:, 640:1280, 0] = 255

print("%-22s | %-14s | %s" % ("眼前是什么", "眼肌亮几档(右左上下)", "哪几片「细_某列」亮着"))
print("-" * 92)
for 事, w, 定图 in 情形:
    大脑.亮[:] = False
    大脑.上一拍[:] = False
    力 = None
    for k in range(6):
        图 = 定图 if 定图 is not None else (红带 if 事 == "正前方一条红带" else w.看())
        大脑.一拍(图=图)
        力 = 运动.解码眼球发力(大脑.亮[运起:运起 + 运宽])
        w.眼肌发力 = 力
        w.走眼睛(帧秒)
    档 = np.rint(力 * 运动.每块眼球肌肉神经元).astype(int)
    亮 = [n[3:] for n, b in 细块.items() if 大脑.上一拍[b].mean() >= 0.5]
    print("%-22s | %2d/%2d/%2d/%2d        | %s"
          % (事, 档[0], 档[1], 档[2], 档[3], "、".join(亮) if 亮 else "（都不亮）"))
print()
print("说明：眼肌「几档」= 那 10 个细胞亮了几个。0/0/0/0 = 一动不动（这才是对的）。")
